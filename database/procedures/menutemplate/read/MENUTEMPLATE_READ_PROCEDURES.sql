USE cms_db;

/* ============================================================
   MENUTEMPLATE_READ_PROCEDURES.sql
   Covers Menu Template Lookups, Item Listing, and Sample Generation
   ============================================================ */

DROP PROCEDURE IF EXISTS CMSGETMENUTPL;
DROP PROCEDURE IF EXISTS CMSLISTMENUTPL;
DROP PROCEDURE IF EXISTS CMSLISTMENUTPLDT;
DROP PROCEDURE IF EXISTS CMSDRAFTMENUTPL;

DELIMITER $$

CREATE PROCEDURE CMSGETMENUTPL (IN PMENUTPLID INT)
BEGIN
    SELECT T.MENUTPLID, T.CANTEENID, C.CANTEENNAME,
           T.SERVICEID, S.SERVCODE, S.SERVNAME,
           T.TPLNAME, T.WEEKDAY, T.STATUSID, ST.STATUSCODE AS STATUSCODE,
           T.CREATEDBY, T.CREATEDAT, T.UPDATEDAT
    FROM   CMS_MENUTPL T
    JOIN   CMS_STATUS ST ON ST.STATUSID = T.STATUSID
    JOIN   CMS_CANTEEN C ON C.CANTEENID = T.CANTEENID
    JOIN   CMS_SERVICE S ON S.SERVICEID = T.SERVICEID
    WHERE  T.MENUTPLID = PMENUTPLID;
END$$


CREATE PROCEDURE CMSLISTMENUTPL (IN PCANTEENID INT, IN PSERVICEID INT)
BEGIN
    SELECT T.MENUTPLID, T.CANTEENID, C.CANTEENNAME,
           T.SERVICEID, S.SERVCODE, S.SERVNAME,
           T.TPLNAME, T.WEEKDAY, T.STATUSID, ST.STATUSCODE AS STATUSCODE
    FROM   CMS_MENUTPL T
    JOIN   CMS_STATUS ST ON ST.STATUSID = T.STATUSID
    JOIN   CMS_CANTEEN C ON C.CANTEENID = T.CANTEENID
    JOIN   CMS_SERVICE S ON S.SERVICEID = T.SERVICEID
    WHERE  (PCANTEENID IS NULL OR T.CANTEENID = PCANTEENID)
      AND  (PSERVICEID IS NULL OR T.SERVICEID = PSERVICEID)
      AND  ST.STATUSCODE = 'ACT'
    ORDER BY T.TPLNAME;
END$$


CREATE PROCEDURE CMSLISTMENUTPLDT (IN PMENUTPLID INT)
BEGIN
    SELECT TD.MENUTPLDTID, TD.MENUTPLID, TD.MENUITEMID,
           MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           TD.ISSPECIAL, TD.ISPREBOOK, TD.ISKIOSK,
           TD.MAXQTY, TD.DEFAVAILQTY
    FROM   CMS_MENUTPLDT TD
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = TD.MENUITEMID
    WHERE  TD.MENUTPLID = PMENUTPLID
    ORDER BY MI.ITEMNAME;
END$$


/* ============================================================
   CMSDRAFTMENUTPL — Smart Sample Generator for Menu Templates
   Fetches active items matching the selected Service (or generic items)
   and provides ready-to-use template defaults.
   ============================================================ */
CREATE PROCEDURE CMSDRAFTMENUTPL (
    IN PCANTEENID INT,
    IN PSERVICEID INT,
    IN PCOUNT     INT
)
BEGIN
    DECLARE VCOUNT INT;
    SET VCOUNT = COALESCE(PCOUNT, 6);
    IF VCOUNT <= 0 THEN SET VCOUNT = 6; END IF;
    IF VCOUNT > 30 THEN SET VCOUNT = 30; END IF;

    IF PSERVICEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service ID is required';
    END IF;

    SELECT MI.MENUITEMID,
           MI.MENUCODE,
           MI.ITEMNAME,
           MI.SHORTNAME,
           MI.ITEMDESCR,
           MI.ISSPECIAL,
           MI.SERVICEID,
           S.SERVCODE,
           S.SERVNAME,
           1 AS ISPREBOOK,
           1 AS ISKIOSK,
           1 AS MAXQTY,
           100 AS DEFAVAILQTY
    FROM   CMS_MENUITEM MI
    LEFT JOIN CMS_SERVICE S ON S.SERVICEID = MI.SERVICEID
    WHERE  MI.STATUSID = 10
      AND  (MI.SERVICEID = PSERVICEID OR MI.SERVICEID IS NULL)
    ORDER BY (CASE WHEN MI.SERVICEID = PSERVICEID THEN 0 ELSE 1 END), RAND()
    LIMIT VCOUNT;
END$$

DELIMITER ;
