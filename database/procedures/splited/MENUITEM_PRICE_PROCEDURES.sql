/* ============================================================
   CMS_ITEMPRICE + CMS_ITEMPRICEDT — Pricing Subsystem

   CMSADDITEMPRICE creates a price band header + one detail
   row per customer type in a single JSON array.

   PPRICEJSON shape:
     [{"CTYPECODE":"PERMANENT","PRICE":60.00},
      {"CTYPECODE":"CONTRACT","PRICE":80.00}, ...]
   ============================================================ */

CREATE PROCEDURE CMSADDITEMPRICE (
    IN PMENUITEMID INT,
    IN PEFFFROM    DATE,
    IN PPRICEJSON  JSON,
    IN PCREATEDBY  INT
)
BEGIN
    DECLARE VITEMPRICEID INT;
    DECLARE VCOUNT       INT DEFAULT 0;
    DECLARE VINVALID     INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PMENUITEMID IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu Item ID is required'; END IF;
    IF PEFFFROM IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Effective From date is required'; END IF;
    IF PPRICEJSON IS NULL OR JSON_TYPE(PPRICEJSON) <> 'ARRAY' OR JSON_LENGTH(PPRICEJSON) = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'At least one price entry is required';
    END IF;

    SELECT COUNT(*) INTO VCOUNT FROM CMS_MENUITEM WHERE MENUITEMID = PMENUITEMID AND STATUS = 'A';
    IF VCOUNT = 0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Active menu item not found'; END IF;

    -- Validate all customer type codes exist
    SELECT COUNT(*) INTO VINVALID
    FROM JSON_TABLE(PPRICEJSON, '$[*]' COLUMNS (
        CTYPECODE VARCHAR(20) PATH '$.CTYPECODE',
        PRICE DECIMAL(10,2) PATH '$.PRICE'
    )) JT
    LEFT JOIN CMS_CUSTTYPE CT ON CT.CTYPECODE = JT.CTYPECODE AND CT.ISACTIVE = 1
    WHERE CT.CTYPEID IS NULL OR JT.PRICE IS NULL OR JT.PRICE < 0;

    IF VINVALID > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more price entries have invalid customer type or negative price';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_ITEMPRICE (MENUITEMID, EFFFROM, STATUS, CREATEDBY)
    VALUES (PMENUITEMID, PEFFFROM, 'A', PCREATEDBY);
    SET VITEMPRICEID = LAST_INSERT_ID();

    INSERT INTO CMS_ITEMPRICEDT (ITEMPRICEID, CTYPECODE, PRICE)
    SELECT VITEMPRICEID, JT.CTYPECODE, JT.PRICE
    FROM JSON_TABLE(PPRICEJSON, '$[*]' COLUMNS (
        CTYPECODE VARCHAR(20) PATH '$.CTYPECODE',
        PRICE DECIMAL(10,2) PATH '$.PRICE'
    )) JT;

    COMMIT;
    SELECT VITEMPRICEID AS ITEMPRICEID;
END$$


CREATE PROCEDURE CMSGETITEMPRICE (
    IN PMENUITEMID  INT,
    IN PSERVICEDATE DATE
)
BEGIN
    DECLARE VEFFDATE DATE;

    SET VEFFDATE = COALESCE(PSERVICEDATE, CURRENT_DATE);

    SELECT IP.ITEMPRICEID, IP.MENUITEMID, IP.EFFFROM, IP.STATUS,
           IPD.ITEMPRICEDTID, IPD.CTYPECODE, CT.CTYPENAME, IPD.PRICE
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_ITEMPRICEDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
    JOIN   CMS_CUSTTYPE CT     ON CT.CTYPECODE    = IPD.CTYPECODE
    WHERE  IP.MENUITEMID = PMENUITEMID
      AND  IP.EFFFROM   <= VEFFDATE
      AND  IP.STATUS     = 'A'
      AND  IP.ITEMPRICEID = (
          SELECT IP2.ITEMPRICEID
          FROM   CMS_ITEMPRICE IP2
          WHERE  IP2.MENUITEMID = PMENUITEMID
            AND  IP2.EFFFROM  <= VEFFDATE
            AND  IP2.STATUS    = 'A'
          ORDER BY IP2.EFFFROM DESC
          LIMIT 1
      )
    ORDER BY IPD.CTYPECODE;
END$$


CREATE PROCEDURE CMSGETITEMPRICEDT (
    IN PMENUITEMID  INT,
    IN PCTYPECODE   VARCHAR(20),
    IN PSERVICEDATE DATE
)
BEGIN
    SELECT IPD.PRICE
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_ITEMPRICEDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
    WHERE  IP.MENUITEMID  = PMENUITEMID
      AND  IPD.CTYPECODE  = PCTYPECODE
      AND  IP.EFFFROM    <= COALESCE(PSERVICEDATE, CURRENT_DATE)
      AND  IP.STATUS      = 'A'
    ORDER BY IP.EFFFROM DESC
    LIMIT 1;
END$$


CREATE PROCEDURE CMSLISTITEMPRICE (IN PMENUITEMID INT)
BEGIN
    SELECT IP.ITEMPRICEID, IP.MENUITEMID, MI.MENUCODE, MI.ITEMNAME,
           IP.EFFFROM, IP.STATUS, IP.CREATEDBY, IP.CREATEDAT
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = IP.MENUITEMID
    WHERE  IP.MENUITEMID = PMENUITEMID
    ORDER BY IP.EFFFROM DESC;
END$$


CREATE PROCEDURE CMSDEACTITEMPRICE (IN PITEMPRICEID INT)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE VEFFFROM DATE;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PITEMPRICEID IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Item Price ID is required'; END IF;
    SELECT COUNT(*), EFFFROM INTO VCOUNT, VEFFFROM FROM CMS_ITEMPRICE WHERE ITEMPRICEID = PITEMPRICEID;
    IF VCOUNT = 0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Price band not found'; END IF;
    IF VEFFFROM <= CURRENT_DATE THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot withdraw a price band that is already effective'; END IF;

    START TRANSACTION;
    UPDATE CMS_ITEMPRICE SET STATUS = 'D', UPDATEDAT = CURRENT_TIMESTAMP WHERE ITEMPRICEID = PITEMPRICEID;
    COMMIT;
    SELECT PITEMPRICEID AS ITEMPRICEID;
END$$

