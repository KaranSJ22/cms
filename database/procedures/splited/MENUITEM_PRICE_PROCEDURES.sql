/* ============================================================
   CMS_MENUITEM — Shared Menu Item Catalog (NO price columns)
   ============================================================ */

CREATE PROCEDURE CMSADDMENUITEM (
    IN PMENUCODE  VARCHAR(20),
    IN PSHORTNAME VARCHAR(30),
    IN PITEMNAME  VARCHAR(100),
    IN PITEMDESCR VARCHAR(255),
    IN PISSPECIAL TINYINT,
    IN PCREATEDBY INT
)
BEGIN
    DECLARE VMENUITEMID INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PMENUCODE IS NULL OR TRIM(PMENUCODE) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu Code is required'; END IF;
    IF PSHORTNAME IS NULL OR TRIM(PSHORTNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Short Name is required'; END IF;
    IF PITEMNAME IS NULL OR TRIM(PITEMNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Item Name is required'; END IF;
    IF COALESCE(PISSPECIAL, 0) NOT IN (0, 1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid special item flag'; END IF;

    START TRANSACTION;
    INSERT INTO CMS_MENUITEM (MENUCODE, SHORTNAME, ITEMNAME, ITEMDESCR, ISSPECIAL, STATUS, CREATEDBY)
    VALUES (TRIM(PMENUCODE), TRIM(PSHORTNAME), TRIM(PITEMNAME), PITEMDESCR, COALESCE(PISSPECIAL, 0), 'A', PCREATEDBY);
    SET VMENUITEMID = LAST_INSERT_ID();
    COMMIT;

    SELECT VMENUITEMID AS MENUITEMID;
END$$


CREATE PROCEDURE CMSUPDMENUITEM (
    IN PMENUITEMID INT,
    IN PSHORTNAME  VARCHAR(30),
    IN PITEMNAME   VARCHAR(100),
    IN PITEMDESCR  VARCHAR(255),
    IN PISSPECIAL  TINYINT,
    IN PSTATUS     VARCHAR(20),
    IN PCHANGEDBY  INT,
    IN PCHGREASON  VARCHAR(255)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PMENUITEMID IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu Item ID is required'; END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_MENUITEM WHERE MENUITEMID = PMENUITEMID;
    IF VCOUNT = 0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu item not found'; END IF;
    IF PSHORTNAME IS NULL OR TRIM(PSHORTNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Short Name is required'; END IF;
    IF PITEMNAME IS NULL OR TRIM(PITEMNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Item Name is required'; END IF;
    IF COALESCE(PISSPECIAL, 0) NOT IN (0, 1) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid special item flag'; END IF;
    IF PSTATUS IS NULL OR PSTATUS NOT IN ('A', 'D', 'EXP', 'BLK') THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid menu item status'; END IF;

    START TRANSACTION;

    INSERT INTO CMS_MENUHIST (MENUITEMID, MENUCODE, SHORTNAME, ITEMNAME, ITEMDESCR, ISSPECIAL, STATUS, CHANGEDBY, CHGREASON)
    SELECT MENUITEMID, MENUCODE, SHORTNAME, ITEMNAME, ITEMDESCR, ISSPECIAL, STATUS, PCHANGEDBY, PCHGREASON
    FROM CMS_MENUITEM WHERE MENUITEMID = PMENUITEMID;

    UPDATE CMS_MENUITEM
    SET    SHORTNAME = TRIM(PSHORTNAME),
           ITEMNAME  = TRIM(PITEMNAME),
           ITEMDESCR = PITEMDESCR,
           ISSPECIAL = COALESCE(PISSPECIAL, ISSPECIAL),
           STATUS    = PSTATUS,
           UPDATEDAT = CURRENT_TIMESTAMP
    WHERE  MENUITEMID = PMENUITEMID;
    COMMIT;

    SELECT PMENUITEMID AS MENUITEMID;
END$$


CREATE PROCEDURE CMSGETMENUITEM (IN PMENUITEMID INT)
BEGIN
    SELECT MI.MENUITEMID, MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.ITEMDESCR, MI.ISSPECIAL, MI.STATUS,
           MI.CREATEDBY, MI.CREATEDAT, MI.UPDATEDAT
    FROM   CMS_MENUITEM MI
    WHERE  MI.MENUITEMID = PMENUITEMID;
END$$


CREATE PROCEDURE CMSLISTMENUITEM (
    IN PISSPECIAL TINYINT,
    IN PSTATUS    VARCHAR(20)
)
BEGIN
    SELECT MI.MENUITEMID, MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.ITEMDESCR, MI.ISSPECIAL, MI.STATUS,
           MI.CREATEDBY, MI.CREATEDAT, MI.UPDATEDAT
    FROM   CMS_MENUITEM MI
    WHERE  (PISSPECIAL IS NULL OR MI.ISSPECIAL = PISSPECIAL)
      AND  (PSTATUS    IS NULL OR MI.STATUS    = PSTATUS)
    ORDER BY MI.ITEMNAME;
END$$


CREATE PROCEDURE CMSSEARCHMENUITEM (IN PKEYWORD VARCHAR(100))
BEGIN
    SELECT MI.MENUITEMID, MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.ISSPECIAL, MI.STATUS
    FROM   CMS_MENUITEM MI
    WHERE  (MI.MENUCODE  LIKE CONCAT('%', PKEYWORD, '%')
       OR   MI.SHORTNAME LIKE CONCAT('%', PKEYWORD, '%')
       OR   MI.ITEMNAME  LIKE CONCAT('%', PKEYWORD, '%'))
    ORDER BY MI.ITEMNAME;
END$$


