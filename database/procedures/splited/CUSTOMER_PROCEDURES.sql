DROP PROCEDURE IF EXISTS CMSUPDCUST;
DROP PROCEDURE IF EXISTS CMSGETCUST;
DROP PROCEDURE IF EXISTS CMSLISTCUST;
DROP PROCEDURE IF EXISTS CMSSEARCHCUST;
DROP PROCEDURE IF EXISTS CMSACTCUST;
