/* ============================================================
   CMSVIEWMENU — Published Menu View (Customer-facing)

   Rewritten for new pricing model:
   - Price resolved via CMS_ITEMPRICE + CMS_ITEMPRICEDT
   - CANTEENID filter (required)
   ============================================================ */

CREATE PROCEDURE CMSVIEWMENU (
    IN PCANTEENID INT,
    IN PSERVDATE  DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.CANTEENID,
        C.CANTEENNAME,
        DS.DAYSLOTID,
        S.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DS.SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        MI.ITEMDESCR,
        DM.ISSPECIAL,
        DM.ISPREBOOK,
        DM.ISKIOSK,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKUNTIL,
        DM.CANCELUNTIL,
        (
            SELECT IPD.PRICE
            FROM   CMS_ITEMPRICE IP
            JOIN   CMS_ITEMPRICEDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
            WHERE  IP.MENUITEMID  = MI.MENUITEMID
              AND  IP.EFFFROM    <= DS.SERVDATE
              AND  IP.STATUS      = 'A'
              AND  (IPD.CTYPECODE = PCTYPECODE OR IPD.CTYPECODE = 'VISITOR')
            ORDER BY 
              IP.EFFFROM DESC,
              CASE WHEN IPD.CTYPECODE = PCTYPECODE THEN 1 ELSE 2 END
            LIMIT 1
        ) AS DISPLAYPRICE
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS  ON DS.DAYSLOTID  = DM.DAYSLOTID
    JOIN CMS_SERVICE S   ON S.SERVICEID   = DS.SERVICEID
    JOIN CMS_CANTEEN C   ON C.CANTEENID   = DS.CANTEENID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    WHERE DS.CANTEENID  = PCANTEENID
      AND DS.SERVDATE  = PSERVDATE
      AND DM.APPRSTATUS = 'APP'
      AND DM.STATUS     = 'A'
      AND DS.STATUS     = 'A'
      AND S.STATUS      = 'A'
      AND MI.STATUS     = 'A'
      AND CURRENT_TIMESTAMP <= DM.BOOKUNTIL
    ORDER BY DS.STARTTIME, S.SERVNAME, MI.ITEMNAME;
END$$

