DELIMITER $$
/* ============================================================
   CMS_USER — System User
   ============================================================ */




CREATE PROCEDURE CMSADDUSER (
    IN PLOGINID   VARCHAR(50),
    IN PFULLNAME  VARCHAR(120),
    IN PEMAIL     VARCHAR(120),
    IN PMOBILENO  VARCHAR(20),
    IN PPWDHASH   VARCHAR(255),
    IN PAUTHPROV  VARCHAR(20),
    IN PAUTHID    VARCHAR(120)
)
BEGIN
    DECLARE VUSERID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PLOGINID IS NULL OR TRIM(PLOGINID) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Login ID is required';
    END IF;
    IF PFULLNAME IS NULL OR TRIM(PFULLNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Full Name is required';
    END IF;
    IF PPWDHASH IS NULL OR TRIM(PPWDHASH) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Password hash is required';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_USER (LOGINID, FULLNAME, EMAIL, MOBILENO, PWDHASH, AUTHPROV, AUTHID)
    VALUES (TRIM(PLOGINID), TRIM(PFULLNAME), PEMAIL, PMOBILENO,
            PPWDHASH, COALESCE(PAUTHPROV, 'LOCAL'), PAUTHID);

    SET VUSERID = LAST_INSERT_ID();
    COMMIT;

    SELECT VUSERID AS USERID;
END$$


CREATE PROCEDURE CMSUPDUSER (
    IN PUSERID   INT,
    IN PFULLNAME VARCHAR(120),
    IN PEMAIL    VARCHAR(120),
    IN PMOBILENO VARCHAR(20),
    IN PAUTHPROV VARCHAR(20),
    IN PAUTHID   VARCHAR(120)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PUSERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User ID is required';
    END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_USER WHERE USERID = PUSERID;
    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User not found';
    END IF;
    IF PFULLNAME IS NULL OR TRIM(PFULLNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Full Name is required';
    END IF;

    START TRANSACTION;
    UPDATE CMS_USER
    SET    FULLNAME  = TRIM(PFULLNAME),
           EMAIL     = PEMAIL,
           MOBILENO  = PMOBILENO,
           AUTHPROV  = COALESCE(PAUTHPROV, AUTHPROV),
           AUTHID    = PAUTHID,
           UPDATEDAT = CURRENT_TIMESTAMP
    WHERE  USERID    = PUSERID;
    COMMIT;

    SELECT PUSERID AS USERID;
END$$


CREATE PROCEDURE CMSGETUSER (IN PUSERID INT)
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  U.USERID = PUSERID;
END$$


CREATE PROCEDURE CMSLISTUSER (
    IN PISACTIVE TINYINT
)
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  (PISACTIVE IS NULL OR U.ISACTIVE = PISACTIVE)
    ORDER BY U.FULLNAME;
END$$


CREATE PROCEDURE CMSSEARCHUSER (IN PKEYWORD VARCHAR(120))
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  (U.LOGINID  LIKE CONCAT('%', PKEYWORD, '%')
       OR   U.FULLNAME LIKE CONCAT('%', PKEYWORD, '%')
       OR   U.EMAIL    LIKE CONCAT('%', PKEYWORD, '%'))
    ORDER BY U.FULLNAME;
END$$





CREATE PROCEDURE CMSCHANGEPWD (
    IN PUSERID     INT,
    IN PNEWPWDHASH VARCHAR(255)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PUSERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User ID is required';
    END IF;
    IF PNEWPWDHASH IS NULL OR TRIM(PNEWPWDHASH) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'New password hash is required';
    END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_USER WHERE USERID = PUSERID;
    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User not found';
    END IF;

    START TRANSACTION;
    UPDATE CMS_USER SET PWDHASH = PNEWPWDHASH, UPDATEDAT = CURRENT_TIMESTAMP WHERE USERID = PUSERID;
    COMMIT;
    SELECT PUSERID AS USERID;
END$$


CREATE PROCEDURE CMSACTUSER (IN PUSERID INT)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PUSERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User ID is required';
    END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_USER WHERE USERID = PUSERID;
    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User not found';
