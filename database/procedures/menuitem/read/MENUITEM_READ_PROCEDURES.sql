USE cms_db;

/* ============================================================
   MENUITEM_READ_PROCEDURES.sql
   Covers Dishes, Active Price Bands, Readiness Checks, and Price History
   ============================================================ */

DROP PROCEDURE IF EXISTS CMSGETMENUITEM;
DROP PROCEDURE IF EXISTS CMSLISTMENUITEM;
DROP PROCEDURE IF EXISTS CMSSEARCHMENUITEM;
DROP PROCEDURE IF EXISTS CMSCHECKITEMPRICEREADINESS;
DROP PROCEDURE IF EXISTS CMSGETITEMPRICE;
DROP PROCEDURE IF EXISTS CMSGETITEMPRICEDT;
DROP PROCEDURE IF EXISTS CMSLISTITEMPRICE;
DROP PROCEDURE IF EXISTS CMSGETITEMPRICEHISTORY;

DELIMITER $$

CREATE PROCEDURE CMSGETMENUITEM (IN PMENUITEMID INT)
BEGIN
    SELECT MI.MENUITEMID, MI.SERVICEID, S.SERVCODE, S.SERVNAME,
           MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.DESCR, MI.DESCR AS ITEMDESCR,
           MI.ISSPECIAL,
           MI.ISOFFSER, MI.ISOFFSER AS OFFSER,
           MI.STATUSID, ST.STATUSCODE AS STATUSCODE, ST.STATUSNAME AS STATUSNAME,
           MI.CREATEDBY, MI.CREATEDAT, MI.UPDATEDAT
    FROM   CMS_MENUITEM MI
    LEFT JOIN CMS_SERVICE S ON S.SERVICEID = MI.SERVICEID
    JOIN   CMS_STATUS ST ON ST.STATUSID = MI.STATUSID
    WHERE  MI.MENUITEMID = PMENUITEMID;
END$$


CREATE PROCEDURE CMSLISTMENUITEM (
    IN PISSPECIAL TINYINT,
    IN PSTATUSCODE VARCHAR(10)
)
BEGIN
    SELECT MI.MENUITEMID, MI.SERVICEID, S.SERVCODE, S.SERVNAME,
           MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.DESCR, MI.DESCR AS ITEMDESCR,
           MI.ISSPECIAL,
           MI.ISOFFSER, MI.ISOFFSER AS OFFSER,
           MI.STATUSID, ST.STATUSCODE AS STATUSCODE,
           MI.CREATEDBY, MI.CREATEDAT, MI.UPDATEDAT
    FROM   CMS_MENUITEM MI
    LEFT JOIN CMS_SERVICE S ON S.SERVICEID = MI.SERVICEID
    JOIN   CMS_STATUS ST ON ST.STATUSID = MI.STATUSID
    WHERE  (PISSPECIAL IS NULL OR MI.ISSPECIAL = PISSPECIAL)
      AND  (PSTATUSCODE  IS NULL OR ST.STATUSCODE  = PSTATUSCODE)
    ORDER BY MI.ITEMNAME;
END$$


CREATE PROCEDURE CMSSEARCHMENUITEM (IN PKEYWORD VARCHAR(100))
BEGIN
    SELECT MI.MENUITEMID, MI.SERVICEID, S.SERVCODE, S.SERVNAME,
           MI.MENUCODE, MI.SHORTNAME, MI.ITEMNAME,
           MI.DESCR, MI.DESCR AS ITEMDESCR,
           MI.ISSPECIAL,
           MI.ISOFFSER, MI.ISOFFSER AS OFFSER,
           MI.STATUSID, ST.STATUSCODE AS STATUSCODE
    FROM   CMS_MENUITEM MI
    LEFT JOIN CMS_SERVICE S ON S.SERVICEID = MI.SERVICEID
    JOIN   CMS_STATUS ST ON ST.STATUSID = MI.STATUSID
    WHERE  (MI.MENUCODE  LIKE CONCAT('%', PKEYWORD, '%')
       OR   MI.SHORTNAME LIKE CONCAT('%', PKEYWORD, '%')
       OR   MI.ITEMNAME  LIKE CONCAT('%', PKEYWORD, '%'))
    ORDER BY MI.ITEMNAME;
END$$


CREATE PROCEDURE CMSCHECKITEMPRICEREADINESS (
    IN PMENUITEMID INT,
    IN PSERVICEDATE DATE
)
BEGIN
    DECLARE VMISSINGTYPES VARCHAR(255);
    DECLARE VITEMPRICEID INT;
    DECLARE VMSG VARCHAR(255);

    SELECT IP.ITEMPRICEID INTO VITEMPRICEID
    FROM CMS_ITEMPRICE IP
    JOIN CMS_STATUS ST ON ST.STATUSID = IP.STATUSID
    WHERE IP.MENUITEMID = PMENUITEMID
      AND IP.EFFFROM <= COALESCE(PSERVICEDATE, CURRENT_DATE)
      AND ST.STATUSCODE = 'ACT'
    ORDER BY IP.EFFFROM DESC
    LIMIT 1;

    IF VITEMPRICEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'No effective price band found for this item on the given date';
    END IF;

    SELECT GROUP_CONCAT(CT.CTYPENAME SEPARATOR ', ') INTO VMISSINGTYPES
    FROM CMS_CUSTTYPE CT
    WHERE CT.ISACTIVE = 1
      AND NOT EXISTS (
          SELECT 1
          FROM CMS_ITMPRICDT IPD
          WHERE IPD.ITEMPRICEID = VITEMPRICEID
            AND IPD.CTYPEID = CT.CTYPEID
      );

    IF VMISSINGTYPES IS NOT NULL THEN
        SET VMSG = CONCAT('Price missing for active customer types: ', VMISSINGTYPES);
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = VMSG;
    END IF;
END$$


CREATE PROCEDURE CMSGETITEMPRICE (
    IN PMENUITEMID  INT,
    IN PSERVICEDATE DATE
)
BEGIN
    DECLARE VEFFDATE DATE;

    SET VEFFDATE = COALESCE(PSERVICEDATE, CURRENT_DATE);

    SELECT IP.ITEMPRICEID, IP.MENUITEMID, IP.EFFFROM, IP.STATUSID, ST.STATUSCODE AS STATUSCODE,
           IPD.ITMPRICDTID, IPD.ITMPRICDTID AS ITEMPRICEDTID, IPD.CTYPEID, CT.CTYPECODE, CT.CTYPENAME, IPD.PRICE
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_STATUS ST ON ST.STATUSID = IP.STATUSID
    JOIN   CMS_ITMPRICDT IPD  ON IPD.ITEMPRICEID = IP.ITEMPRICEID
    JOIN   CMS_CUSTTYPE CT     ON CT.CTYPEID      = IPD.CTYPEID
    WHERE  IP.MENUITEMID = PMENUITEMID
      AND  IP.EFFFROM   <= VEFFDATE
      AND  ST.STATUSCODE = 'ACT'
      AND  IP.ITEMPRICEID = (
          SELECT IP2.ITEMPRICEID
          FROM   CMS_ITEMPRICE IP2
          JOIN   CMS_STATUS ST2 ON ST2.STATUSID = IP2.STATUSID
          WHERE  IP2.MENUITEMID = PMENUITEMID
            AND  IP2.EFFFROM  <= VEFFDATE
            AND  ST2.STATUSCODE = 'ACT'
          ORDER BY IP2.EFFFROM DESC
          LIMIT 1
      )
    ORDER BY CT.CTYPECODE;
END$$


CREATE PROCEDURE CMSGETITEMPRICEDT (
    IN PMENUITEMID  INT,
    IN PCTYPECODE   VARCHAR(20),
    IN PSERVICEDATE DATE
)
BEGIN
    SELECT IPD.PRICE
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_STATUS ST ON ST.STATUSID = IP.STATUSID
    JOIN   CMS_ITMPRICDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
    JOIN   CMS_CUSTTYPE CT ON CT.CTYPEID = IPD.CTYPEID
    WHERE  IP.MENUITEMID  = PMENUITEMID
      AND  CT.CTYPECODE   = PCTYPECODE
      AND  IP.EFFFROM    <= COALESCE(PSERVICEDATE, CURRENT_DATE)
      AND  ST.STATUSCODE = 'ACT'
    ORDER BY IP.EFFFROM DESC
    LIMIT 1;
END$$


CREATE PROCEDURE CMSLISTITEMPRICE (IN PMENUITEMID INT)
BEGIN
    SELECT IP.ITEMPRICEID, IP.MENUITEMID, MI.MENUCODE, MI.ITEMNAME,
           IP.EFFFROM, IP.STATUSID, ST.STATUSCODE AS STATUSCODE, IP.CREATEDBY, IP.CREATEDAT
    FROM   CMS_ITEMPRICE IP
    JOIN   CMS_STATUS ST ON ST.STATUSID = IP.STATUSID
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = IP.MENUITEMID
    WHERE  IP.MENUITEMID = PMENUITEMID
    ORDER BY IP.EFFFROM DESC;
END$$


CREATE PROCEDURE CMSGETITEMPRICEHISTORY (
    IN PMENUITEMID INT
)
BEGIN
    SELECT 
       IP.ITEMPRICEID, 
       IP.MENUITEMID, 
       MI.MENUCODE, 
       MI.ITEMNAME,
       IP.EFFFROM, 
       IP.STATUSID, 
       ST.STATUSCODE, 
       IP.CREATEDBY, 
       IP.CREATEDAT,
       IPD.ITMPRICDTID,
       IPD.ITMPRICDTID AS ITEMPRICEDTID,
       IPD.CTYPEID,
       CT.CTYPECODE,
       CT.CTYPENAME,
       IPD.PRICE
     FROM CMS_ITEMPRICE IP
     JOIN CMS_STATUS ST ON ST.STATUSID = IP.STATUSID
     JOIN CMS_MENUITEM MI ON MI.MENUITEMID = IP.MENUITEMID
     LEFT JOIN CMS_ITMPRICDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
     LEFT JOIN CMS_CUSTTYPE CT ON CT.CTYPEID = IPD.CTYPEID
     WHERE IP.MENUITEMID = PMENUITEMID
     ORDER BY IP.EFFFROM DESC, CT.CTYPENAME ASC;
END$$

DELIMITER ;
