    FROM CMS_BOOKITEM BI
    INNER JOIN CMS_MENUITEM MI ON MI.MENUITEMID = BI.MENUITEMID
    INNER JOIN CMS_STATUS BIST ON BIST.STATUSID = BI.STATUSID
    WHERE BI.BOOKID = PBOOKID;
END$$

