        B.CUSTOMERID, C.DISPNAME AS CUSTOMERNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE AS STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT
    FROM CMS_BOOKING B
    INNER JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    INNER JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    INNER JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    INNER JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    WHERE (PCUSTOMERID IS NULL OR B.CUSTOMERID = PCUSTOMERID)
      AND (PSERVICEID IS NULL OR B.SERVICEID = PSERVICEID)
      AND (PSTARTDATE IS NULL OR B.SERVICEDATE >= PSTARTDATE)
      AND (PENDDATE IS NULL OR B.SERVICEDATE <= PENDDATE)
      AND (PSTATUSCODE IS NULL OR ST.STATUSCODE = PSTATUSCODE)
    ORDER BY B.SERVICEDATE DESC, B.BOOKNO DESC;
END$$

CREATE PROCEDURE CMSLISTKITCHENPREP (IN PDAYSLOTID INT)
BEGIN
    SELECT DM.DAYMENUID,
           DM.MENUITEMID,
           MI.ITEMNAME,
           MI.SHORTNAME,
           DM.MAXQTY AS PLANNED_QTY,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT', 'SRV', 'NOS') THEN BI.QTY ELSE 0 END), 0) AS TOTAL_BOOKED,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE = 'SRV' THEN BI.QTY ELSE 0 END), 0) AS TOTAL_SERVED,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT', 'NOS') THEN BI.QTY ELSE 0 END), 0) AS REMAINING_QTY
    FROM   CMS_DAYMENU DM
    JOIN   CMS_STATUS DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    LEFT JOIN CMS_BOOKITEM BI ON BI.DAYMENUID = DM.DAYMENUID
    LEFT JOIN CMS_STATUS B_ST ON B_ST.STATUSID = BI.STATUSID AND B_ST.STATUSCODE IN ('CRT', 'SRV', 'NOS')
    WHERE  DM.DAYSLOTID = PDAYSLOTID
      AND  DM_ST.STATUSCODE = 'ACT'
    GROUP BY DM.DAYMENUID, DM.MENUITEMID, MI.ITEMNAME, MI.SHORTNAME, DM.MAXQTY
    ORDER BY MI.ITEMNAME;
END$$

-- New procedure to list bookings for the current day
CREATE PROCEDURE CMSLISTBOOKTODAY(
    IN PCUSTOMERID INT,
    IN PSERVICEID INT,
    IN PSTATUSCODE VARCHAR(10)
)
BEGIN
    DECLARE TODAY DATE;
    SET TODAY = CURDATE();

    SELECT 
        B.BOOKID, B.BOOKNO, BT.BOOKTYPECODE, 
        B.CUSTOMERID, C.DISPNAME AS CUSTOMERNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE AS STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT
    FROM CMS_BOOKING B
    INNER JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    INNER JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    INNER JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    INNER JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    WHERE (PCUSTOMERID IS NULL OR B.CUSTOMERID = PCUSTOMERID)
      AND (PSERVICEID IS NULL OR B.SERVICEID = PSERVICEID)
      AND B.SERVICEDATE = TODAY
      AND (PSTATUSCODE IS NULL OR ST.STATUSCODE = PSTATUSCODE)
    ORDER BY B.SERVICEDATE DESC, B.BOOKNO DESC;
END$$

