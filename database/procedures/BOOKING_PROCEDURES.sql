    FROM CMS_BOOKITEM
    WHERE BOOKID = PBOOKID;

    -- 33 = 'CAN' (Cancelled)
    UPDATE CMS_BOOKING
    SET STATUSID = 33,
        CANCELLEDBY = PCANCELLEDBY,
        CANCELLEDON = CURRENT_TIMESTAMP,
        REMARKS = COALESCE(PCHGREASON, REMARKS),
        UPDATEDBY = PCANCELLEDBY,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKID = PBOOKID;

    -- Cascade cancellation to line items (33 = CAN)
    UPDATE CMS_BOOKITEM
    SET STATUSID = 33
    WHERE BOOKID = PBOOKID;

    DELETE FROM CMS_PBACTIVE WHERE BOOKID = PBOOKID;

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
        SELECT W.WALLETID, W.BALANCE INTO VWALLETID, VWALLETBALANCE
        FROM CMS_WALLET W
        JOIN CMS_STATUS W_ST ON W_ST.STATUSID = W.STATUSID
        WHERE W.CUSTOMERID = VCUSTOMERID AND W_ST.STATUSCODE = 'ACT'
        FOR UPDATE;

        IF VWALLETID IS NOT NULL THEN
            UPDATE CMS_WALLET
            SET BALANCE = BALANCE + VTOTALAMOUNT
            WHERE WALLETID = VWALLETID;

            CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);

