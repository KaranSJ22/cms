                WALLETID,
                BOOKINGID,
                TRANSTYPE,
                SOURCECODE,
                AMOUNT,
                BALBEFORE,
                BALAFTER,
                PAYMENTMETHOD,
                REFNO,
                STATUSID,
                CREATEDBY,
                REMARKS
            )
            VALUES
            (
                VWALLETID,
                PBOOKID,
                'CREDIT',
                'REFUND',
                VTOTALAMOUNT,
                VWALLETBALANCE,
                VWALLETBALANCE + VTOTALAMOUNT,
                'WALLET',
                VAUTOREFNO,
                40,
                PCANCELLEDBY,
                'Pre-booking cancelled refund'
            );
