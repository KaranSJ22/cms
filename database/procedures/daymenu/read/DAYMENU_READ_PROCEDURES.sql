/* ============================================================
   CMSGETDAYMENUBYID — Fetch specific day menu entry by ID
   ============================================================ */
CREATE PROCEDURE CMSGETDAYMENUBYID (
    IN PDAYMENUID INT
)
BEGIN
    SELECT DM.*, MI.ITEMNAME, MI.DESCR, MI.DESCR AS ITEMDESCR
    FROM CMS_DAYMENU DM 
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID 
    WHERE DM.DAYMENUID = PDAYMENUID;
END$$


/* ============================================================
   CMSGETDAYMENUBATCH — Look up DayMenu and item details for batch IDs
   ============================================================ */
CREATE PROCEDURE CMSGETDAYMENUBATCH (
    IN PDAYMENUIDS JSON
)
BEGIN
    SELECT DM.DAYMENUID, DM.DAYSLOTID, DM.MENUITEMID, DM.BOOKUNTIL, DM.CANCELUNTIL, MI.ITEMNAME, MI.DESCR, MI.DESCR AS ITEMDESCR
    FROM JSON_TABLE(PDAYMENUIDS, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$'
    )) JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID;
END$$


/* ============================================================
   CMSWALKINGETACTIVEMENU — Fetch active meal slot menu items & prices for walk-in counter
   ============================================================ */
CREATE PROCEDURE CMSWALKINGETACTIVEMENU (
    IN PCANTEENID INT,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    IF PCTYPECODE IS NULL OR TRIM(PCTYPECODE) = '' THEN
        SET PCTYPECODE = 'PRM';
    END IF;

    SELECT 
        dm.DAYMENUID,
        dm.DAYSLOTID,
        ds.SERVICEID,
        s.SERVCODE,
        s.SERVNAME,
        ds.STARTTIME,
        ds.ENDTIME,
        mi.MENUITEMID,
        mi.ITEMNAME,
        mi.SHORTNAME,
        dm.ISBASE,
        dm.ISSPECIAL,
        COALESCE((
            SELECT d.PRICE
            FROM CMS_ITEMPRICE p
            JOIN CMS_STATUS ip_st ON ip_st.STATUSID = p.STATUSID AND ip_st.STATUSCODE = 'ACT'
            JOIN CMS_ITMPRICDT d ON d.ITEMPRICEID = p.ITEMPRICEID
            JOIN CMS_CUSTTYPE ct ON ct.CTYPEID = d.CTYPEID
            WHERE p.MENUITEMID = dm.MENUITEMID
              AND ct.CTYPECODE = PCTYPECODE
              AND p.EFFFROM <= CURDATE()
            ORDER BY p.EFFFROM DESC 
            LIMIT 1
        ), 0.00) AS PRICE
    FROM CMS_DAYSLOT ds
    JOIN CMS_DAYMENU dm ON dm.DAYSLOTID = ds.DAYSLOTID
    JOIN CMS_MENUITEM mi ON mi.MENUITEMID = dm.MENUITEMID
    JOIN CMS_SERVICE s ON s.SERVICEID = ds.SERVICEID
    JOIN CMS_STATUS dm_st ON dm_st.STATUSID = dm.STATUSID AND dm_st.STATUSCODE = 'ACT'
    JOIN CMS_STATUS mi_st ON mi_st.STATUSID = mi.STATUSID AND mi_st.STATUSCODE = 'ACT'
    WHERE ds.CANTEENID = PCANTEENID
      AND ds.SERVICEDATE = CURDATE()
      AND ds.STATUSID = 10
      AND ds.APPRSTATUSID = 22 
    ORDER BY dm.ISBASE DESC, mi.ITEMNAME ASC;
END$$


/* ============================================================
   CMSLISTHOLIDAYSRANGE — Fetch holidays in date range
   ============================================================ */
CREATE PROCEDURE CMSLISTHOLIDAYSRANGE (
    IN PSTARTDATE DATE,
    IN PENDDATE   DATE
)
BEGIN
    SELECT HOLIDAYID, HOLIDAYNAME, 
           DATE_FORMAT(HOLIDAYDATE, '%Y-%m-%d') AS HOLIDAYDATE, 
           ISRECURRING
    FROM CMS_HOLIDAY
    WHERE STATUSID = 10
      AND (
        (HOLIDAYDATE >= PSTARTDATE AND HOLIDAYDATE <= PENDDATE)
        OR ISRECURRING = 1
      );
END$$

