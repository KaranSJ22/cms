USE cms_db;

DROP PROCEDURE IF EXISTS CMSGETDMENUWORKSPACE;
DROP PROCEDURE IF EXISTS CMSLISTPENDINGDMENUS;
DROP PROCEDURE IF EXISTS CMSVIEWMENU;
DROP PROCEDURE IF EXISTS CMSVIEWMENURANGE;
DROP PROCEDURE IF EXISTS CMSGETDAYMENUBYID;
DROP PROCEDURE IF EXISTS CMSGETDAYMENUBATCH;

DELIMITER $$

/* ============================================================
   CMSGETDMENUWORKSPACE — Fetch items configured in a slot workspace
   ============================================================ */
CREATE PROCEDURE CMSGETDMENUWORKSPACE (
    IN PDAYSLOTID INT
)
BEGIN
    SELECT DM.DAYMENUID, DM.DMENUNO, DM.DAYSLOTID,
           DM.MENUITEMID, MI.MENUCODE, MI.ITEMNAME, MI.SHORTNAME,
           DM.ISBASE, DM.ISSPECIAL, DM.ISPREBOOK, DM.ISKIOSK,
           DM.AVAILQTY, DM.MAXQTY,
           DM.BOOKUNTIL, DM.CANCELUNTIL,
           DM.STATUSID, ST.STATUSCODE AS STATUSCODE,
           DM.CREATEDBY, DM.CREATEDAT, DM.UPDATEDAT
    FROM   CMS_DAYMENU DM
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN   CMS_STATUS ST ON ST.STATUSID = DM.STATUSID
    WHERE  DM.DAYSLOTID = PDAYSLOTID
    ORDER BY MI.ITEMNAME;
END$$


/* ============================================================
   CMSLISTPENDINGDMENUS — Fetch slots with pending menu approvals
   ============================================================ */
CREATE PROCEDURE CMSLISTPENDINGDMENUS (
    IN PCANTEENID INT
)
BEGIN
    SELECT DS.DAYSLOTID, DS.SLOTNO, DS.SERVICEID, S.SERVNAME,
           DS.CANTEENID, C.CANTEENNAME,
           DS.SERVDATE, DS.STARTTIME, DS.ENDTIME,
           DS.STATUSID, DS.APPRSTATUSID, DS.MENUSUBMITTEDBY, DS.MENUSUBMITTEDAT
    FROM   CMS_DAYSLOT DS
    JOIN   CMS_SERVICE S   ON S.SERVICEID = DS.SERVICEID
    JOIN   CMS_CANTEEN C   ON C.CANTEENID = DS.CANTEENID
    JOIN   CMS_STATUS AST  ON AST.STATUSID = DS.APPRSTATUSID
    WHERE  (PCANTEENID IS NULL OR DS.CANTEENID = PCANTEENID)
      AND  AST.STATUSCODE = 'PEN'
    ORDER BY DS.SERVDATE, DS.STARTTIME;
END$$


/* ============================================================
   CMSVIEWMENU — Published Menu View for a single day (Customer-facing)
   ============================================================ */
CREATE PROCEDURE CMSVIEWMENU (
    IN PCANTEENID INT,
    IN PSERVDATE  DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.CANTEENID,
        C.CANTEENNAME,
        DS.DAYSLOTID,
        S.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DS.SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        MI.ITEMDESCR,
        DM.ISBASE,
        DM.ISSPECIAL,
        DM.ISPREBOOK,
        DM.ISKIOSK,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKUNTIL,
        DM.CANCELUNTIL,
        (
            SELECT IPD.PRICE
            FROM   CMS_ITEMPRICE IP
            JOIN   CMS_ITEMPRICEDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
            JOIN   CMS_STATUS IPST ON IPST.STATUSID = IP.STATUSID
            WHERE  IP.MENUITEMID  = MI.MENUITEMID
              AND  IP.EFFFROM    <= DS.SERVDATE
              AND  IPST.STATUSCODE = 'ACT'
              AND  (IPD.CTYPECODE = PCTYPECODE OR IPD.CTYPECODE = 'VIS')
            ORDER BY 
              IP.EFFFROM DESC,
              CASE WHEN IPD.CTYPECODE = PCTYPECODE THEN 1 ELSE 2 END
            LIMIT 1
        ) AS DISPLAYPRICE
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS  ON DS.DAYSLOTID  = DM.DAYSLOTID
    JOIN CMS_SERVICE S   ON S.SERVICEID   = DS.SERVICEID
    JOIN CMS_CANTEEN C   ON C.CANTEENID   = DS.CANTEENID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN CMS_STATUS DS_ST ON DS_ST.STATUSID = DS.STATUSID
    JOIN CMS_STATUS DS_AST ON DS_AST.STATUSID = DS.APPRSTATUSID
    JOIN CMS_STATUS DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN CMS_STATUS S_ST ON S_ST.STATUSID = S.STATUSID
    JOIN CMS_STATUS MI_ST ON MI_ST.STATUSID = MI.STATUSID
    WHERE DS.CANTEENID  = PCANTEENID
      AND DS.SERVDATE   = PSERVDATE
      AND DS_AST.STATUSCODE = 'APR'
      AND DM_ST.STATUSCODE  = 'ACT'
      AND DS_ST.STATUSCODE  = 'ACT'
      AND S_ST.STATUSCODE   = 'ACT'
      AND MI_ST.STATUSCODE  = 'ACT'
      AND CURRENT_TIMESTAMP <= DM.BOOKUNTIL
    ORDER BY DS.STARTTIME, S.SERVNAME, MI.ITEMNAME;
END$$


/* ============================================================
   CMSVIEWMENURANGE — Published Menu View across a Date Range (Pre-Booking Workspace)
   ============================================================ */
CREATE PROCEDURE CMSVIEWMENURANGE (
    IN PCANTEENID INT,
    IN PSTARTDATE DATE,
    IN PENDDATE   DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.CANTEENID,
        C.CANTEENNAME,
        DS.DAYSLOTID,
        DS.SLOTNO,
        S.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DATE_FORMAT(DS.SERVDATE, '%Y-%m-%d') AS SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        MI.ITEMDESCR,
        DM.ISBASE,
        DM.ISSPECIAL,
        DM.ISPREBOOK,
        DM.ISKIOSK,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKUNTIL,
        DM.CANCELUNTIL,
        (
            SELECT IPD.PRICE
            FROM   CMS_ITEMPRICE IP
            JOIN   CMS_ITEMPRICEDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
            JOIN   CMS_STATUS IPST ON IPST.STATUSID = IP.STATUSID
            WHERE  IP.MENUITEMID  = MI.MENUITEMID
              AND  IP.EFFFROM    <= DS.SERVDATE
              AND  IPST.STATUSCODE = 'ACT'
              AND  (IPD.CTYPECODE = PCTYPECODE OR IPD.CTYPECODE = 'VIS')
            ORDER BY 
              IP.EFFFROM DESC,
              CASE WHEN IPD.CTYPECODE = PCTYPECODE THEN 1 ELSE 2 END
            LIMIT 1
        ) AS DISPLAYPRICE
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS  ON DS.DAYSLOTID  = DM.DAYSLOTID
    JOIN CMS_SERVICE S   ON S.SERVICEID   = DS.SERVICEID
    JOIN CMS_CANTEEN C   ON C.CANTEENID   = DS.CANTEENID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN CMS_STATUS DS_ST ON DS_ST.STATUSID = DS.STATUSID
    JOIN CMS_STATUS DS_AST ON DS_AST.STATUSID = DS.APPRSTATUSID
    JOIN CMS_STATUS DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN CMS_STATUS S_ST ON S_ST.STATUSID = S.STATUSID
    JOIN CMS_STATUS MI_ST ON MI_ST.STATUSID = MI.STATUSID
    WHERE DS.CANTEENID  = PCANTEENID
      AND DS.SERVDATE  >= PSTARTDATE
      AND DS.SERVDATE  <= PENDDATE
      AND DS_AST.STATUSCODE = 'APR'
      AND DM_ST.STATUSCODE  = 'ACT'
      AND DS_ST.STATUSCODE  = 'ACT'
      AND S_ST.STATUSCODE   = 'ACT'
      AND MI_ST.STATUSCODE  = 'ACT'
      AND DM.ISPREBOOK      = 1
    ORDER BY DS.SERVDATE, DS.STARTTIME, S.SERVNAME, DM.ISBASE DESC, MI.ITEMNAME;
END$$


/* ============================================================
   CMSGETDAYMENUBYID — Fetch specific day menu entry by ID
   ============================================================ */
CREATE PROCEDURE CMSGETDAYMENUBYID (
    IN PDAYMENUID INT
)
BEGIN
    SELECT DM.*, MI.ITEMNAME 
    FROM CMS_DAYMENU DM 
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID 
    WHERE DM.DAYMENUID = PDAYMENUID;
END$$


/* ============================================================
   CMSGETDAYMENUBATCH — Look up DayMenu and item details for batch IDs
   ============================================================ */
CREATE PROCEDURE CMSGETDAYMENUBATCH (
    IN PDAYMENUIDS JSON
)
BEGIN
    SELECT DM.DAYMENUID, DM.DAYSLOTID, DM.MENUITEMID, DM.BOOKUNTIL, DM.CANCELUNTIL, MI.ITEMNAME
    FROM JSON_TABLE(PDAYMENUIDS, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$'
    )) JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID;
END$$

