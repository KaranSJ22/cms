/* ============================================================
   CMSGETDMENUWORKSPACE — Fetch items configured in a slot workspace
   ============================================================ */
CREATE PROCEDURE CMSGETDMENUWORKSPACE (
    IN PDAYSLOTID INT
)
BEGIN
    SELECT DM.DAYMENUID, DM.DMENUNO, DM.DAYSLOTID,
           DM.MENUITEMID, MI.MENUCODE, MI.ITEMNAME, MI.SHORTNAME,
           MI.DESCR, MI.DESCR AS ITEMDESCR,
           DM.ISBASE, DM.ISSPECIAL, DM.ISPREBOOK, DM.ISKIOSK,
           DM.AVAILQTY, DM.MAXQTY,
           DM.BOOKUNTIL, DM.CANCELUNTIL,
           DM.STATUSID, ST.STATUSCODE AS STATUSCODE,
           DM.CREATEDBY, DM.CREATEDAT, DM.UPDATEDAT
    FROM   CMS_DAYMENU DM
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN   CMS_STATUS ST ON ST.STATUSID = DM.STATUSID
    WHERE  DM.DAYSLOTID = PDAYSLOTID
    ORDER BY MI.ITEMNAME;
END$$


/* ============================================================
   CMSLISTPENDINGDMENUS — Fetch slots with pending menu approvals
   ============================================================ */
CREATE PROCEDURE CMSLISTPENDINGDMENUS (
    IN PCANTEENID INT
)
BEGIN
    SELECT DS.DAYSLOTID, DS.SLOTNO, DS.SERVICEID, S.SERVNAME,
           DS.CANTEENID, C.CANTEENNAME,
           DS.SERVICEDATE, DS.SERVICEDATE AS SERVDATE, DS.STARTTIME, DS.ENDTIME,
           DS.STATUSID, DS.APPRSTATUSID, DS.MENUSUBMITTEDBY, DS.MENUSUBMITTEDAT,
           COUNT(DM.DAYMENUID) AS ITEMCOUNT,
           COALESCE(GROUP_CONCAT(MI.ITEMNAME ORDER BY DM.ISBASE DESC, MI.ITEMNAME SEPARATOR ', '), '') AS ITEMSNAMES
    FROM   CMS_DAYSLOT DS
    JOIN   CMS_SERVICE S   ON S.SERVICEID = DS.SERVICEID
    JOIN   CMS_CANTEEN C   ON C.CANTEENID = DS.CANTEENID
    JOIN   CMS_STATUS AST  ON AST.STATUSID = DS.APPRSTATUSID
    LEFT JOIN CMS_DAYMENU DM ON DM.DAYSLOTID = DS.DAYSLOTID
    LEFT JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    WHERE  (PCANTEENID IS NULL OR DS.CANTEENID = PCANTEENID)
      AND  AST.STATUSCODE = 'PEN'
    GROUP BY DS.DAYSLOTID, DS.SLOTNO, DS.SERVICEID, S.SERVNAME,
             DS.CANTEENID, C.CANTEENNAME,
             DS.SERVICEDATE, DS.STARTTIME, DS.ENDTIME,
             DS.STATUSID, DS.APPRSTATUSID, DS.MENUSUBMITTEDBY, DS.MENUSUBMITTEDAT
    ORDER BY DS.SERVICEDATE, DS.STARTTIME;
END$$


/* ============================================================
   CMSVIEWMENU — Published Menu View for a single day (Customer-facing)
   ============================================================ */
CREATE PROCEDURE CMSVIEWMENU (
    IN PCANTEENID INT,
    IN PSERVDATE  DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.CANTEENID,
        C.CANTEENNAME,
        DS.DAYSLOTID,
        S.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DATE_FORMAT(DS.SERVICEDATE, '%Y-%m-%d') AS SERVICEDATE,
        DATE_FORMAT(DS.SERVICEDATE, '%Y-%m-%d') AS SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        MI.DESCR,
        MI.DESCR AS ITEMDESCR,
        DM.ISBASE,
        DM.ISSPECIAL,
        DM.ISPREBOOK,
        DM.ISKIOSK,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKUNTIL,
        DM.CANCELUNTIL,
        (
            SELECT IPD.PRICE
            FROM   CMS_ITEMPRICE IP
            JOIN   CMS_ITMPRICDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
            JOIN   CMS_CUSTTYPE CT ON CT.CTYPEID = IPD.CTYPEID
            JOIN   CMS_STATUS IPST ON IPST.STATUSID = IP.STATUSID
            WHERE  IP.MENUITEMID  = MI.MENUITEMID
              AND  IP.EFFFROM    <= DS.SERVICEDATE
              AND  IPST.STATUSCODE = 'ACT'
              AND  (CT.CTYPECODE = PCTYPECODE OR CT.CTYPECODE = 'VIS')
            ORDER BY 
              IP.EFFFROM DESC,
              CASE WHEN CT.CTYPECODE = PCTYPECODE THEN 1 ELSE 2 END
            LIMIT 1
        ) AS DISPLAYPRICE
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS  ON DS.DAYSLOTID  = DM.DAYSLOTID
    JOIN CMS_SERVICE S   ON S.SERVICEID   = DS.SERVICEID
    JOIN CMS_CANTEEN C   ON C.CANTEENID   = DS.CANTEENID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN CMS_STATUS DS_ST ON DS_ST.STATUSID = DS.STATUSID
    JOIN CMS_STATUS DS_AST ON DS_AST.STATUSID = DS.APPRSTATUSID
    JOIN CMS_STATUS DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN CMS_STATUS S_ST ON S_ST.STATUSID = S.STATUSID
    JOIN CMS_STATUS MI_ST ON MI_ST.STATUSID = MI.STATUSID
    WHERE DS.CANTEENID  = PCANTEENID
      AND DS.SERVICEDATE   = PSERVDATE
      AND DS_AST.STATUSCODE = 'APR'
      AND DM_ST.STATUSCODE  = 'ACT'
      AND DS_ST.STATUSCODE  = 'ACT'
      AND S_ST.STATUSCODE   = 'ACT'
      AND MI_ST.STATUSCODE  = 'ACT'
      AND CURRENT_TIMESTAMP <= DM.BOOKUNTIL
    ORDER BY DS.STARTTIME, S.SERVNAME, MI.ITEMNAME;
END$$


