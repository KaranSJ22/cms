-- v2_module1
-- Modified to add mandatory input validation and transaction exception handling.
CREATE PROCEDURE CMSADDUSER (
    IN PLOGINID VARCHAR(50),
    IN PFULLNAME VARCHAR(120),
    IN PEMAIL VARCHAR(120),
    IN PMOBILENO VARCHAR(20),
    IN PPWDHASH VARCHAR(255),
    IN PAUTHPROV VARCHAR(20),
    IN PAUTHID VARCHAR(120)
)
BEGIN
    DECLARE VUSERID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PLOGINID IS NULL OR TRIM(PLOGINID) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Login ID is required';
    END IF;

    IF PFULLNAME IS NULL OR TRIM(PFULLNAME) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Full Name is required';
    END IF;

    IF PPWDHASH IS NULL OR TRIM(PPWDHASH) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Password hash is required';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_USER (LOGINID, FULLNAME, EMAIL, MOBILENO, PWDHASH, AUTHPROV, AUTHID)
    VALUES (TRIM(PLOGINID), TRIM(PFULLNAME), PEMAIL, PMOBILENO, PPWDHASH, COALESCE(PAUTHPROV, 'LOCAL'), PAUTHID);

    SET VUSERID = LAST_INSERT_ID();

    COMMIT;

    SELECT VUSERID AS USERID;
END$$

