-- v2_module1
-- Modified to validate role assignment date range and add transaction exception handling.
CREATE PROCEDURE CMSASSIGNROL (
    IN PUSERID INT,
    IN PROLEID INT,
    IN PASSIGNEDBY INT,
    IN PVALIDFROM DATETIME,
    IN PVALIDUNTIL DATETIME
)
BEGIN
    DECLARE VVALIDFROM DATETIME;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    SET VVALIDFROM = COALESCE(PVALIDFROM, CURRENT_TIMESTAMP);

    IF PVALIDUNTIL IS NOT NULL AND PVALIDUNTIL < VVALIDFROM THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Role valid until date must be greater than or equal to valid from date';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_USRROLE (USERID, ROLEID, ASSIGNEDBY, VALIDFROM, VALIDUNTIL, ISACTIVE)
    VALUES (PUSERID, PROLEID, PASSIGNEDBY, VVALIDFROM, PVALIDUNTIL, 1)
    ON DUPLICATE KEY UPDATE
        ASSIGNEDBY = PASSIGNEDBY,
        VALIDFROM = VVALIDFROM,
        VALIDUNTIL = PVALIDUNTIL,
        ISACTIVE = 1,
        ASSIGNEDAT = CURRENT_TIMESTAMP;

    COMMIT;
END$$

