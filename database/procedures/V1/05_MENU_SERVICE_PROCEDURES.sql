-- Added status validation, history-before-update enforcement, and transaction exception handling.
CREATE PROCEDURE CMSUPDSERV (
    IN PSERVICEID INT,
    IN PSERVNAME VARCHAR(80),
    IN PDEFSTART TIME,
    IN PDEFEND TIME,
    IN PVALIDFROM DATE,
    IN PVALIDUNTIL DATE,
    IN PSTATUS VARCHAR(20),
    IN PCHANGEDBY INT,
    IN PCHGREASON VARCHAR(255)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PSERVICEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service ID is required';
    END IF;

    SELECT COUNT(*) INTO VCOUNT
    FROM CMS_SERVICE
    WHERE SERVICEID = PSERVICEID;

    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service not found';
    END IF;

    IF PSERVNAME IS NULL OR TRIM(PSERVNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service Name is required';
    END IF;

    IF PDEFSTART IS NULL OR PDEFEND IS NULL OR PDEFEND <= PDEFSTART THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service end time must be after start time';
    END IF;

    IF PVALIDUNTIL IS NOT NULL AND PVALIDFROM IS NOT NULL AND PVALIDUNTIL < PVALIDFROM THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service valid until date must be greater than or equal to valid from date';
    END IF;

    IF PSTATUS IS NULL OR PSTATUS NOT IN ('A', 'D', 'EXP', 'BLK') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid service status';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_SERVHIST (SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, CHANGEDBY, CHGREASON)
    SELECT SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, PCHANGEDBY, PCHGREASON
    FROM CMS_SERVICE
    WHERE SERVICEID = PSERVICEID;

    UPDATE CMS_SERVICE
    SET SERVNAME = TRIM(PSERVNAME),
        DEFSTART = PDEFSTART,
        DEFEND = PDEFEND,
        VALIDFROM = PVALIDFROM,
        VALIDUNTIL = PVALIDUNTIL,
        STATUS = PSTATUS,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE SERVICEID = PSERVICEID;

    COMMIT;
END$$

