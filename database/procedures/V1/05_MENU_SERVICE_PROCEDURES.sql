CREATE PROCEDURE CMSUPDMENU (
    IN PMENUITEMID INT,
    IN PSHORTNAME VARCHAR(30),
    IN PITEMNAME VARCHAR(100),
    IN PITEMDESCR VARCHAR(255),
    IN PPERMPRICE DECIMAL(10,2),
    IN PCONTPRICE DECIMAL(10,2),
    IN PVISPRICE DECIMAL(10,2),
    IN POFFPRICE DECIMAL(10,2),
    IN PISSPECIAL TINYINT,
    IN PSTATUS VARCHAR(20),
    IN PCHANGEDBY INT,
    IN PCHGREASON VARCHAR(255)
)
BEGIN
    INSERT INTO CMS_MENUHIST (MENUITEMID, MENUCODE, SHORTNAME, ITEMNAME, ITEMDESCR, PERMPRICE, CONTPRICE, VISPRICE, OFFPRICE, ISSPECIAL, STATUS, CHANGEDBY, CHGREASON)
