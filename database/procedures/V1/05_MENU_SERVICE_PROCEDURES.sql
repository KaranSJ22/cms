DELIMITER $$

CREATE PROCEDURE CMSADDSERV (
    IN PSERVCODE VARCHAR(20),
    IN PSERVNAME VARCHAR(80),
    IN PDEFSTART TIME,
    IN PDEFEND TIME,
    IN PVALIDFROM DATE,
    IN PVALIDUNTIL DATE,
    IN PCREATEDBY INT
)
BEGIN
    INSERT INTO CMS_SERVICE (SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, CREATEDBY)
    VALUES (PSERVCODE, PSERVNAME, PDEFSTART, PDEFEND, PVALIDFROM, PVALIDUNTIL, 'A', PCREATEDBY);

    SELECT LAST_INSERT_ID() AS SERVICEID;
END$$

CREATE PROCEDURE CMSUPDSERV (
    IN PSERVICEID INT,
    IN PSERVNAME VARCHAR(80),
    IN PDEFSTART TIME,
    IN PDEFEND TIME,
    IN PVALIDFROM DATE,
    IN PVALIDUNTIL DATE,
    IN PSTATUS VARCHAR(20),
    IN PCHANGEDBY INT,
    IN PCHGREASON VARCHAR(255)
)
BEGIN
    INSERT INTO CMS_SERVHIST (SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, CHANGEDBY, CHGREASON)
    SELECT SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, PCHANGEDBY, PCHGREASON
    FROM CMS_SERVICE
    WHERE SERVICEID = PSERVICEID;

    UPDATE CMS_SERVICE
    SET SERVNAME = PSERVNAME,
        DEFSTART = PDEFSTART,
        DEFEND = PDEFEND,
        VALIDFROM = PVALIDFROM,
        VALIDUNTIL = PVALIDUNTIL,
        STATUS = PSTATUS,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE SERVICEID = PSERVICEID;
END$$

