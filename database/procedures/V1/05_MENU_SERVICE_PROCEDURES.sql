CREATE PROCEDURE CMSUPDSLOT (
    IN PDAYSLOTID INT,
    IN PSTARTTIME TIME,
    IN PENDTIME TIME,
    IN PSTATUS VARCHAR(20),
    IN PCHANGEDBY INT,
    IN PCHGREASON VARCHAR(255)
)
BEGIN
    INSERT INTO CMS_SLOTHIST (DAYSLOTID, SERVICEID, SERVDATE, STARTTIME, ENDTIME, STATUS, CHANGEDBY, CHGREASON)
    SELECT DAYSLOTID, SERVICEID, SERVDATE, STARTTIME, ENDTIME, STATUS, PCHANGEDBY, PCHGREASON
    FROM CMS_DAYSLOT
    WHERE DAYSLOTID = PDAYSLOTID;

    UPDATE CMS_DAYSLOT
    SET STARTTIME = PSTARTTIME,
        ENDTIME = PENDTIME,
        STATUS = PSTATUS,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE DAYSLOTID = PDAYSLOTID;
END$$

CREATE PROCEDURE CMSADDDMENU (
    IN PDAYSLOTID INT,
    IN PMENUITEMID INT,
    IN PISSPECIAL TINYINT,
    IN PISPREBOOK TINYINT,
    IN PISWALKIN TINYINT,
    IN PISKIOSK TINYINT,
    IN PAVAILQTY INT,
    IN PMAXQTY INT,
    IN PBOOKSTART DATETIME,
    IN PBOOKEND DATETIME,
    IN PCANCELAT DATETIME,
    IN PADDEDBY INT,
    IN PREMARKS VARCHAR(255)
)
BEGIN
    DECLARE VDMENUNO VARCHAR(30);

    CALL CMSGENAUTO('CMS_DAYMENU', 'DMENUNO', VDMENUNO);

    INSERT INTO CMS_DAYMENU (DMENUNO, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, ADDEDBY, REMARKS)
    VALUES (VDMENUNO, PDAYSLOTID, PMENUITEMID, PISSPECIAL, PISPREBOOK, PISWALKIN, PISKIOSK, PAVAILQTY, PMAXQTY, PBOOKSTART, PBOOKEND, PCANCELAT, 'P', PADDEDBY, PREMARKS);

    SELECT LAST_INSERT_ID() AS DAYMENUID, VDMENUNO AS DMENUNO;
END$$

CREATE PROCEDURE CMSAPPDMENU (
    IN PDAYMENUID INT,
    IN PAPPRSTATUS VARCHAR(20),
    IN PAPPROVEDBY INT,
    IN PREMARKS VARCHAR(255)
)
BEGIN
    INSERT INTO CMS_DMENUHIS (DAYMENUID, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, CHANGEDBY, CHGREASON, REMARKS)
    SELECT DAYMENUID, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, PAPPROVEDBY, 'Approval status changed', REMARKS
    FROM CMS_DAYMENU
    WHERE DAYMENUID = PDAYMENUID;

    UPDATE CMS_DAYMENU
    SET APPRSTATUS = PAPPRSTATUS,
        APPROVEDBY = PAPPROVEDBY,
        APPROVEDAT = CURRENT_TIMESTAMP,
        REMARKS = PREMARKS,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE DAYMENUID = PDAYMENUID;
END$$

CREATE PROCEDURE CMSVIEWMENU (
    IN PSERVDATE DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.DAYSLOTID,
        S.SERVCODE,
        S.SERVNAME,
        DS.SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUCODE,
        MI.ITEMNAME,
        MI.ITEMDESCR,
        CASE
            WHEN PCTYPECODE IN ('PERMANENT', 'OTHERCENTRE') THEN MI.PERMPRICE
            WHEN PCTYPECODE = 'CONTRACT' THEN MI.CONTPRICE
            WHEN PCTYPECODE = 'VISITOR' THEN MI.VISPRICE
            ELSE MI.VISPRICE
        END AS DISPLAYPRICE,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKSTART,
        DM.BOOKEND,
        DM.CANCELAT
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    WHERE DS.SERVDATE = PSERVDATE
      AND DM.APPRSTATUS = 'APP'
      AND DS.STATUS = 'A'
      AND MI.STATUS = 'A'
    ORDER BY DS.STARTTIME, MI.ITEMNAME;
END$$

DELIMITER ;
