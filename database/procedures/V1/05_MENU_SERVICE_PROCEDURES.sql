-- v2_module2
-- Added day-menu business validation and atomic DMENUNO generation within this transaction.
CREATE PROCEDURE CMSADDDMENU (
    IN PDAYSLOTID INT,
    IN PMENUITEMID INT,
    IN PISSPECIAL TINYINT,
    IN PISPREBOOK TINYINT,
    IN PISWALKIN TINYINT,
    IN PISKIOSK TINYINT,
    IN PAVAILQTY INT,
    IN PMAXQTY INT,
    IN PBOOKSTART DATETIME,
    IN PBOOKEND DATETIME,
    IN PCANCELAT DATETIME,
    IN PADDEDBY INT,
    IN PREMARKS VARCHAR(255)
)
BEGIN
    DECLARE VDMENUNO VARCHAR(30);
    DECLARE VDAYMENUID INT;
    DECLARE VSLOTSTATUS VARCHAR(20);
    DECLARE VMENUSTATUS VARCHAR(20);
    DECLARE VSERVDATE DATE;
    DECLARE VSTARTTIME TIME;
    DECLARE VEXISTS INT DEFAULT 0;
    DECLARE VPREFIX VARCHAR(5);
    DECLARE VLASTNO BIGINT;
    DECLARE VNEWNO BIGINT;
    DECLARE VYEAR CHAR(4);
    DECLARE VLENGTH INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PDAYSLOTID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day Slot ID is required';
    END IF;

    IF PMENUITEMID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu Item ID is required';
    END IF;

    IF PBOOKSTART IS NULL OR PBOOKEND IS NULL OR PCANCELAT IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking start, booking end, and cancellation deadline are required';
    END IF;

    IF PBOOKEND <= PBOOKSTART THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking end must be after booking start';
    END IF;

    IF PAVAILQTY IS NULL OR PAVAILQTY < 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Available quantity must be zero or greater';
    END IF;

    IF PMAXQTY IS NULL OR PMAXQTY < 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Maximum quantity must be at least one';
    END IF;

    IF COALESCE(PISSPECIAL, 0) NOT IN (0, 1)
       OR COALESCE(PISPREBOOK, 1) NOT IN (0, 1)
       OR COALESCE(PISWALKIN, 1) NOT IN (0, 1)
       OR COALESCE(PISKIOSK, 1) NOT IN (0, 1) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid day menu channel flag';
    END IF;

    SELECT STATUS, SERVDATE, STARTTIME
    INTO VSLOTSTATUS, VSERVDATE, VSTARTTIME
    FROM CMS_DAYSLOT
    WHERE DAYSLOTID = PDAYSLOTID;

    IF VSLOTSTATUS IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day slot not found';
    END IF;

    IF VSLOTSTATUS <> 'A' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day slot must be active';
    END IF;

    SELECT STATUS
    INTO VMENUSTATUS
    FROM CMS_MENUITEM
    WHERE MENUITEMID = PMENUITEMID;

    IF VMENUSTATUS IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu item not found';
    END IF;

    IF VMENUSTATUS <> 'A' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu item must be active';
    END IF;

    IF PCANCELAT > TIMESTAMP(VSERVDATE, VSTARTTIME) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cancellation deadline must be before service begins';
    END IF;

    SELECT COUNT(*) INTO VEXISTS
    FROM CMS_DAYMENU
    WHERE DAYSLOTID = PDAYSLOTID
      AND MENUITEMID = PMENUITEMID;

    IF VEXISTS > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Menu item is already assigned to this day slot';
    END IF;

    START TRANSACTION;

    SELECT PREFIXCHAR, LASTNO, ITEMLEN
    INTO VPREFIX, VLASTNO, VLENGTH
    FROM CMS_AUTONOS
    WHERE TBLNAME = 'CMS_DAYMENU'
      AND DATAITEM = 'DMENUNO'
      AND STATUS = 'A'
    FOR UPDATE;

    IF VPREFIX IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Active day menu autonumber configuration not found';
    END IF;

    SET VNEWNO = VLASTNO + 1;
    SET VYEAR = DATE_FORMAT(CURRENT_DATE, '%Y');
    SET VDMENUNO = CONCAT(VPREFIX, VYEAR, LPAD(VNEWNO, GREATEST(VLENGTH - LENGTH(VPREFIX) - 4, 1), '0'));

    UPDATE CMS_AUTONOS
    SET LASTNO = VNEWNO,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE TBLNAME = 'CMS_DAYMENU'
      AND DATAITEM = 'DMENUNO';

    INSERT INTO CMS_DAYMENU (DMENUNO, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, ADDEDBY, REMARKS)
    VALUES (VDMENUNO, PDAYSLOTID, PMENUITEMID, COALESCE(PISSPECIAL, 0), COALESCE(PISPREBOOK, 1), COALESCE(PISWALKIN, 1), COALESCE(PISKIOSK, 1), PAVAILQTY, PMAXQTY, PBOOKSTART, PBOOKEND, PCANCELAT, 'P', PADDEDBY, PREMARKS);

    SET VDAYMENUID = LAST_INSERT_ID();

    COMMIT;

    SELECT VDAYMENUID AS DAYMENUID, VDMENUNO AS DMENUNO;
END$$

-- v2_module2
-- Added approval status validation, processed-record protection, history capture, and transaction exception handling.
CREATE PROCEDURE CMSAPPDMENU (
    IN PDAYMENUID INT,
    IN PAPPRSTATUS VARCHAR(20),
    IN PAPPROVEDBY INT,
    IN PREMARKS VARCHAR(255)
)
BEGIN
    DECLARE VCURRENTSTATUS VARCHAR(20);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PDAYMENUID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day Menu ID is required';
    END IF;

    IF PAPPRSTATUS IS NULL OR PAPPRSTATUS NOT IN ('APP', 'REJ') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Approval status must be APP or REJ';
    END IF;

    SELECT APPRSTATUS
    INTO VCURRENTSTATUS
    FROM CMS_DAYMENU
    WHERE DAYMENUID = PDAYMENUID;

    IF VCURRENTSTATUS IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day menu not found';
    END IF;

    IF VCURRENTSTATUS <> 'P' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day menu has already been processed';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_DMENUHIS (DAYMENUID, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, CHANGEDBY, CHGREASON, REMARKS)
    SELECT DAYMENUID, DAYSLOTID, MENUITEMID, ISSPECIAL, ISPREBOOK, ISWALKIN, ISKIOSK, AVAILQTY, MAXQTY, BOOKSTART, BOOKEND, CANCELAT, APPRSTATUS, PAPPROVEDBY, 'Approval status changed', REMARKS
    FROM CMS_DAYMENU
    WHERE DAYMENUID = PDAYMENUID;

    UPDATE CMS_DAYMENU
    SET APPRSTATUS = PAPPRSTATUS,
        APPROVEDBY = PAPPROVEDBY,
        APPROVEDAT = CURRENT_TIMESTAMP,
        REMARKS = PREMARKS,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE DAYMENUID = PDAYMENUID;

    COMMIT;
END$$

-- v2_module2
-- Modified to return active services, active slots, active items, approved menus, and currently bookable windows.
CREATE PROCEDURE CMSVIEWMENU (
    IN PSERVDATE DATE,
    IN PCTYPECODE VARCHAR(20)
)
BEGIN
    SELECT
        DS.DAYSLOTID,
        S.SERVCODE,
        S.SERVNAME,
        DS.SERVDATE,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.DAYMENUID,
        DM.DMENUNO,
        MI.MENUCODE,
        MI.ITEMNAME,
        MI.ITEMDESCR,
        CASE
            WHEN PCTYPECODE IN ('PERMANENT', 'OTHERCENTRE') THEN MI.PERMPRICE
            WHEN PCTYPECODE = 'CONTRACT' THEN MI.CONTPRICE
            WHEN PCTYPECODE = 'VISITOR' THEN MI.VISPRICE
            ELSE MI.VISPRICE
        END AS DISPLAYPRICE,
        DM.AVAILQTY,
        DM.MAXQTY,
        DM.BOOKSTART,
        DM.BOOKEND,
        DM.CANCELAT
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    WHERE DS.SERVDATE = PSERVDATE
      AND DM.APPRSTATUS = 'APP'
      AND DS.STATUS = 'A'
      AND S.STATUS = 'A'
      AND MI.STATUS = 'A'
      AND CURRENT_TIMESTAMP BETWEEN DM.BOOKSTART AND DM.BOOKEND
    ORDER BY DS.STARTTIME, S.SERVNAME, MI.ITEMNAME;
END$$

