-- v2_module2
-- Added service existence, active service, mandatory input, time range, and transaction exception validation.
CREATE PROCEDURE CMSADDSLOT (
    IN PSERVICEID INT,
    IN PSERVDATE DATE,
    IN PSTARTTIME TIME,
    IN PENDTIME TIME,
    IN PCREATEDBY INT
)
BEGIN
    DECLARE VSERVSTATUS VARCHAR(20);
    DECLARE VVALIDFROM DATE;
    DECLARE VVALIDUNTIL DATE;
    DECLARE VDAYSLOTID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PSERVICEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service ID is required';
    END IF;

    IF PSERVDATE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service Date is required';
    END IF;

    IF PSTARTTIME IS NULL OR PENDTIME IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Slot start and end time are required';
    END IF;

    IF PENDTIME <= PSTARTTIME THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Slot end time must be after start time';
    END IF;

    SELECT STATUS, VALIDFROM, VALIDUNTIL
    INTO VSERVSTATUS, VVALIDFROM, VVALIDUNTIL
    FROM CMS_SERVICE
    WHERE SERVICEID = PSERVICEID;

    IF VSERVSTATUS IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service not found';
    END IF;

    IF VSERVSTATUS <> 'A' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service must be active';
    END IF;

    IF (VVALIDFROM IS NOT NULL AND PSERVDATE < VVALIDFROM)
       OR (VVALIDUNTIL IS NOT NULL AND PSERVDATE > VVALIDUNTIL) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service date is outside service validity period';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_DAYSLOT (SERVICEID, SERVDATE, STARTTIME, ENDTIME, STATUS, CREATEDBY)
    VALUES (PSERVICEID, PSERVDATE, PSTARTTIME, PENDTIME, 'A', PCREATEDBY);

    SET VDAYSLOTID = LAST_INSERT_ID();

    COMMIT;

    SELECT VDAYSLOTID AS DAYSLOTID;
END$$

