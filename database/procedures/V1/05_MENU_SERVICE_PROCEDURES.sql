-- v2_module2
-- Added mandatory input, time range, date range, and transaction exception validation.
CREATE PROCEDURE CMSADDSERV (
    IN PSERVCODE VARCHAR(20),
    IN PSERVNAME VARCHAR(80),
    IN PDEFSTART TIME,
    IN PDEFEND TIME,
    IN PVALIDFROM DATE,
    IN PVALIDUNTIL DATE,
    IN PCREATEDBY INT
)
BEGIN
    DECLARE VSERVICEID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PSERVCODE IS NULL OR TRIM(PSERVCODE) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service Code is required';
    END IF;

    IF PSERVNAME IS NULL OR TRIM(PSERVNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service Name is required';
    END IF;

    IF PDEFSTART IS NULL OR PDEFEND IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service start and end time are required';
    END IF;

    IF PDEFEND <= PDEFSTART THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service end time must be after start time';
    END IF;

    IF PVALIDUNTIL IS NOT NULL AND PVALIDFROM IS NOT NULL AND PVALIDUNTIL < PVALIDFROM THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service valid until date must be greater than or equal to valid from date';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_SERVICE (SERVCODE, SERVNAME, DEFSTART, DEFEND, VALIDFROM, VALIDUNTIL, STATUS, CREATEDBY)
    VALUES (TRIM(PSERVCODE), TRIM(PSERVNAME), PDEFSTART, PDEFEND, PVALIDFROM, PVALIDUNTIL, 'A', PCREATEDBY);

    SET VSERVICEID = LAST_INSERT_ID();

    COMMIT;

    SELECT VSERVICEID AS SERVICEID;
END$$

