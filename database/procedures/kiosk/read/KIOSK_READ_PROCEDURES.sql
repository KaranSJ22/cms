/* ============================================================
   CMSIDENTIFYKIOSK
   Resolves physical kiosk metadata and assigned canteen by IP address
   ============================================================ */
CREATE PROCEDURE CMSIDENTIFYKIOSK (
    IN PIPADDRESS VARCHAR(45)
)
BEGIN
    DECLARE VKIOSKID INT DEFAULT NULL;

    IF PIPADDRESS IS NULL OR TRIM(PIPADDRESS) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Client IP address is required';
    END IF;

    -- Lookup active kiosk matching the IP
    SELECT KD.KIOSKID INTO VKIOSKID
    FROM CMS_KIOSK KD
    WHERE KD.IPADDRESS = TRIM(PIPADDRESS)
      AND KD.STATUSID = 10
    LIMIT 1;

    IF VKIOSKID IS NOT NULL THEN
        -- Update last seen IP and heartbeat
        UPDATE CMS_KIOSK
        SET LASTHEARTBEATAT = CURRENT_TIMESTAMP,
            LASTSEENIP = TRIM(PIPADDRESS)
        WHERE KIOSKID = VKIOSKID;

        -- Return Kiosk + Canteen Configuration
        SELECT 
            KD.KIOSKID,
            KD.DEVICECODE,
            KD.DEVICENAME,
            KD.IPADDRESS,
            KD.MACADDRESS,
            KD.CANTEENID,
            C.CANTEENNAME,
            C.CANTEENCODE,
            C.LOCATION AS CANTEENLOCATION,
            KD.KIOSKTYPE,
            (CASE WHEN KD.STATUSID = 10 THEN 1 ELSE 0 END) AS ISACTIVE,
            ST.STATUSCODE
        FROM CMS_KIOSK KD
        JOIN CMS_CANTEEN C ON C.CANTEENID = KD.CANTEENID
        JOIN CMS_STATUS ST ON ST.STATUSID = KD.STATUSID
        WHERE KD.KIOSKID = VKIOSKID;
    ELSE
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Kiosk device not registered for this IP address';
    END IF;
END$$


