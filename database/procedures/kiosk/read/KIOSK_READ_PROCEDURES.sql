/* ============================================================
   CMSKIOSKGETCURRENTSLOT
   Returns the meal slot currently active for the canteen based on clock time,
   or the next upcoming slot for today.
   ============================================================ */
CREATE PROCEDURE CMSKIOSKGETCURRENTSLOT (
    IN PCANTEENID INT,
    IN PKIOSKID   INT
)
BEGIN
    DECLARE VCANTEENID INT DEFAULT PCANTEENID;
    DECLARE VSLOTCOUNT INT DEFAULT 0;

    -- If CANTEENID was not passed but KIOSKID is available, resolve from Kiosk record
    IF VCANTEENID IS NULL AND PKIOSKID IS NOT NULL THEN
        SELECT KD.CANTEENID INTO VCANTEENID
        FROM CMS_KIOSK KD
        WHERE KD.KIOSKID = PKIOSKID
        LIMIT 1;
    END IF;

    IF VCANTEENID IS NULL THEN
        SET VCANTEENID = 1;
    END IF;

    -- 1. Check for slot currently serving (within STARTTIME - 15m and ENDTIME + 15m buffer)
    SELECT COUNT(*) INTO VSLOTCOUNT
    FROM CMS_DAYSLOT DS
    WHERE DS.CANTEENID = VCANTEENID
      AND DS.SERVICEDATE = CURDATE()
      AND DS.STATUSID = 10
      AND CURRENT_TIME() BETWEEN (DS.STARTTIME - INTERVAL 15 MINUTE) AND (DS.ENDTIME + INTERVAL 15 MINUTE);

    IF VSLOTCOUNT > 0 THEN
        SELECT 
            DS.DAYSLOTID,
            DS.SLOTNO,
            DS.SERVICEID,
            S.SERVCODE,
            S.SERVNAME,
            DS.CANTEENID,
            C.CANTEENNAME,
            C.CANTEENCODE,
            DS.SERVICEDATE,
            DS.SERVICEDATE AS SERVDATE,
            DS.STARTTIME,
            DS.ENDTIME,
            1 AS ISACTIVENOW,
            GREATEST(0, TIMESTAMPDIFF(MINUTE, CURRENT_TIMESTAMP, CONCAT(DS.SERVICEDATE, ' ', DS.ENDTIME))) AS MINUTESREMAINING,
            0 AS MINUTESUNTILSTART,
            'SERVING' AS SLOTSTATE
        FROM CMS_DAYSLOT DS
        JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
        JOIN CMS_CANTEEN C ON C.CANTEENID = DS.CANTEENID
        WHERE DS.CANTEENID = VCANTEENID
          AND DS.SERVICEDATE = CURDATE()
          AND DS.STATUSID = 10
          AND CURRENT_TIME() BETWEEN (DS.STARTTIME - INTERVAL 15 MINUTE) AND (DS.ENDTIME + INTERVAL 15 MINUTE)
        ORDER BY DS.STARTTIME ASC
        LIMIT 1;
    ELSE
        -- 2. Fallback: Find the nearest UPCOMING slot today
        SELECT 
            DS.DAYSLOTID,
            DS.SLOTNO,
            DS.SERVICEID,
            S.SERVCODE,
            S.SERVNAME,
            DS.CANTEENID,
            C.CANTEENNAME,
            C.CANTEENCODE,
            DS.SERVICEDATE,
            DS.SERVICEDATE AS SERVDATE,
            DS.STARTTIME,
            DS.ENDTIME,
            0 AS ISACTIVENOW,
            0 AS MINUTESREMAINING,
            GREATEST(0, TIMESTAMPDIFF(MINUTE, CURRENT_TIMESTAMP, CONCAT(DS.SERVICEDATE, ' ', DS.STARTTIME))) AS MINUTESUNTILSTART,
            'UPCOMING' AS SLOTSTATE
        FROM CMS_DAYSLOT DS
        JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
        JOIN CMS_CANTEEN C ON C.CANTEENID = DS.CANTEENID
        WHERE DS.CANTEENID = VCANTEENID
          AND DS.SERVICEDATE = CURDATE()
          AND DS.STATUSID = 10
          AND DS.STARTTIME > CURRENT_TIME()
        ORDER BY DS.STARTTIME ASC
        LIMIT 1;
    END IF;
END$$


/* ============================================================
   CMSKIOSKRESOLVEBOOKING
   Dedicated Kiosk Serving resolver:
   - Priority resolution: RFID KeyCard UID -> LoginID -> CustomerID -> BookNo
   - Slot-aware matching: prioritized to active meal slot at current time
   - Returns 2 Result Sets: Header (with slot & out-of-window warning) + Items
   ============================================================ */
CREATE PROCEDURE CMSKIOSKRESOLVEBOOKING (
    IN PIDENTIFIER VARCHAR(255),
    IN PCANTEENID   INT,
    IN PKIOSKID     INT,
    IN PDAYSLOTID   INT
)
BEGIN
    DECLARE VBOOKID        INT DEFAULT NULL;
    DECLARE VCUSTOMERID    INT DEFAULT NULL;
    DECLARE VCANTEENID     INT DEFAULT PCANTEENID;
    DECLARE VACTIVESLOTID  INT DEFAULT PDAYSLOTID;
    DECLARE VIDENTIFIER    VARCHAR(255);

    IF PIDENTIFIER IS NULL OR TRIM(PIDENTIFIER) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Identifier or Booking Number is required';
    END IF;

    SET VIDENTIFIER = TRIM(PIDENTIFIER);

    -- If CANTEENID was not provided, derive from Kiosk hardware record
    IF VCANTEENID IS NULL AND PKIOSKID IS NOT NULL THEN
        SELECT KD.CANTEENID INTO VCANTEENID
        FROM CMS_KIOSK KD
        WHERE KD.KIOSKID = PKIOSKID
        LIMIT 1;
    END IF;

    -- 1. Direct formatted Booking Number (PB... / BK... / KS... / WI...)
    IF UPPER(VIDENTIFIER) LIKE 'PB%' OR UPPER(VIDENTIFIER) LIKE 'BK%' OR UPPER(VIDENTIFIER) LIKE 'KS%' OR UPPER(VIDENTIFIER) LIKE 'WI%' THEN
        SELECT B.BOOKID INTO VBOOKID
        FROM CMS_BOOKING B
        LEFT JOIN CMS_BOOKITEM BI ON BI.BOOKID = B.BOOKID
        LEFT JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        LEFT JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        WHERE B.BOOKNO = VIDENTIFIER
          AND (VCANTEENID IS NULL OR DS.CANTEENID = VCANTEENID)
        LIMIT 1;
    ELSE
        -- 2. Try RFID Access Key
        SELECT AK.CUSTOMERID INTO VCUSTOMERID
        FROM CMS_ACCKEY AK
        JOIN CMS_STATUS STAK ON STAK.STATUSID = AK.STATUSID
        WHERE AK.KEYVALUE = VIDENTIFIER
          AND STAK.STATUSCODE = 'ACT'
          AND (AK.EXPIRESAT IS NULL OR AK.EXPIRESAT > CURRENT_TIMESTAMP)
        LIMIT 1;

        -- 3. Fallback to CMS_USER.LOGINID
        IF VCUSTOMERID IS NULL THEN
            SELECT C.CUSTOMERID INTO VCUSTOMERID
            FROM CMS_USER U
            JOIN CMS_CUSTOMER C ON C.USERID = U.USERID
            WHERE U.LOGINID = VIDENTIFIER
            LIMIT 1;
        END IF;

        -- 4. Fallback to direct numeric CUSTOMERID
        IF VCUSTOMERID IS NULL AND VIDENTIFIER REGEXP '^[0-9]+$' THEN
            SELECT C.CUSTOMERID INTO VCUSTOMERID
            FROM CMS_CUSTOMER C
            WHERE C.CUSTOMERID = CAST(VIDENTIFIER AS UNSIGNED)
            LIMIT 1;
        END IF;

        -- 5. Fallback to employee code, contractor code, or visitor phone
        IF VCUSTOMERID IS NULL THEN
            SELECT C.CUSTOMERID INTO VCUSTOMERID
            FROM CMS_CUSTOMER C
            LEFT JOIN CMS_PERMEMP PE ON PE.CUSTOMERID = C.CUSTOMERID
            LEFT JOIN CMS_CONTEMP CE ON CE.CUSTOMERID = C.CUSTOMERID
            LEFT JOIN CMS_OCEEMP OE ON OE.CUSTOMERID = C.CUSTOMERID
            LEFT JOIN CMS_VISITOR V ON V.CUSTOMERID = C.CUSTOMERID
            WHERE LOWER(PE.EMPCODE) = LOWER(VIDENTIFIER)
               OR LOWER(CE.CONTCODE) = LOWER(VIDENTIFIER)
               OR LOWER(OE.EMPCODE) = LOWER(VIDENTIFIER)
               OR V.MOBILENO = VIDENTIFIER
            LIMIT 1;
        END IF;

        IF VCUSTOMERID IS NULL THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Employee or badge not recognized';
        END IF;

        -- 5. Auto-detect active meal slot if PDAYSLOTID was not explicitly specified
        IF VACTIVESLOTID IS NULL AND VCANTEENID IS NOT NULL THEN
            SELECT DS.DAYSLOTID INTO VACTIVESLOTID
            FROM CMS_DAYSLOT DS
            WHERE DS.CANTEENID = VCANTEENID
              AND DS.SERVICEDATE = CURDATE()
              AND DS.STATUSID = 10
              AND CURRENT_TIME() BETWEEN (DS.STARTTIME - INTERVAL 30 MINUTE) AND (DS.ENDTIME + INTERVAL 30 MINUTE)
            ORDER BY DS.STARTTIME ASC
            LIMIT 1;
        END IF;

        -- 6. Slot-Aware Matching: First look for a booking in the active meal slot
        IF VACTIVESLOTID IS NOT NULL THEN
            SELECT B.BOOKID INTO VBOOKID
            FROM CMS_BOOKING B
            JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
            JOIN CMS_BOOKITEM BI ON BI.BOOKID = B.BOOKID
            JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
            WHERE B.CUSTOMERID = VCUSTOMERID
              AND B.SERVICEDATE = CURDATE()
              AND DM.DAYSLOTID = VACTIVESLOTID
              AND ST.STATUSCODE IN ('CRT', 'SRV')
            ORDER BY (CASE WHEN ST.STATUSCODE = 'CRT' THEN 0 ELSE 1 END) ASC, B.BOOKID DESC
            LIMIT 1;
        END IF;

        -- 7. Fallback: If no booking in current slot, find ANY booking for today (prioritizing CRT)
        IF VBOOKID IS NULL THEN
            SELECT B.BOOKID INTO VBOOKID
            FROM CMS_BOOKING B
            JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
            LEFT JOIN CMS_BOOKITEM BI ON BI.BOOKID = B.BOOKID
            LEFT JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
            LEFT JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
            WHERE B.CUSTOMERID = VCUSTOMERID
              AND B.SERVICEDATE = CURDATE()
              AND ST.STATUSCODE IN ('CRT', 'SRV')
              AND (VCANTEENID IS NULL OR DS.CANTEENID IS NULL OR DS.CANTEENID = VCANTEENID)
            ORDER BY (CASE WHEN ST.STATUSCODE = 'CRT' THEN 0 ELSE 1 END) ASC, B.BOOKID DESC
            LIMIT 1;
        END IF;
    END IF;

    IF VBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'No active booking found for this customer today';
    END IF;

    -- Result Set 1: Booking Header
    SELECT 
        B.BOOKID,
        B.BOOKNO,
        B.BOOKTYPEID,
        BT.BOOKTYPECODE,
        BT.BOOKTYPENAME,
        B.CUSTOMERID,
        C.DISPNAME AS CUSTOMERNAME,
        CT.CTYPECODE,
        U.LOGINID,
        B.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DS.DAYSLOTID,
        DS.SLOTNO,
        DS.STARTTIME,
        DS.ENDTIME,
        DS.CANTEENID,
        CAN.CANTEENNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE AS STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.BOOKEDAT,
        B.BOOKEDAT AS BOOKEDON,
        B.SERVEDBY,
        USRV.FULLNAME AS SERVEDBYNAME,
        B.SERVEDAT,
        B.SERVEDAT AS SERVEDON,
        B.KIOSKID,
        KD.DEVICECODE AS SERVEDKIOSKCODE,
        (CASE 
            WHEN DS.STARTTIME IS NOT NULL AND CURRENT_TIME() BETWEEN (DS.STARTTIME - INTERVAL 15 MINUTE) AND (DS.ENDTIME + INTERVAL 15 MINUTE) THEN 1 
            ELSE 0 
        END) AS ISINWINDOW,
        B.REMARKS
    FROM CMS_BOOKING B
    JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    JOIN CMS_CUSTOMER C  ON C.CUSTOMERID  = B.CUSTOMERID
    JOIN CMS_CUSTTYPE CT ON CT.CTYPEID    = C.CTYPEID
    JOIN CMS_SERVICE  S  ON S.SERVICEID   = B.SERVICEID
    JOIN CMS_STATUS   ST ON ST.STATUSID   = B.STATUSID
    LEFT JOIN CMS_USER U ON U.USERID      = C.USERID
    LEFT JOIN CMS_USER USRV ON USRV.USERID = B.SERVEDBY
    LEFT JOIN CMS_KIOSK KD ON KD.KIOSKID = B.KIOSKID
    LEFT JOIN CMS_BOOKITEM BI ON BI.BOOKID = B.BOOKID
    LEFT JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
    LEFT JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    LEFT JOIN CMS_CANTEEN CAN ON CAN.CANTEENID = DS.CANTEENID
    WHERE B.BOOKID = VBOOKID
    LIMIT 1;

    -- Result Set 2: Booking Items
    SELECT
        BI.BOOKITEMID,
        BI.DAYMENUID,
        BI.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        BI.QTY,
        BI.RATE,
        BI.AMOUNT,
        BI.STATUSID,
        ST.STATUSCODE AS STATUSCODE
    FROM CMS_BOOKITEM BI
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = BI.MENUITEMID
    JOIN CMS_STATUS ST ON ST.STATUSID = BI.STATUSID
    WHERE BI.BOOKID = VBOOKID
    ORDER BY BI.BOOKITEMID ASC;

END$$


/* ============================================================
   CMSKIOSKSCANSELFSERVICE
   High-performance single round-trip scan for Employee Self-Service Kiosks.
   Returns:
     RS-1: Customer Profile + Wallet Eligibility & Balance
     RS-2: Today's Bookings for current meal slots
     RS-3: Upcoming Pre-Bookings
   ============================================================ */
CREATE PROCEDURE CMSKIOSKSCANSELFSERVICE (
    IN PIDENTIFIER VARCHAR(255),
    IN PCANTEENID   INT,
    IN PKIOSKID     INT
)
BEGIN
    DECLARE VCUSTOMERID INT DEFAULT NULL;
    DECLARE VIDENTIFIER VARCHAR(255);

    IF PIDENTIFIER IS NULL OR TRIM(PIDENTIFIER) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Identifier or card badge is required';
    END IF;

    SET VIDENTIFIER = TRIM(PIDENTIFIER);

    -- 1. Try RFID KeyCard
    SELECT AK.CUSTOMERID INTO VCUSTOMERID
    FROM CMS_ACCKEY AK
    JOIN CMS_STATUS STAK ON STAK.STATUSID = AK.STATUSID
    WHERE AK.KEYVALUE = VIDENTIFIER
      AND STAK.STATUSCODE = 'ACT'
      AND (AK.EXPIRESAT IS NULL OR AK.EXPIRESAT > CURRENT_TIMESTAMP)
    LIMIT 1;

    -- 2. Fallback to CMS_USER.LOGINID
    IF VCUSTOMERID IS NULL THEN
        SELECT C.CUSTOMERID INTO VCUSTOMERID
        FROM CMS_USER U
        JOIN CMS_CUSTOMER C ON C.USERID = U.USERID
        WHERE U.LOGINID = VIDENTIFIER
        LIMIT 1;
    END IF;

    -- 3. Fallback to direct numeric CUSTOMERID
    IF VCUSTOMERID IS NULL AND VIDENTIFIER REGEXP '^[0-9]+$' THEN
        SELECT C.CUSTOMERID INTO VCUSTOMERID
        FROM CMS_CUSTOMER C
        WHERE C.CUSTOMERID = CAST(VIDENTIFIER AS UNSIGNED)
        LIMIT 1;
    END IF;

    IF VCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Employee or badge not recognized';
    END IF;

    -- Result Set 1: Customer Profile + Wallet
    SELECT 
        C.CUSTOMERID,
        C.DISPNAME,
        CT.CTYPECODE,
        CT.CTYPENAME,
        U.LOGINID,
        COALESCE(PE.EMPCODE, CE.CONTCODE, U.LOGINID, CAST(C.CUSTOMERID AS CHAR)) AS EMPLOYEE_ID,
        PE.EMPCODE,
        CE.CONTCODE,
        PE.DEPT,
        PE.DESIG,
        CE.VENDORNAME,
        (CASE WHEN CT.CTYPECODE IN ('CONTEMP', 'CNT', 'VIS', 'VISITOR') THEN 1 ELSE 0 END) AS ISWALLETELIGIBLE,
        COALESCE(W.BALANCE, 0.00) AS WALLETBALANCE,
        COALESCE(W.RESERVEDAMT, 0.00) AS RESERVEDAMT,
        W.STATUSID AS WALLETSTATUSID
    FROM CMS_CUSTOMER C
    JOIN CMS_CUSTTYPE CT ON CT.CTYPEID = C.CTYPEID
    LEFT JOIN CMS_USER U ON U.USERID = C.USERID
    LEFT JOIN CMS_PERMEMP PE ON PE.CUSTOMERID = C.CUSTOMERID
    LEFT JOIN CMS_CONTEMP CE ON CE.CUSTOMERID = C.CUSTOMERID
    LEFT JOIN CMS_WALLET W ON W.CUSTOMERID = C.CUSTOMERID
    WHERE C.CUSTOMERID = VCUSTOMERID;

    -- Result Set 2: Today's Bookings
    SELECT 
        B.BOOKID,
        B.BOOKNO,
        B.SERVICEID,
        S.SERVNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.SERVEDAT,
        B.SERVEDAT AS SERVEDON,
        B.SERVEDBY
    FROM CMS_BOOKING B
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    WHERE B.CUSTOMERID = VCUSTOMERID
      AND B.SERVICEDATE = CURDATE()
    ORDER BY B.BOOKID DESC;

    -- Result Set 3: Upcoming Pre-Bookings
    SELECT 
        B.BOOKID,
        B.BOOKNO,
        B.SERVICEID,
        S.SERVNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.BOOKEDAT,
        B.BOOKEDAT AS BOOKEDON
    FROM CMS_BOOKING B
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    WHERE B.CUSTOMERID = VCUSTOMERID
      AND B.SERVICEDATE > CURDATE()
      AND ST.STATUSCODE = 'CRT'
    ORDER BY B.SERVICEDATE ASC, B.BOOKID ASC;

END$$


/* ============================================================
   CMSGETKIOSKPUBLISHEDMENU — Published Menu items enabled for Kiosks
   ============================================================ */
CREATE PROCEDURE CMSGETKIOSKPUBLISHEDMENU (
    IN PCANTEENID INT,
    IN PSERVDATE  DATE,
    IN PSERVICEID INT
)
BEGIN
    SELECT 
        DM.DAYMENUID,
        DM.DAYSLOTID,
        DS.SERVICEID,
        S.SERVNAME,
        DS.STARTTIME,
        DS.ENDTIME,
        DM.MENUITEMID,
        MI.MENUCODE,
        MI.SHORTNAME,
        MI.ITEMNAME,
        MI.DESCR AS ITEMDESC,
        MI.DESCR AS ITEMDESCR,
        MI.DESCR,
        COALESCE(
          (SELECT IPD.PRICE 
           FROM CMS_ITEMPRICE IP
           JOIN CMS_ITMPRICDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
           WHERE IP.MENUITEMID = MI.MENUITEMID 
             AND IP.STATUSID = 10 
             AND IP.EFFFROM <= PSERVDATE
           ORDER BY IP.EFFFROM DESC 
           LIMIT 1),
          0.00
        ) AS RATE,
        DM.BOOKUNTIL,
        DM.CANCELUNTIL,
        DM.AVAILQTY,
        DM.MAXQTY
     FROM CMS_DAYMENU DM
     JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
     JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
     JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
     WHERE DS.CANTEENID = PCANTEENID
       AND DS.SERVICEDATE = PSERVDATE
       AND DM.ISKIOSK = 1
       AND DM.STATUSID = 10
       AND (PSERVICEID IS NULL OR DS.SERVICEID = PSERVICEID)
     ORDER BY DS.STARTTIME ASC, MI.ITEMNAME ASC;
END$$


