/* ============================================================
   CMSKIOSKGETCUSTOMERBOOKINGS — Last N Active/Upcoming Bookings for Kiosk
   ============================================================ */
CREATE PROCEDURE CMSKIOSKGETCUSTOMERBOOKINGS (
    IN PCUSTOMERID INT,
    IN PLIMIT INT
)
BEGIN
    DECLARE VLIMIT INT DEFAULT 10;
    IF PLIMIT IS NOT NULL AND PLIMIT > 0 THEN
        SET VLIMIT = PLIMIT;
    END IF;

    SELECT
        B.BOOKID,
        B.BOOKNO,
        BT.BOOKTYPECODE,
        BK_CAN.CANTEENID,
        BK_CAN.CANTEENNAME,
        B.SERVICEID,
        S.SERVNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE AS STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.BOOKEDAT,
        B.BOOKEDAT AS BOOKEDON,
        B.CANCELLEDAT,
        B.CANCELLEDAT AS CANCELLEDON,
        B.SERVEDAT,
        B.SERVEDAT AS SERVEDON,
        B.NOSHOWAT,
        B.NOSHOWAT AS NOSHOWON
    FROM CMS_BOOKING B
    JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
        FROM CMS_BOOKITEM BI
        JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN CMS_CANTEEN C ON C.CANTEENID = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE B.CUSTOMERID = PCUSTOMERID
      AND ST.STATUSCODE = 'CRT'
      AND B.SERVICEDATE >= CURDATE()
    ORDER BY B.SERVICEDATE ASC, B.BOOKID DESC
    LIMIT VLIMIT;
END$$


/* ============================================================
   CMSKIOSKGETNEXTDAYSERVICES — Meal services available tomorrow for kiosk
   ============================================================ */
CREATE PROCEDURE CMSKIOSKGETNEXTDAYSERVICES (
    IN PCANTEENID INT,
    IN PSERVICEDATE DATE
)
BEGIN
    SELECT 
        DS.SERVICEID,
        S.SERVCODE,
        S.SERVNAME,
        DS.STARTTIME,
        DS.ENDTIME,
        COUNT(DM.DAYMENUID) AS TOTALITEMS
    FROM CMS_DAYSLOT DS
    JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
    JOIN CMS_DAYMENU DM ON DM.DAYSLOTID = DS.DAYSLOTID AND DM.ISKIOSK = 1 AND DM.STATUSID = 10
    WHERE DS.CANTEENID = PCANTEENID
      AND DS.SERVICEDATE = PSERVICEDATE
      AND DS.STATUSID = 10
    GROUP BY DS.SERVICEID, S.SERVCODE, S.SERVNAME, DS.STARTTIME, DS.ENDTIME
    ORDER BY DS.STARTTIME ASC;
END$$


/* ============================================================
   CMSKIOSKGETBOOTSTRAP — Offline Kiosk Master Snapshot Package
   ============================================================ */
CREATE PROCEDURE CMSKIOSKGETBOOTSTRAP (
    IN PCANTEENID INT,
    IN PTODAY     DATE
)
BEGIN
    DECLARE VCANTEENID INT DEFAULT 1;
    IF PCANTEENID IS NOT NULL AND PCANTEENID > 0 THEN
        SET VCANTEENID = PCANTEENID;
    END IF;
    IF PTODAY IS NULL THEN
        SET PTODAY = CURDATE();
    END IF;

    -- RS-0: Last change timestamp
    SELECT GREATEST(
      COALESCE((SELECT MAX(COALESCE(UPDATEDAT, CREATEDAT)) FROM CMS_CUSTOMER WHERE STATUSID = 10), '1970-01-01 00:00:00'),
      COALESCE((SELECT MAX(COALESCE(UPDATEDAT, CREATEDAT)) FROM CMS_DAYMENU WHERE STATUSID = 10), '1970-01-01 00:00:00'),
      COALESCE((SELECT MAX(COALESCE(UPDATEDAT, CREATEDAT)) FROM CMS_DAYSLOT WHERE STATUSID = 10 AND CANTEENID = VCANTEENID), '1970-01-01 00:00:00'),
      COALESCE((SELECT MAX(COALESCE(UPDATEDAT, CREATEDAT)) FROM CMS_ACCKEY WHERE STATUSID = 10), '1970-01-01 00:00:00')
    ) AS LAST_CHANGE;

    -- RS-1: Customers
    SELECT 
        c.CUSTOMERID AS customerId,
        COALESCE(ak.KEYVALUE, '') AS rfidUid,
        COALESCE(pe.EMPCODE, ce.CONTCODE, oe.EMPCODE, u.LOGINID, CAST(c.CUSTOMERID AS CHAR)) AS loginId,
        c.DISPNAME AS dispName,
        ct.CTYPECODE AS ctypeCode,
        ct.CTYPENAME AS ctypeName
    FROM CMS_CUSTOMER c
    JOIN CMS_CUSTTYPE ct ON ct.CTYPEID = c.CTYPEID
    LEFT JOIN CMS_USER u ON u.USERID = c.USERID
    LEFT JOIN CMS_PERMEMP pe ON pe.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_CONTEMP ce ON ce.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_OCEEMP oe ON oe.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_ACCKEY ak ON ak.CUSTOMERID = c.CUSTOMERID AND ak.STATUSID = 10
    WHERE c.STATUSID = 10;

    -- RS-2: Wallets
    SELECT 
        w.CUSTOMERID AS customerId,
        w.BALANCE AS balance,
        w.STATUSID AS statusId
    FROM CMS_WALLET w
    JOIN CMS_CUSTOMER c ON c.CUSTOMERID = w.CUSTOMERID
    WHERE w.STATUSID = 10;

    -- RS-3: Day Slots
    SELECT 
        DS.DAYSLOTID AS daySlotId,
        DS.CANTEENID AS canteenId,
        DS.SERVICEID AS serviceId,
        S.SERVNAME AS serviceName,
        DATE_FORMAT(DS.SERVICEDATE, '%Y-%m-%d') AS servDate,
        DS.STARTTIME AS startTime,
        DS.ENDTIME AS endTime
    FROM CMS_DAYSLOT DS
    JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
    WHERE DS.CANTEENID = VCANTEENID
      AND DS.SERVICEDATE > PTODAY
      AND DS.STATUSID = 10
    ORDER BY DS.SERVICEDATE ASC, DS.STARTTIME ASC;

    -- RS-4: Menu Items
    SELECT 
        DM.DAYMENUID AS dayMenuId,
        DM.DAYSLOTID AS daySlotId,
        DM.MENUITEMID AS menuItemId,
        MI.ITEMNAME AS itemName,
        COALESCE(
          (SELECT IPD.PRICE 
           FROM CMS_ITEMPRICE IP
           JOIN CMS_ITMPRICDT IPD ON IPD.ITEMPRICEID = IP.ITEMPRICEID
           WHERE IP.MENUITEMID = MI.MENUITEMID 
             AND IP.STATUSID = 10 
             AND IP.EFFFROM <= DS.SERVICEDATE
           ORDER BY IP.EFFFROM DESC 
           LIMIT 1),
          0.00
        ) AS rate,
        DM.ISBASE AS isBase,
        DM.ISSPECIAL AS isSpecial,
        DM.MAXQTY AS maxQty,
        DM.BOOKUNTIL AS bookUntil
    FROM CMS_DAYMENU DM
    JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    WHERE DS.CANTEENID = VCANTEENID
      AND DS.SERVICEDATE > PTODAY
      AND DS.STATUSID = 10
      AND DM.ISKIOSK = 1
      AND DM.STATUSID = 10;

    -- RS-5: Active Bookings
    SELECT 
        B.CUSTOMERID AS customerId,
        B.SERVICEID AS serviceId,
        DATE_FORMAT(B.SERVICEDATE, '%Y-%m-%d') AS servDate,
        B.BOOKID AS bookId,
        B.BOOKNO AS tokenNo
    FROM CMS_BOOKING B
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    JOIN CMS_DAYSLOT DS ON DS.SERVICEID = B.SERVICEID AND DS.SERVICEDATE = B.SERVICEDATE AND DS.CANTEENID = VCANTEENID
    WHERE B.SERVICEDATE > PTODAY
      AND ST.STATUSCODE <> 'CAN'
      AND B.STATUSID = 10;

    -- RS-6: Today's Bookings
    SELECT 
        B.BOOKID AS bookId,
        B.BOOKNO AS bookNo,
        B.CUSTOMERID AS customerId,
        COALESCE(PE.EMPCODE, CE.CONTCODE, OE.EMPCODE, U.LOGINID, CAST(B.CUSTOMERID AS CHAR)) AS loginId,
        COALESCE((SELECT AK.KEYVALUE FROM CMS_ACCKEY AK WHERE AK.CUSTOMERID = C.CUSTOMERID AND AK.STATUSID = 10 ORDER BY AK.ACCKEYID DESC LIMIT 1), '') AS rfidUid,
        C.DISPNAME AS dispName,
        CT.CTYPECODE AS ctypeCode,
        B.SERVICEID AS serviceId,
        DS.DAYSLOTID AS daySlotId,
        S.SERVNAME AS slotName,
        ST.STATUSCODE AS statusCode,
        B.SERVEDBY AS servedBy,
        B.SERVEDAT AS servedOn,
        B.TOTALAMOUNT AS totalAmount
    FROM CMS_BOOKING B
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    JOIN CMS_CUSTTYPE CT ON CT.CTYPEID = C.CTYPEID
    LEFT JOIN CMS_USER U ON U.USERID = C.USERID
    LEFT JOIN CMS_PERMEMP PE ON PE.CUSTOMERID = C.CUSTOMERID
    LEFT JOIN CMS_CONTEMP CE ON CE.CUSTOMERID = C.CUSTOMERID
    LEFT JOIN CMS_OCEEMP OE ON OE.CUSTOMERID = C.CUSTOMERID
    JOIN CMS_DAYSLOT DS ON DS.SERVICEID = B.SERVICEID AND DS.SERVICEDATE = B.SERVICEDATE AND DS.CANTEENID = VCANTEENID
    JOIN CMS_SERVICE S ON S.SERVICEID = DS.SERVICEID
    WHERE B.SERVICEDATE = PTODAY
      AND ST.STATUSCODE IN ('CRT', 'SRV')
    ORDER BY B.BOOKID DESC;

    -- RS-7: Today's Booking Items
    SELECT 
        BI.BOOKITEMID AS bookItemId,
        BI.BOOKID AS bookId,
        BI.MENUITEMID AS menuItemId,
        MI.ITEMNAME AS itemName,
        BI.QTY AS qty,
        BI.RATE AS rate
    FROM CMS_BOOKITEM BI
    JOIN CMS_BOOKING B ON B.BOOKID = BI.BOOKID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = BI.MENUITEMID
    JOIN CMS_DAYSLOT DS ON DS.SERVICEID = B.SERVICEID AND DS.SERVICEDATE = B.SERVICEDATE AND DS.CANTEENID = VCANTEENID
    WHERE B.SERVICEDATE = PTODAY
      AND ST.STATUSCODE IN ('CRT', 'SRV');
END$$

