USE cms_db;

DROP PROCEDURE IF EXISTS CMSREGISTERKIOSKDEVICE;
DROP PROCEDURE IF EXISTS CMSHEARTBEATKIOSK;
DROP PROCEDURE IF EXISTS CMSKIOSKSERVEBOOKING;

DELIMITER $$

/* ============================================================
   CMSREGISTERKIOSKDEVICE
   Upserts hardware kiosk record for physical terminals
   ============================================================ */
CREATE PROCEDURE CMSREGISTERKIOSKDEVICE (
    IN PDEVICECODE VARCHAR(30),
    IN PDEVICENAME VARCHAR(100),
    IN PIPADDRESS  VARCHAR(45),
    IN PMACADDRESS VARCHAR(17),
    IN PCANTEENID  INT,
    IN PKIOSKTYPE  VARCHAR(30),
    IN PUSERID     INT
)
BEGIN
    DECLARE VCANTEENSTATUSID INT;
    DECLARE VKIOSKID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PDEVICECODE IS NULL OR TRIM(PDEVICECODE) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Device code is required';
    END IF;
    IF PIPADDRESS IS NULL OR TRIM(PIPADDRESS) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Static IP address is required';
    END IF;
    IF PCANTEENID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Canteen facility ID is required';
    END IF;
    IF PKIOSKTYPE NOT IN ('STAFF_COUNTER', 'EMP_SELF_SERVICE') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid Kiosk Type. Must be STAFF_COUNTER or EMP_SELF_SERVICE';
    END IF;

    SELECT STATUSID INTO VCANTEENSTATUSID FROM CMS_CANTEEN WHERE CANTEENID = PCANTEENID;
    IF VCANTEENSTATUSID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Target canteen facility not found';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_KIOSK_DEVICE (
        DEVICECODE, DEVICENAME, IPADDRESS, MACADDRESS, CANTEENID, KIOSKTYPE, STATUSID, ISACTIVE, CREATEDBY
    ) VALUES (
        TRIM(PDEVICECODE),
        TRIM(PDEVICENAME),
        TRIM(PIPADDRESS),
        TRIM(PMACADDRESS),
        PCANTEENID,
        PKIOSKTYPE,
        10,
        1,
        PUSERID
    )
    ON DUPLICATE KEY UPDATE
        DEVICENAME = VALUES(DEVICENAME),
        IPADDRESS = VALUES(IPADDRESS),
        MACADDRESS = VALUES(MACADDRESS),
        CANTEENID = VALUES(CANTEENID),
        KIOSKTYPE = VALUES(KIOSKTYPE),
        UPDATEDBY = PUSERID,
        UPDATEDAT = CURRENT_TIMESTAMP;

    SELECT KIOSKID INTO VKIOSKID FROM CMS_KIOSK_DEVICE WHERE DEVICECODE = TRIM(PDEVICECODE);

    COMMIT;

    SELECT VKIOSKID AS KIOSKID, 'SUCCESS' AS RESULT;
END$$


/* ============================================================
   CMSHEARTBEATKIOSK
   Updates telemetry timestamp and last seen IP for a kiosk
   ============================================================ */
CREATE PROCEDURE CMSHEARTBEATKIOSK (
    IN PKIOSKID   INT,
    IN PIPADDRESS VARCHAR(45)
)
BEGIN
    UPDATE CMS_KIOSK_DEVICE
    SET LASTHEARTBEATAT = CURRENT_TIMESTAMP,
        LASTSEENIP = COALESCE(PIPADDRESS, LASTSEENIP)
    WHERE KIOSKID = PKIOSKID;

    SELECT PKIOSKID AS KIOSKID, 'HEARTBEAT_ACK' AS STATUS;
END$$


/* ============================================================
   CMSKIOSKSERVEBOOKING
   Atomically marks booking as served, attributing staff user & physical kiosk.
   Includes built-in idempotency (returns ALREADY_SERVED = 1).
   ============================================================ */
CREATE PROCEDURE CMSKIOSKSERVEBOOKING (
    IN PBOOKID  INT,
    IN PUSERID  INT,
    IN PKIOSKID INT
)
BEGIN
    DECLARE VSTATUSID     INT;
    DECLARE VBOOKHISTID   INT;
    DECLARE VCUSTOMERID   INT;
    DECLARE VCTYPECODE    VARCHAR(10);
    DECLARE VTOTALAMOUNT  DECIMAL(12,2);
    DECLARE VSERVICEDATE  DATE;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION 
    BEGIN 
        ROLLBACK; 
        RESIGNAL; 
    END;

    IF PBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking ID is required';
    END IF;

    -- Check current status
    SELECT B.STATUSID, B.CUSTOMERID, C.CTYPECODE, B.TOTALAMOUNT, B.SERVICEDATE
    INTO VSTATUSID, VCUSTOMERID, VCTYPECODE, VTOTALAMOUNT, VSERVICEDATE
    FROM CMS_BOOKING B
    JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    WHERE B.BOOKID = PBOOKID;

    IF VSTATUSID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking not found';
    END IF;

    -- Idempotent check: if already served (32 = 'SRV'), acknowledge cleanly
    IF VSTATUSID = 32 THEN
        SELECT PBOOKID AS BOOKID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 1 AS ALREADY_SERVED;
    ELSEIF VSTATUSID = 33 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot serve a cancelled booking';
    ELSEIF VSERVICEDATE > CURDATE() THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot serve a future booking before its scheduled service date';
    ELSE
        START TRANSACTION;

        -- Record Audit History
        INSERT INTO CMS_BOOKHIST (
            BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
            STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
            BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
            KIOSKID,
            REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, CHANGEDBY, CHGREASON
        )
        SELECT
            BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
            STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
            BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
            PKIOSKID,
            REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, PUSERID, 'Served at Kiosk'
        FROM CMS_BOOKING
        WHERE BOOKID = PBOOKID;

        SET VBOOKHISTID = LAST_INSERT_ID();

        INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
        SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
        FROM CMS_BOOKITEM
        WHERE BOOKID = PBOOKID;

        -- 32 = 'SRV' (Served)
        UPDATE CMS_BOOKING
        SET STATUSID = 32,
            SERVEDBY = PUSERID,
            SERVEDON = CURRENT_TIMESTAMP,
            KIOSKID = COALESCE(PKIOSKID, KIOSKID),
            UPDATEDBY = PUSERID,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKID = PBOOKID;

        UPDATE CMS_BOOKITEM
        SET STATUSID = 32,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKID = PBOOKID AND STATUSID = 30;

        DELETE FROM CMS_PBACTIVE WHERE BOOKID = PBOOKID;

        COMMIT;

        SELECT PBOOKID AS BOOKID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 0 AS ALREADY_SERVED;
    END IF;
END$$

DELIMITER ;
