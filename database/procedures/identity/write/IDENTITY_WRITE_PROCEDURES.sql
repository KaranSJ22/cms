CREATE PROCEDURE CMSADDCUST (
    IN PUSERID     INT,
    IN PCTYPECODE  VARCHAR(20),
    IN PDISPNAME   VARCHAR(120),
    IN PSTATUSCODE VARCHAR(20),
    IN PVALIDFROM  DATETIME,
    IN PVALIDUNTIL DATETIME
)
BEGIN
    DECLARE VCUSTOMERID INT;
    DECLARE VCTYPE INT DEFAULT 0;
    DECLARE VSTATUSID INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PCTYPECODE IS NULL OR TRIM(PCTYPECODE) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer Type Code is required';
    END IF;
    IF PDISPNAME IS NULL OR TRIM(PDISPNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Display Name is required';
    END IF;

    SELECT COUNT(*) INTO VCTYPE FROM CMS_CUSTTYPE WHERE CTYPECODE = PCTYPECODE AND ISACTIVE = 1;
    IF VCTYPE = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid or inactive Customer Type Code';
    END IF;

    IF PSTATUSCODE IS NOT NULL AND TRIM(PSTATUSCODE) <> '' THEN
        IF PSTATUSCODE IN ('A', 'ACT') THEN
            SET VSTATUSID = 10;
        ELSEIF PSTATUSCODE IN ('I', 'INACT') THEN
            SET VSTATUSID = 11;
        ELSEIF PSTATUSCODE IN ('B', 'BLK') THEN
            SET VSTATUSID = 12;
        ELSEIF PSTATUSCODE IN ('S', 'SUSP') THEN
            SET VSTATUSID = 13;
        ELSE
            SELECT STATUSID INTO VSTATUSID FROM CMS_STATUS WHERE STATUSCODE = PSTATUSCODE AND STATUSGRP = 'SYS';
            IF VSTATUSID IS NULL THEN
                SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid Status Code';
            END IF;
        END IF;
    ELSE
        SET VSTATUSID = 10;
    END IF;

    START TRANSACTION;
    INSERT INTO CMS_CUSTOMER (USERID, CTYPECODE, DISPNAME, STATUSID, VALIDFROM, VALIDUNTIL)
    VALUES (PUSERID, TRIM(PCTYPECODE), TRIM(PDISPNAME), VSTATUSID, PVALIDFROM, PVALIDUNTIL);
    SET VCUSTOMERID = LAST_INSERT_ID();
    COMMIT;

    SELECT VCUSTOMERID AS CUSTOMERID;
END$$


