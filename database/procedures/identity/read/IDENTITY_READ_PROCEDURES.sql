CREATE PROCEDURE CMSGETUSER (IN PUSERID INT)
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  U.USERID = PUSERID;
END$$


CREATE PROCEDURE CMSLISTUSER (
    IN PISACTIVE TINYINT
)
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  (PISACTIVE IS NULL OR U.ISACTIVE = PISACTIVE)
    ORDER BY U.FULLNAME;
END$$


CREATE PROCEDURE CMSSEARCHUSER (IN PKEYWORD VARCHAR(120))
BEGIN
    SELECT U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
           U.AUTHPROV, U.ISACTIVE, U.CREATEDAT, U.UPDATEDAT
    FROM   CMS_USER U
    WHERE  (U.LOGINID  LIKE CONCAT('%', PKEYWORD, '%')
       OR   U.FULLNAME LIKE CONCAT('%', PKEYWORD, '%')
       OR   U.EMAIL    LIKE CONCAT('%', PKEYWORD, '%'))
    ORDER BY U.FULLNAME;
END$$


CREATE PROCEDURE CMSLOGININFO (
    IN PLOGINID VARCHAR(50)
)
BEGIN
    DECLARE VUSERID INT DEFAULT NULL;

    SELECT USERID
      INTO VUSERID
    FROM CMS_USER
    WHERE LOGINID = PLOGINID
      AND ISACTIVE = 1
    LIMIT 1;

    -- Result Set 1: User + Customer Information
    SELECT
        U.USERID,
        U.LOGINID,
        U.FULLNAME,
        U.EMAIL,
        U.MOBILENO,
        U.PWDHASH,
        U.AUTHPROV,
        U.AUTHID,
        U.ISACTIVE,
        C.CUSTOMERID,
        C.CTYPECODE,
        C.DISPNAME,
        C.STATUSID AS CUSTOMERSTATUS,
        CE.DEFAULTCANTEENID
    FROM CMS_USER U
    LEFT JOIN CMS_CUSTOMER C ON C.USERID = U.USERID
    LEFT JOIN CMS_CONTEMP CE ON CE.CUSTOMERID = C.CUSTOMERID
    WHERE U.USERID = VUSERID;

    -- Result Set 2: Consumer Roles
    IF VUSERID IS NOT NULL THEN
        SELECT
            CR.USRROLEID,
            CR.ROLEID,
            R.ROLECODE,
            R.ROLENAME
        FROM CMS_CONSUMERROLE CR
        INNER JOIN CMS_ROLE R ON R.ROLEID = CR.ROLEID
        WHERE CR.USERID = VUSERID
          AND CR.ISACTIVE = 1
          AND R.ISACTIVE = 1
          AND (CR.VALIDFROM IS NULL OR CURRENT_TIMESTAMP >= CR.VALIDFROM)
          AND (CR.VALIDUNTIL IS NULL OR CURRENT_TIMESTAMP <= CR.VALIDUNTIL)
        ORDER BY R.ROLECODE;
    END IF;

    -- Result Set 3: Canteen Roles
    IF VUSERID IS NOT NULL THEN
        SELECT
            CR.USRCANROLEID,
            CR.CANTEENID,
            CN.CANTEENCODE,
            CN.CANTEENNAME,
            CR.ROLEID,
            R.ROLECODE,
            R.ROLENAME,
            CR.ISDEFAULT
        FROM CMS_CANTEENROLE CR
        INNER JOIN CMS_CANTEEN CN ON CN.CANTEENID = CR.CANTEENID
        INNER JOIN CMS_ROLE R ON R.ROLEID = CR.ROLEID
        WHERE CR.USERID = VUSERID
          AND CR.ISACTIVE = 1
          AND R.ISACTIVE = 1
          AND (CR.VALIDFROM IS NULL OR CURRENT_TIMESTAMP >= CR.VALIDFROM)
          AND (CR.VALIDUNTIL IS NULL OR CURRENT_TIMESTAMP <= CR.VALIDUNTIL)
        ORDER BY CR.ISDEFAULT DESC, CN.CANTEENNAME;
    END IF;
END$$


