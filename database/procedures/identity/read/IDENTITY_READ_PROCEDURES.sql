CREATE PROCEDURE CMSLISTCANROL (IN PUSERID INT)
BEGIN
    SELECT CR.USRCANROLEID, CR.USERID, CR.ROLEID,
           R.ROLECODE, R.ROLENAME,
           CR.CANTEENID, C.CANTEENCODE, C.CANTEENNAME,
           CR.ISDEFAULT, CR.VALIDFROM, CR.VALIDUNTIL,
           CR.ISACTIVE, CR.ASSIGNEDBY, CR.ASSIGNEDAT
    FROM   CMS_CANTEENROLE CR
    JOIN   CMS_ROLE R    ON R.ROLEID     = CR.ROLEID
    JOIN   CMS_CANTEEN C ON C.CANTEENID  = CR.CANTEENID
    WHERE  CR.USERID = PUSERID
    ORDER BY C.CANTEENNAME, R.ROLECODE;
END$$


CREATE PROCEDURE CMSLISTCANROLSTAFF (IN PCANTEENID INT)
BEGIN
    SELECT CR.USRCANROLEID, CR.USERID, U.LOGINID, U.FULLNAME,
           CR.ROLEID, R.ROLECODE, R.ROLENAME,
           CR.ISDEFAULT, CR.VALIDFROM, CR.VALIDUNTIL,
           CR.ISACTIVE, CR.ASSIGNEDBY, CR.ASSIGNEDAT
    FROM   CMS_CANTEENROLE CR
    JOIN   CMS_USER U ON U.USERID = CR.USERID
    JOIN   CMS_ROLE R ON R.ROLEID = CR.ROLEID
    WHERE  CR.CANTEENID = PCANTEENID
      AND  CR.ISACTIVE  = 1
    ORDER BY U.FULLNAME, R.ROLECODE;
END$$


CREATE PROCEDURE CMSLISTCONSROL (IN PUSERID INT)
BEGIN
    SELECT CR.USRROLEID, CR.USERID, CR.ROLEID,
           R.ROLECODE, R.ROLENAME,
           CR.ASSIGNEDBY, CR.ASSIGNEDAT,
           CR.VALIDFROM, CR.VALIDUNTIL, CR.ISACTIVE
    FROM   CMS_CONSUMERROLE CR
    JOIN   CMS_ROLE R ON R.ROLEID = CR.ROLEID
    WHERE  CR.USERID = PUSERID
    ORDER BY R.ROLECODE;
