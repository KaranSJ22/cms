CREATE PROCEDURE CMSFINDCUSTBYIDENTIFIER (
    IN PIDENTIFIER VARCHAR(100)
)
BEGIN
    DECLARE VCLEANID VARCHAR(100);
    DECLARE VNUMERICID INT DEFAULT NULL;

    IF PIDENTIFIER IS NULL OR TRIM(PIDENTIFIER) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Search identifier is required';
    END IF;

    SET VCLEANID = TRIM(PIDENTIFIER);
    IF VCLEANID REGEXP '^[0-9]+$' THEN
        SET VNUMERICID = CAST(VCLEANID AS UNSIGNED);
    END IF;

    SELECT 
        c.CUSTOMERID,
        c.USERID,
        u.LOGINID,
        u.FULLNAME,
        u.EMAIL,
        u.MOBILENO,
        c.CTYPECODE,
        ct.CTYPENAME,
        c.DISPNAME,
        c.STATUSID,
        st.STATUSCODE,
        ce.CONTCODE,
        ce.VENDORNAME,
        pe.EMPCODE,
        pe.DEPT,
        pe.DESIG,
        ak.KEYVALUE AS RFID_UID,
        COALESCE(pe.EMPCODE, ce.CONTCODE, oe.EMPCODE, u.LOGINID, CAST(c.CUSTOMERID AS CHAR)) AS EMPLOYEE_ID,
        COALESCE(ce.CONTCODE, pe.EMPCODE, oe.EMPCODE, u.LOGINID) AS EMPLOYEE_CODE
    FROM CMS_CUSTOMER c
    LEFT JOIN CMS_USER u ON u.USERID = c.USERID
    LEFT JOIN CMS_CUSTTYPE ct ON ct.CTYPECODE = c.CTYPECODE
    LEFT JOIN CMS_STATUS st ON st.STATUSID = c.STATUSID
    LEFT JOIN CMS_CONTEMP ce ON ce.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_PERMEMP pe ON pe.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_OCEEMP oe ON oe.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN CMS_ACCKEY ak ON ak.CUSTOMERID = c.CUSTOMERID AND ak.STATUSID = 10
    WHERE LOWER(ce.CONTCODE) = LOWER(VCLEANID)
       OR LOWER(pe.EMPCODE) = LOWER(VCLEANID)
       OR LOWER(oe.EMPCODE) = LOWER(VCLEANID)
       OR LOWER(u.LOGINID) = LOWER(VCLEANID)
       OR ak.KEYVALUE = VCLEANID
       OR (VNUMERICID IS NOT NULL AND c.CUSTOMERID = VNUMERICID)
    LIMIT 1;
END$$


