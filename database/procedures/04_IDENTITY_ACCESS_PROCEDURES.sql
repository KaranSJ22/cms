DELIMITER $$

CREATE PROCEDURE CMSADDUSER (
    IN PLOGINID VARCHAR(50),
    IN PFULLNAME VARCHAR(120),
    IN PEMAIL VARCHAR(120),
    IN PMOBILENO VARCHAR(20),
    IN PPWDHASH VARCHAR(255),
    IN PAUTHPROV VARCHAR(20),
    IN PAUTHID VARCHAR(120)
)
BEGIN
    INSERT INTO CMS_USER (LOGINID, FULLNAME, EMAIL, MOBILENO, PWDHASH, AUTHPROV, AUTHID)
    VALUES (PLOGINID, PFULLNAME, PEMAIL, PMOBILENO, PPWDHASH, COALESCE(PAUTHPROV, 'LOCAL'), PAUTHID);

    SELECT LAST_INSERT_ID() AS USERID;
END$$

CREATE PROCEDURE CMSADDROLE (
    IN PROLECODE VARCHAR(50),
    IN PROLENAME VARCHAR(100),
    IN PDESCR VARCHAR(255)
)
BEGIN
    INSERT INTO CMS_ROLE (ROLECODE, ROLENAME, DESCR)
    VALUES (PROLECODE, PROLENAME, PDESCR);

    SELECT LAST_INSERT_ID() AS ROLEID;
END$$

CREATE PROCEDURE CMSASSIGNROL (
    IN PUSERID INT,
    IN PROLEID INT,
    IN PASSIGNEDBY INT,
    IN PVALIDFROM DATETIME,
    IN PVALIDUNTIL DATETIME
)
BEGIN
    INSERT INTO CMS_USRROLE (USERID, ROLEID, ASSIGNEDBY, VALIDFROM, VALIDUNTIL, ISACTIVE)
    VALUES (PUSERID, PROLEID, PASSIGNEDBY, COALESCE(PVALIDFROM, CURRENT_TIMESTAMP), PVALIDUNTIL, 1)
    ON DUPLICATE KEY UPDATE
        ASSIGNEDBY = PASSIGNEDBY,
        VALIDFROM = COALESCE(PVALIDFROM, CURRENT_TIMESTAMP),
        VALIDUNTIL = PVALIDUNTIL,
        ISACTIVE = 1,
        ASSIGNEDAT = CURRENT_TIMESTAMP;
END$$

