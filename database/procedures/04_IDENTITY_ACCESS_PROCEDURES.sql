CREATE PROCEDURE CMSLOGININFO (
    IN PLOGINID VARCHAR(50)
)
BEGIN
    SELECT
        U.USERID,
        U.LOGINID,
        U.FULLNAME,
        U.EMAIL,
        U.MOBILENO,
        U.PWDHASH,
        U.AUTHPROV,
        U.ISACTIVE,
        C.CUSTOMERID,
        C.CTYPECODE,
        C.DISPNAME,
        GROUP_CONCAT(R.ROLECODE ORDER BY R.ROLECODE) AS ROLECODES
    FROM CMS_USER U
    LEFT JOIN CMS_CUSTOMER C ON C.USERID = U.USERID
    LEFT JOIN CMS_USRROLE UR ON UR.USERID = U.USERID AND UR.ISACTIVE = 1
    LEFT JOIN CMS_ROLE R ON R.ROLEID = UR.ROLEID AND R.ISACTIVE = 1
    WHERE U.LOGINID = PLOGINID
    GROUP BY U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO, U.PWDHASH, U.AUTHPROV, U.ISACTIVE, C.CUSTOMERID, C.CTYPECODE, C.DISPNAME;
END$$

