/* ============================================================
   3. MEAL SERVICE QUERIES
   ============================================================ */

CREATE PROCEDURE CMSGETSERV (IN PSERVICEID INT)
BEGIN
    SELECT S.SERVICEID,
           S.SERVCODE, S.SERVNAME, S.DEFSTART, S.DEFEND,
           S.STATUSID, ST.STATUSCODE AS STATUSCODE, S.CREATEDBY, S.CREATEDAT, S.UPDATEDAT
    FROM   CMS_SERVICE S
    JOIN   CMS_STATUS ST ON ST.STATUSID = S.STATUSID
    WHERE  S.SERVICEID = PSERVICEID;
END$$

CREATE PROCEDURE CMSLISTSERV ()
BEGIN
    SELECT S.SERVICEID,
           S.SERVCODE, S.SERVNAME, S.DEFSTART, S.DEFEND,
           S.STATUSID, ST.STATUSCODE AS STATUSCODE, S.CREATEDBY, S.CREATEDAT, S.UPDATEDAT
    FROM   CMS_SERVICE S
    JOIN   CMS_STATUS ST ON ST.STATUSID = S.STATUSID
    ORDER BY S.DEFSTART;
END$$

CREATE PROCEDURE CMSSEARCHSERV (IN PKEYWORD VARCHAR(80))
BEGIN
    SELECT S.SERVICEID,
           S.SERVCODE, S.SERVNAME, S.STATUSID, ST.STATUSCODE AS STATUSCODE
    FROM   CMS_SERVICE S
    JOIN   CMS_STATUS ST ON ST.STATUSID = S.STATUSID
    WHERE  (S.SERVCODE LIKE CONCAT('%', PKEYWORD, '%')
       OR   S.SERVNAME LIKE CONCAT('%', PKEYWORD, '%'))
    ORDER BY S.SERVNAME;
END$$


/* ============================================================
   4. HOLIDAY QUERIES
   ============================================================ */

CREATE PROCEDURE CMSGETHOLIDAY (IN PHOLIDAYID INT)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE AS STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   CMS_HOLIDAY H
    JOIN   CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  H.HOLIDAYID = PHOLIDAYID;
END$$

CREATE PROCEDURE CMSLISTHOLIDAY (
    IN PYEAR INT
)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE AS STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   CMS_HOLIDAY H
    JOIN   CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  (PYEAR IS NULL OR YEAR(H.HOLIDAYDATE) = PYEAR OR H.ISRECURRING = 1)
    ORDER BY MONTH(H.HOLIDAYDATE), DAY(H.HOLIDAYDATE), YEAR(H.HOLIDAYDATE);
END$$

CREATE PROCEDURE CMSLISTHOLIDAYRANGE (
    IN PSTARTDATE DATE,
    IN PENDDATE   DATE
)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYNAME, DATE_FORMAT(H.HOLIDAYDATE, '%Y-%m-%d') AS HOLIDAYDATE, H.ISRECURRING
    FROM CMS_HOLIDAY H
    WHERE H.STATUSID = 10
      AND (
        (H.HOLIDAYDATE >= PSTARTDATE AND H.HOLIDAYDATE <= PENDDATE)
        OR H.ISRECURRING = 1
      )
    ORDER BY H.HOLIDAYDATE ASC;
END$$

DELIMITER ;
