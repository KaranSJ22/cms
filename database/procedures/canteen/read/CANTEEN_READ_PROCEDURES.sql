CREATE PROCEDURE CMSGETHOLIDAY (IN PHOLIDAYID INT)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE AS STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   CMS_HOLIDAY H
    JOIN   CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  H.HOLIDAYID = PHOLIDAYID;
END$$

CREATE PROCEDURE CMSLISTHOLIDAY (
    IN PYEAR INT
)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE AS STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   CMS_HOLIDAY H
    JOIN   CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  (PYEAR IS NULL OR YEAR(H.HOLIDAYDATE) = PYEAR OR H.ISRECURRING = 1)
    ORDER BY MONTH(H.HOLIDAYDATE), DAY(H.HOLIDAYDATE), YEAR(H.HOLIDAYDATE);
END$$

CREATE PROCEDURE CMSLISTHOLIDAYRANGE (
    IN PSTARTDATE DATE,
    IN PENDDATE   DATE
)
BEGIN
    SELECT H.HOLIDAYID, H.HOLIDAYNAME, DATE_FORMAT(H.HOLIDAYDATE, '%Y-%m-%d') AS HOLIDAYDATE, H.ISRECURRING
    FROM CMS_HOLIDAY H
    WHERE H.STATUSID = 10
      AND (
        (H.HOLIDAYDATE >= PSTARTDATE AND H.HOLIDAYDATE <= PENDDATE)
        OR H.ISRECURRING = 1
      )
    ORDER BY H.HOLIDAYDATE ASC;
END$$


/* ============================================================
   5. RESOURCE CANTEEN RESOLUTION
   ============================================================ */

CREATE PROCEDURE CMSGETRESOURCECANTEEN (
    IN PRESOURCETYPE VARCHAR(20),
    IN PRESOURCEID   INT
)
BEGIN
    IF PRESOURCETYPE = 'DAYSLOT' THEN
        SELECT DS.CANTEENID
        FROM CMS_DAYSLOT DS
        WHERE DS.DAYSLOTID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'DAYMENU' THEN
        SELECT DS.CANTEENID
        FROM CMS_DAYMENU DM
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        WHERE DM.DAYMENUID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'BOOKING' THEN
        SELECT DS.CANTEENID
        FROM CMS_BOOKITEM BI
        JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        WHERE BI.BOOKID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'OFFSERV' THEN
        SELECT os.CANTEENID
        FROM CMS_OFFSERV os
        WHERE os.OFFSERVID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'OFFCOMBO' THEN
        SELECT os.CANTEENID
        FROM CMS_OFFCOMBO oc
        JOIN CMS_OFFSERV os ON os.OFFSERVID = oc.OFFSERVID
        WHERE oc.OFFCOMBOID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'OFFBOOK' THEN
        SELECT ob.CANTEENID
        FROM CMS_OFFBOOK ob
        WHERE ob.OFFBOOKID = PRESOURCEID
        LIMIT 1;
    ELSEIF PRESOURCETYPE = 'WALLETWD' THEN
        SELECT COALESCE(
            CE.DEFAULTCANTEENID,
            (SELECT CANTEENID FROM CMS_CANTEEN WHERE STATUSID = 10 ORDER BY CANTEENID ASC LIMIT 1)
        ) AS CANTEENID
        FROM CMS_WALLETWD WD
        JOIN CMS_WALLET W ON W.WALLETID = WD.WALLETID
        LEFT JOIN CMS_CONTEMP CE ON CE.CUSTOMERID = W.CUSTOMERID
        WHERE WD.WALLETWDID = PRESOURCEID
        LIMIT 1;
    ELSE
        SELECT NULL AS CANTEENID WHERE 1 = 0;
    END IF;
END$$

