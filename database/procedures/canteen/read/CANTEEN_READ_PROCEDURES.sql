DROP PROCEDURE IF EXISTS CMSGETCENTER;
DROP PROCEDURE IF EXISTS CMSLISTCENTER;
DROP PROCEDURE IF EXISTS CMSSEARCHCENTER;
DROP PROCEDURE IF EXISTS CMSGETSERV;
