USE cms_db;
DROP PROCEDURE IF EXISTS CMSGETSTATUS;
DROP PROCEDURE IF EXISTS CMSLISTSTATUS;
DROP PROCEDURE IF EXISTS CMSLISTCUSTTYPE;
DROP PROCEDURE IF EXISTS CMSGETCUSTTYPE;
DROP PROCEDURE IF EXISTS CMSGETSCREEN;
DROP PROCEDURE IF EXISTS CMSLISTSCREEN;
DROP PROCEDURE IF EXISTS CMSGETROLESCN;
DROP PROCEDURE IF EXISTS CMSLISTROLESCN;
DROP PROCEDURE IF EXISTS CMSLISTAUTONO;

DELIMITER $$


CREATE PROCEDURE CMSGETSTATUS (
    IN PSTATUSID INT
)
BEGIN
    SELECT STATUSID, STATUSCODE, STATUSNAME, STATUSGRP,
           DESCR, ISACTIVE, CREATEDAT, UPDATEDAT
    FROM   CMS_STATUS
    WHERE  STATUSID = PSTATUSID;
END$$


CREATE PROCEDURE CMSGETCUSTTYPE (
    IN PCTYPEID INT
)
BEGIN
    SELECT CTYPEID, CTYPECODE, CTYPENAME, DESCR,
           ISACTIVE, CREATEDAT, UPDATEDAT
    FROM   CMS_CUSTTYPE
    WHERE  CTYPEID = PCTYPEID;
END$$

CREATE PROCEDURE CMSLISTSTATUS (
    IN PSTATUSGRP VARCHAR(30)
)
BEGIN
    SELECT STATUSID, STATUSCODE, STATUSNAME, STATUSGRP,
           DESCR, ISACTIVE, CREATEDAT, UPDATEDAT
    FROM   CMS_STATUS
    WHERE  (PSTATUSGRP IS NULL OR STATUSGRP = PSTATUSGRP)
    ORDER BY STATUSGRP, STATUSCODE;
END$$



CREATE PROCEDURE CMSLISTCUSTTYPE ()
BEGIN
    SELECT CTYPEID, CTYPECODE, CTYPENAME, DESCR,
           ISACTIVE, CREATEDAT, UPDATEDAT
    FROM   CMS_CUSTTYPE
    ORDER BY CTYPECODE;
END$$




CREATE PROCEDURE CMSGETSCREEN (
    IN PSCREENID INT
)
BEGIN
    SELECT SCREENID, SCREENCODE, SCREENNAME, DESCR,
           ROUTEPATH, ISACTIVE, CREATEDBY, CREATEDAT, UPDATEDAT
    FROM   CMS_SCREEN
    WHERE  SCREENID = PSCREENID;
END$$



CREATE PROCEDURE CMSLISTSCREEN ()
BEGIN
    SELECT SCREENID, SCREENCODE, SCREENNAME, DESCR,
           ROUTEPATH, ISACTIVE, CREATEDBY, CREATEDAT, UPDATEDAT
    FROM   CMS_SCREEN
    ORDER BY SCREENCODE;
END$$






CREATE PROCEDURE CMSGETROLESCN (
    IN PROLEID   INT,
    IN PSCREENID INT
)
BEGIN
    SELECT RS.ROLESCNID, RS.ROLEID, R.ROLECODE, R.ROLENAME,
           RS.SCREENID, SC.SCREENCODE, SC.SCREENNAME,
           RS.CANVIEW, RS.CANCREATE, RS.CANUPDATE, RS.CANDELETE,
           RS.ISACTIVE, RS.CREATEDAT, RS.UPDATEDAT
    FROM   CMS_ROLESCN RS
    JOIN   CMS_ROLE R    ON R.ROLEID   = RS.ROLEID
    JOIN   CMS_SCREEN SC ON SC.SCREENID = RS.SCREENID
    WHERE  RS.ROLEID   = PROLEID
      AND  RS.SCREENID = PSCREENID;
END$$




CREATE PROCEDURE CMSLISTAUTONO ()
BEGIN
    SELECT AUTONOID, TBLNAME, DATAITEM, ITEMLEN, FLDTYPE,
           PREFIXCHAR, STARTNO, STARTDATE, LASTNO, STATUS,
           CREATEDBY, CREATEDAT, UPDATEDAT
    FROM   CMS_AUTONOS
    ORDER BY TBLNAME, DATAITEM;
END$$



DELIMITER $$
