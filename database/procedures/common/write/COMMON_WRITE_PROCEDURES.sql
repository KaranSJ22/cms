/* ============================================================
   CMS_ROLESCN — Role-Screen Permission Mutations
   ============================================================ */

CREATE PROCEDURE CMSSETROLESCN (
    IN PROLEID    INT,
    IN PSCREENID  INT,
    IN PCANVIEW   TINYINT,
    IN PCANCREATE TINYINT,
    IN PCANUPDATE TINYINT,
    IN PCANDELETE TINYINT
)
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PROLEID IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Role ID is required';
    END IF;

    IF PSCREENID IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Screen ID is required';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_ROLESCN (ROLEID, SCREENID, CANVIEW, CANCREATE, CANUPDATE, CANDELETE)
    VALUES (PROLEID, PSCREENID,
            COALESCE(PCANVIEW, 0),
            COALESCE(PCANCREATE, 0),
            COALESCE(PCANUPDATE, 0),
            COALESCE(PCANDELETE, 0))
    ON DUPLICATE KEY UPDATE
        CANVIEW   = COALESCE(PCANVIEW, CANVIEW),
        CANCREATE = COALESCE(PCANCREATE, CANCREATE),
        CANUPDATE = COALESCE(PCANUPDATE, CANUPDATE),
        CANDELETE = COALESCE(PCANDELETE, CANDELETE),
        ISACTIVE  = 1,
        UPDATEDAT = CURRENT_TIMESTAMP;

    COMMIT;

    SELECT PROLEID AS ROLEID, PSCREENID AS SCREENID;
END$$

CREATE PROCEDURE CMSREMOVEROLESCN (
    IN PROLEID   INT,
    IN PSCREENID INT
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PROLEID IS NULL OR PSCREENID IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Role ID and Screen ID are required';
    END IF;

    SELECT COUNT(*) INTO VCOUNT
    FROM   CMS_ROLESCN
    WHERE  ROLEID   = PROLEID
      AND  SCREENID = PSCREENID;

    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Role-Screen mapping not found';
    END IF;

    START TRANSACTION;

    UPDATE CMS_ROLESCN
    SET    ISACTIVE  = 0,
           UPDATEDAT = CURRENT_TIMESTAMP
    WHERE  ROLEID   = PROLEID
      AND  SCREENID = PSCREENID;

    COMMIT;

    SELECT PROLEID AS ROLEID, PSCREENID AS SCREENID;
END$$

/* ============================================================
   CMS_AUTONOS — Auto-Number Configuration Mutations
   ============================================================ */

CREATE PROCEDURE CMSADDAUTONO (
    IN PTBLNAME    VARCHAR(50),
    IN PDATAITEM   VARCHAR(30),
    IN PITEMLEN    INT,
    IN PFLDTYPE    VARCHAR(10),
    IN PPREFIXCHAR VARCHAR(5),
    IN PSTARTNO    BIGINT,
    IN PCREATEDBY  INT
)
BEGIN
    DECLARE VAUTONOID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PTBLNAME IS NULL OR TRIM(PTBLNAME) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Table Name is required';
    END IF;

    IF PDATAITEM IS NULL OR TRIM(PDATAITEM) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Data Item is required';
    END IF;

    IF PPREFIXCHAR IS NULL OR TRIM(PPREFIXCHAR) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Prefix Character is required';
    END IF;

    IF PITEMLEN IS NULL OR PITEMLEN < 1 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Item Length must be at least 1';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_AUTONOS (
        TBLNAME, DATAITEM, ITEMLEN, FLDTYPE, PREFIXCHAR,
        STARTNO, STARTDATE, LASTNO, STATUS, CREATEDBY
    )
    VALUES (
        TRIM(PTBLNAME), TRIM(PDATAITEM), PITEMLEN,
        COALESCE(PFLDTYPE, 'CHAR'), TRIM(PPREFIXCHAR),
        COALESCE(PSTARTNO, 1), CURRENT_DATE, 0, 'A', PCREATEDBY
    );

    SET VAUTONOID = LAST_INSERT_ID();

    COMMIT;

    SELECT VAUTONOID AS AUTONOID;
END$$

CREATE PROCEDURE CMSUPDAUTONO (
    IN PAUTONOID   INT,
    IN PITEMLEN    INT,
    IN PPREFIXCHAR VARCHAR(5),
    IN PSTATUS     VARCHAR(10)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PAUTONOID IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Auto Number ID is required';
    END IF;

    SELECT COUNT(*) INTO VCOUNT
    FROM   CMS_AUTONOS
    WHERE  AUTONOID = PAUTONOID;

    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Auto Number configuration not found';
    END IF;

    START TRANSACTION;

    UPDATE CMS_AUTONOS
    SET    ITEMLEN    = COALESCE(PITEMLEN, ITEMLEN),
           PREFIXCHAR = COALESCE(PPREFIXCHAR, PREFIXCHAR),
           STATUS     = COALESCE(PSTATUS, STATUS),
           UPDATEDAT  = CURRENT_TIMESTAMP
    WHERE  AUTONOID   = PAUTONOID;

    COMMIT;

    SELECT PAUTONOID AS AUTONOID;
END$$

