/* ============================================================
   1. CMSOFFGENBOOKNO — Sequential Booking Number Generator
   Generates unique daily sequential number format:
   OBK-<CANTEENCODE>-<YYYYMMDD>-<0001>
   Locked via CMS_OFFBOOKCTR with safe CMS_OFFBOOK ceiling check.
   ============================================================ */
CREATE PROCEDURE CMSOFFGENBOOKNO (
    IN  PCANTEENID INT,
    OUT PBOOKNO    VARCHAR(35)
)
BEGIN
    DECLARE VCANTEENCODE VARCHAR(10);
    DECLARE VTODAYDATE   DATE;
    DECLARE VDATESTR     VARCHAR(8);
    DECLARE VPREFIX      VARCHAR(30);
    DECLARE VLASTNO      BIGINT DEFAULT 0;
    DECLARE VMAXSEQ      BIGINT DEFAULT 0;
    DECLARE VNEXTSEQ     BIGINT DEFAULT 1;

    SELECT COALESCE(CANTEENCODE, 'CAN') INTO VCANTEENCODE
    FROM CMS_CANTEEN
    WHERE CANTEENID = PCANTEENID;

    SET VTODAYDATE = CURRENT_DATE;
    SET VDATESTR = DATE_FORMAT(VTODAYDATE, '%Y%m%d');
    SET VPREFIX = CONCAT('OBK-', VCANTEENCODE, '-', VDATESTR, '-');

    -- Ensure counter record exists for (PCANTEENID, VTODAYDATE)
    INSERT INTO CMS_OFFBOOKCTR (CANTEENID, BOOKDATE, LASTNO)
    VALUES (PCANTEENID, VTODAYDATE, 0)
    ON DUPLICATE KEY UPDATE LASTNO = LASTNO;

    -- Lock counter record
    SELECT LASTNO INTO VLASTNO
    FROM CMS_OFFBOOKCTR
    WHERE CANTEENID = PCANTEENID AND BOOKDATE = VTODAYDATE
    FOR UPDATE;

    -- Max sequence check in CMS_OFFBOOK for safety
    SELECT COALESCE(MAX(CAST(SUBSTRING(BOOKNO, LENGTH(VPREFIX) + 1) AS UNSIGNED)), 0)
    INTO VMAXSEQ
    FROM CMS_OFFBOOK
    WHERE BOOKNO LIKE CONCAT(VPREFIX, '%');

    IF VLASTNO < VMAXSEQ THEN
        SET VNEXTSEQ = VMAXSEQ + 1;
    ELSE
        SET VNEXTSEQ = VLASTNO + 1;
    END IF;

    UPDATE CMS_OFFBOOKCTR
    SET LASTNO = VNEXTSEQ
    WHERE CANTEENID = PCANTEENID AND BOOKDATE = VTODAYDATE;

    SET PBOOKNO = CONCAT(VPREFIX, LPAD(VNEXTSEQ, 4, '0'));
END$$


/* ============================================================
   2. CMSOFFCREATESERVICE — Create Official Catering Service Header
   ============================================================ */
CREATE PROCEDURE CMSOFFCREATESERVICE (
    IN PCANTEENID   INT,
    IN PSERVNAME    VARCHAR(100),
    IN PDESCR       VARCHAR(500),
    IN PCUTOFFHOURS INT,
    IN PREQAPPRLVL  VARCHAR(10),
    IN PCREATEDBY   INT
)
BEGIN
    DECLARE VCUTOFF INT DEFAULT 24;
    DECLARE VAPPRLVL VARCHAR(10) DEFAULT 'L1';

    IF PCUTOFFHOURS IS NOT NULL AND PCUTOFFHOURS > 0 THEN
        SET VCUTOFF = PCUTOFFHOURS;
    END IF;

    IF PREQAPPRLVL IS NOT NULL AND PREQAPPRLVL IN ('L1', 'L2') THEN
        SET VAPPRLVL = PREQAPPRLVL;
    END IF;

    INSERT INTO CMS_OFFSERV (
        CANTEENID, SERVNAME, DESCR, CUTOFFHOURS, REQAPPRLVL, STATUSID, CREATEDBY
    ) VALUES (
        PCANTEENID, PSERVNAME, PDESCR, VCUTOFF, VAPPRLVL, 10, PCREATEDBY
    );

    SELECT LAST_INSERT_ID() AS OFFSERVID;
END$$


