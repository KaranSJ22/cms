/* ============================================================
   4. CMSOFFCREATECOMBO — Create Predefined Combo & Items
   ============================================================ */
CREATE PROCEDURE CMSOFFCREATECOMBO (
    IN POFFSERVID       INT,
    IN PCOMBONAME       VARCHAR(100),
    IN PDESCR           VARCHAR(255),
    IN PGROSSPRICE      DECIMAL(10,2),
    IN PHANDLINGCHARGE  DECIMAL(10,2),
    IN PCOMBOPRICE      DECIMAL(10,2),
    IN PITEMSJSON       JSON,
    IN PCREATEDBY       INT
)
BEGIN
    DECLARE VCOMBOID    INT;
    DECLARE VGROSS      DECIMAL(10,2);
    DECLARE VHANDLING   DECIMAL(10,2);
    DECLARE VPRICE      DECIMAL(10,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    SET VGROSS = COALESCE(PGROSSPRICE, PCOMBOPRICE, 0.00);
    SET VHANDLING = COALESCE(PHANDLINGCHARGE, 0.00);
    SET VPRICE = VGROSS + VHANDLING;

    START TRANSACTION;

    INSERT INTO CMS_OFFCOMBO (
        OFFSERVID, COMBONAME, DESCR, GROSSPRICE, HANDLINGCHARGE, COMBOPRICE, STATUSID, CREATEDBY
    ) VALUES (
        POFFSERVID, PCOMBONAME, PDESCR, VGROSS, VHANDLING, VPRICE, 10, PCREATEDBY
    );

    SET VCOMBOID = LAST_INSERT_ID();

    IF PITEMSJSON IS NOT NULL AND JSON_VALID(PITEMSJSON) AND JSON_LENGTH(PITEMSJSON) > 0 THEN
        INSERT INTO CMS_OFFCOMBDT (OFFCOMBOID, MENUITEMID, QTY)
        SELECT VCOMBOID, JT.MENUITEMID, COALESCE(JT.QTY, 1)
        FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
            MENUITEMID INT PATH '$.MENUITEMID',
            QTY INT PATH '$.QTY'
        )) AS JT;
    END IF;

    COMMIT;

    SELECT VCOMBOID AS OFFCOMBOID;
END$$


/* ============================================================
   5. CMSOFFUPDATECOMBO — Update Combo Pricing & Dish Items
   ============================================================ */
CREATE PROCEDURE CMSOFFUPDATECOMBO (
    IN POFFCOMBOID      INT,
    IN PCOMBONAME       VARCHAR(100),
    IN PDESCR           VARCHAR(255),
    IN PGROSSPRICE      DECIMAL(10,2),
    IN PHANDLINGCHARGE  DECIMAL(10,2),
    IN PCOMBOPRICE      DECIMAL(10,2),
    IN PSTATUSID        INT,
    IN PITEMSJSON       JSON,
    IN PUPDATEDBY       INT
)
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    UPDATE CMS_OFFCOMBO
    SET COMBONAME      = COALESCE(PCOMBONAME, COMBONAME),
        DESCR          = COALESCE(PDESCR, DESCR),
        GROSSPRICE     = COALESCE(PGROSSPRICE, GROSSPRICE),
        HANDLINGCHARGE = COALESCE(PHANDLINGCHARGE, HANDLINGCHARGE),
        COMBOPRICE     = COALESCE(PGROSSPRICE, GROSSPRICE) + COALESCE(PHANDLINGCHARGE, HANDLINGCHARGE),
        STATUSID       = COALESCE(PSTATUSID, STATUSID),
        UPDATEDBY      = PUPDATEDBY,
        UPDATEDAT      = CURRENT_TIMESTAMP
    WHERE OFFCOMBOID   = POFFCOMBOID;

    IF PITEMSJSON IS NOT NULL AND JSON_VALID(PITEMSJSON) THEN
        DELETE FROM CMS_OFFCOMBDT WHERE OFFCOMBOID = POFFCOMBOID;

        IF JSON_LENGTH(PITEMSJSON) > 0 THEN
            INSERT INTO CMS_OFFCOMBDT (OFFCOMBOID, MENUITEMID, QTY)
            SELECT POFFCOMBOID, JT.MENUITEMID, COALESCE(JT.QTY, 1)
            FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
                MENUITEMID INT PATH '$.MENUITEMID',
                QTY INT PATH '$.QTY'
            )) AS JT;
        END IF;
    END IF;

    COMMIT;

    SELECT POFFCOMBOID AS OFFCOMBOID;
END$$


/* ============================================================
   6. CMSOFFDELETECOMBO — Soft/Hard Delete Combo
   If bookings exist, soft-deletes (STATUSID = 11).
   If no bookings exist, hard-deletes combo and its mapped items.
   ============================================================ */
CREATE PROCEDURE CMSOFFDELETECOMBO (
    IN POFFCOMBOID INT,
    IN PUSERID     INT
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    SELECT COUNT(*) INTO VCOUNT
    FROM CMS_OFFBOOK
    WHERE OFFCOMBOID = POFFCOMBOID;

    IF VCOUNT > 0 THEN
        UPDATE CMS_OFFCOMBO
        SET STATUSID = 11, -- DISABLED
            UPDATEDBY = PUSERID,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE OFFCOMBOID = POFFCOMBOID;
    ELSE
        DELETE FROM CMS_OFFCOMBDT WHERE OFFCOMBOID = POFFCOMBOID;
        DELETE FROM CMS_OFFCOMBO WHERE OFFCOMBOID = POFFCOMBOID;
    END IF;

    COMMIT;

    SELECT 1 AS SUCCESS;
END$$


