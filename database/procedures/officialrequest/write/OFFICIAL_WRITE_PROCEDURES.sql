    FROM CMS_LVLMAP
    WHERE EMPLEVEL = PEMPLEVEL;
END$$


/* ============================================================
   8. CMSOFFCREATEBOOKING — Atomic Official Request Creation
   Performs:
     - PRM Customer check
     - Self-approval check
     - Active service & cutoff check
     - Approver level qualification check (L1/L2)
     - Price calculation: (Quantity * Gross) + Handling
     - Atomic sequential booking number generation
     - Initial audit trail in CMS_OFFAPPR
   ============================================================ */
CREATE PROCEDURE CMSOFFCREATEBOOKING (
    IN PCANTEENID     INT,
    IN POFFSERVID     INT,
    IN POFFCOMBOID    INT,
    IN PCUSTOMERID    INT,
    IN PBOOKEDBY      INT,
    IN PPURPOSE       VARCHAR(255),
    IN PVENUE         VARCHAR(255),
    IN PEVENTDATETIME DATETIME,
    IN PQUANTITY      INT,
    IN PNOOFPEOPLE    INT,
    IN PAPPRLVL       VARCHAR(10),
    IN PAPPROVERID    INT
)
BEGIN
    DECLARE VCTYPECODE VARCHAR(10);
    DECLARE VCUSTSTATUS INT;
    DECLARE VSERVNAME VARCHAR(100);
    DECLARE VCUTOFFHOURS INT;
    DECLARE VREQAPPRLVL VARCHAR(10);
    DECLARE VSERVSTATUS INT;
    DECLARE VAPPRLVL VARCHAR(10);
    DECLARE VCOMBONAME VARCHAR(100);
    DECLARE VGROSSPRICE DECIMAL(10,2);
    DECLARE VHANDLINGCHARGE DECIMAL(10,2);
    DECLARE VCOMBOPRICE DECIMAL(10,2);
    DECLARE VCOMBOSTATUS INT;
    DECLARE VTOTALAMOUNT DECIMAL(12,2);
    DECLARE VGROSSUNIT DECIMAL(10,2);
    DECLARE VBOOKNO VARCHAR(35);
    DECLARE VOFFBOOKID INT;
    DECLARE VLEADHOURS DECIMAL(10,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    -- 1. Permanent Employee Verification
    SELECT CTYPECODE, STATUSID INTO VCTYPECODE, VCUSTSTATUS
    FROM CMS_CUSTOMER
    WHERE CUSTOMERID = PCUSTOMERID;

    IF VCTYPECODE IS NULL OR VCTYPECODE != 'PRM' OR VCUSTSTATUS != 10 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Only active permanent employees can create Official Bookings';
    END IF;

    -- 2. Self-Approval Prevention
    IF PAPPROVERID = PBOOKEDBY THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Self-approval is not allowed. Please select another eligible approver.';
    END IF;

    -- 3. Check service, required approval level and cutoff
    SELECT SERVNAME, CUTOFFHOURS, REQAPPRLVL, STATUSID
    INTO VSERVNAME, VCUTOFFHOURS, VREQAPPRLVL, VSERVSTATUS
    FROM CMS_OFFSERV
    WHERE OFFSERVID = POFFSERVID;

    IF VSERVNAME IS NULL OR VSERVSTATUS != 10 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'The requested Official Service is not active or does not exist';
    END IF;

    -- Verify approver eligibility against service required level
    SELECT lm.APPRLVL INTO VAPPRLVL
    FROM CMS_USER u
    JOIN CMS_CUSTOMER c ON c.USERID = u.USERID
    JOIN CMS_PERMEMP pe ON pe.CUSTOMERID = c.CUSTOMERID
    JOIN CMS_LVLMAP lm ON lm.EMPLEVEL = pe.LEVEL AND lm.ISACTIVE = 1
    WHERE u.USERID = PAPPROVERID AND u.ISACTIVE = 1 AND c.STATUSID = 10;

    IF VAPPRLVL IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Selected approver is not mapped to an active approval level';
    END IF;

    IF VREQAPPRLVL = 'L2' AND VAPPRLVL != 'L2' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'This service requires Level 2 approval. You must select a Level 2 approver.';
    END IF;

    -- Cutoff validation
    SET VLEADHOURS = TIMESTAMPDIFF(MINUTE, CURRENT_TIMESTAMP, PEVENTDATETIME) / 60.0;
    IF VLEADHOURS < VCUTOFFHOURS THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Booking cutoff violation: The service notice time prior to event has expired.';
    END IF;

    -- 4. Validate combo and price calculation
    SELECT COMBONAME, GROSSPRICE, HANDLINGCHARGE, COMBOPRICE, STATUSID
    INTO VCOMBONAME, VGROSSPRICE, VHANDLINGCHARGE, VCOMBOPRICE, VCOMBOSTATUS
    FROM CMS_OFFCOMBO
    WHERE OFFCOMBOID = POFFCOMBOID AND OFFSERVID = POFFSERVID;

    IF VCOMBONAME IS NULL OR VCOMBOSTATUS != 10 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'The selected combo is not active or does not belong to this service';
    END IF;

    SET VGROSSUNIT = COALESCE(VGROSSPRICE, VCOMBOPRICE, 0.00);
    SET VHANDLINGCHARGE = COALESCE(VHANDLINGCHARGE, 0.00);
    SET VTOTALAMOUNT = ROUND((PQUANTITY * VGROSSUNIT) + VHANDLINGCHARGE, 2);

    START TRANSACTION;

    -- Generate sequential booking number
    CALL CMSOFFGENBOOKNO(PCANTEENID, VBOOKNO);

    INSERT INTO CMS_OFFBOOK (
        BOOKNO, CANTEENID, OFFSERVID, OFFCOMBOID, CUSTOMERID, BOOKEDBY,
        PURPOSE, VENUE, EVENTDATETIME, QUANTITY, NOOFPEOPLE,
        UNITPRICE, HANDLINGCHARGE, TOTALAMOUNT, APPRLVL, APPROVERID, STATUSID
    ) VALUES (
        VBOOKNO, PCANTEENID, POFFSERVID, POFFCOMBOID, PCUSTOMERID, PBOOKEDBY,
        PPURPOSE, PVENUE, PEVENTDATETIME, PQUANTITY, PNOOFPEOPLE,
        VGROSSUNIT, VHANDLINGCHARGE, VTOTALAMOUNT, COALESCE(PAPPRLVL, VAPPRLVL), PAPPROVERID, 35
    );

    SET VOFFBOOKID = LAST_INSERT_ID();

    -- Record initial submission audit
    INSERT INTO CMS_OFFAPPR (OFFBOOKID, ACTIONBY, ACTIONROLE, ACTION, REJREASON)
    VALUES (VOFFBOOKID, PBOOKEDBY, 'EMPLOYEE', 'SUBMITTED', NULL);

    COMMIT;

    SELECT 
        VOFFBOOKID AS OFFBOOKID,
        VBOOKNO AS BOOKNO,
        'Submitted' AS STATUS,
        VGROSSUNIT AS UNITPRICE,
        VHANDLINGCHARGE AS HANDLINGCHARGE,
        VTOTALAMOUNT AS TOTALAMOUNT;
END$$


/* ============================================================
   9. CMSOFFPROCESSAPPROVER — Approver Action (Approve / Reject)
   ============================================================ */
CREATE PROCEDURE CMSOFFPROCESSAPPROVER (
    IN PBOOKINGID       INT,
    IN PACTION          VARCHAR(20),
    IN PREJREASON       VARCHAR(500),
    IN PAPPROVERUSERID  INT
)
BEGIN
    DECLARE VCURRAPPROVER INT;
    DECLARE VCURRSTATUS   INT;
    DECLARE VNEXTSTATUS   INT;
    DECLARE VACTIONLABEL  VARCHAR(20);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    SELECT APPROVERID, STATUSID
    INTO VCURRAPPROVER, VCURRSTATUS
    FROM CMS_OFFBOOK
    WHERE OFFBOOKID = PBOOKINGID
    FOR UPDATE;

    IF VCURRAPPROVER IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Official Booking not found';
    END IF;

    IF VCURRAPPROVER != PAPPROVERUSERID THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'You are not the designated approver for this booking';
    END IF;

    IF VCURRSTATUS != 35 THEN -- Not SUBMITTED
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'This booking is no longer pending approver action';
    END IF;

    IF UPPER(PACTION) = 'APPROVE' THEN
        SET VNEXTSTATUS = 36; -- PENDING_MANAGER
        SET VACTIONLABEL = 'APPROVED';
    ELSEIF UPPER(PACTION) = 'REJECT' THEN
        SET VNEXTSTATUS = 38; -- REJECTED
        SET VACTIONLABEL = 'REJECTED';
    ELSE
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Invalid approver action. Expected APPROVE or REJECT';
    END IF;

    UPDATE CMS_OFFBOOK
    SET STATUSID = VNEXTSTATUS,
        UPDATEDBY = PAPPROVERUSERID,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE OFFBOOKID = PBOOKINGID;

    INSERT INTO CMS_OFFAPPR (OFFBOOKID, ACTIONBY, ACTIONROLE, ACTION, REJREASON)
    VALUES (PBOOKINGID, PAPPROVERUSERID, 'APPROVER', VACTIONLABEL, PREJREASON);

    COMMIT;

    SELECT 
        PBOOKINGID AS OFFBOOKID,
        VACTIONLABEL AS ACTION,
        VNEXTSTATUS AS STATUSID;
END$$


/* ============================================================
   10. CMSOFFPROCESSMANAGER — Canteen Manager Action (Accept / Reject)
   ============================================================ */
CREATE PROCEDURE CMSOFFPROCESSMANAGER (
    IN PBOOKINGID      INT,
    IN PACTION         VARCHAR(20),
    IN PREJREASON      VARCHAR(500),
    IN PMANAGERUSERID  INT
)
BEGIN
    DECLARE VCANTEENID   INT;
    DECLARE VCURRSTATUS  INT;
    DECLARE VNEXTSTATUS  INT;
    DECLARE VACTIONLABEL VARCHAR(20);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    SELECT CANTEENID, STATUSID
    INTO VCANTEENID, VCURRSTATUS
    FROM CMS_OFFBOOK
    WHERE OFFBOOKID = PBOOKINGID
    FOR UPDATE;

    IF VCANTEENID IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Official Booking not found';
    END IF;

    IF VCURRSTATUS != 36 THEN -- Not PENDING_MANAGER
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'This booking is not awaiting Canteen Manager confirmation';
    END IF;

    IF UPPER(PACTION) = 'ACCEPT' THEN
        SET VNEXTSTATUS = 37; -- CONFIRMED
        SET VACTIONLABEL = 'CONFIRMED';
    ELSEIF UPPER(PACTION) = 'REJECT' THEN
        SET VNEXTSTATUS = 38; -- REJECTED
        SET VACTIONLABEL = 'REJECTED';
    ELSE
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Invalid manager action. Expected ACCEPT or REJECT';
    END IF;

    UPDATE CMS_OFFBOOK
    SET STATUSID = VNEXTSTATUS,
        UPDATEDBY = PMANAGERUSERID,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE OFFBOOKID = PBOOKINGID;

    INSERT INTO CMS_OFFAPPR (OFFBOOKID, ACTIONBY, ACTIONROLE, ACTION, REJREASON)
    VALUES (PBOOKINGID, PMANAGERUSERID, 'CANTEEN_MANAGER', VACTIONLABEL, PREJREASON);

    COMMIT;

    SELECT 
        PBOOKINGID AS OFFBOOKID,
        VACTIONLABEL AS ACTION,
        VNEXTSTATUS AS STATUSID;
END$$


/* ============================================================
   11. CMSOFFRESUBMITBOOKING — Resubmit Rejected Official Booking
   ============================================================ */
CREATE PROCEDURE CMSOFFRESUBMITBOOKING (
    IN PBOOKINGID       INT,
    IN PUSERID          INT,
    IN POFFCOMBOID      INT,
    IN PPURPOSE         VARCHAR(255),
    IN PVENUE           VARCHAR(255),
    IN PEVENTDATETIME   DATETIME,
    IN PQUANTITY        INT,
    IN PNOOFPEOPLE      INT,
    IN PAPPROVERID      INT
)
BEGIN
    DECLARE VBOOKEDBY     INT;
    DECLARE VOFFSERVID    INT;
    DECLARE VCURRCOMBOID  INT;
    DECLARE VCURRQTY      INT;
    DECLARE VCURRSTATUS   INT;
    DECLARE VCUTOFFHOURS  INT;
    DECLARE VSERVNAME     VARCHAR(100);
    DECLARE VREQAPPRLVL   VARCHAR(10);
    DECLARE VTGTAPPROVER  INT;
    DECLARE VTGTCOMBO     INT;
    DECLARE VTGTQTY       INT;
    DECLARE VTGTEVENTTIME DATETIME;
    DECLARE VAPPRLVL      VARCHAR(10);
    DECLARE VGROSSPRICE   DECIMAL(10,2);
    DECLARE VHANDLING     DECIMAL(10,2);
    DECLARE VCOMBOPRICE   DECIMAL(10,2);
    DECLARE VTOTALAMOUNT  DECIMAL(12,2);
    DECLARE VGROSSUNIT    DECIMAL(10,2);
    DECLARE VLEADHOURS    DECIMAL(10,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    SELECT 
        ob.BOOKEDBY, ob.OFFSERVID, ob.OFFCOMBOID, ob.QUANTITY, ob.EVENTDATETIME, ob.APPROVERID, ob.STATUSID,
        os.CUTOFFHOURS, os.SERVNAME, os.REQAPPRLVL
    INTO 
        VBOOKEDBY, VOFFSERVID, VCURRCOMBOID, VCURRQTY, VTGTEVENTTIME, VTGTAPPROVER, VCURRSTATUS,
        VCUTOFFHOURS, VSERVNAME, VREQAPPRLVL
    FROM CMS_OFFBOOK ob
    JOIN CMS_OFFSERV os ON os.OFFSERVID = ob.OFFSERVID
    WHERE ob.OFFBOOKID = PBOOKINGID
    FOR UPDATE;

    IF VBOOKEDBY IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Official Booking not found';
    END IF;

    IF VBOOKEDBY != PUSERID THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'You can only resubmit your own bookings';
    END IF;

    IF VCURRSTATUS != 38 THEN -- Not REJECTED
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Only rejected bookings can be modified and resubmitted';
    END IF;

    -- Targets or fallbacks
    SET VTGTAPPROVER = COALESCE(PAPPROVERID, VTGTAPPROVER);
    SET VTGTCOMBO = COALESCE(POFFCOMBOID, VCURRCOMBOID);
    SET VTGTQTY = COALESCE(PQUANTITY, VCURRQTY);
    IF PEVENTDATETIME IS NOT NULL THEN
        SET VTGTEVENTTIME = PEVENTDATETIME;
    END IF;

    -- Self approval prevention
    IF VTGTAPPROVER = PUSERID THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Self-approval is not allowed. Please select another eligible approver.';
    END IF;

    -- Approver tier validation
    SELECT lm.APPRLVL INTO VAPPRLVL
    FROM CMS_USER u
    JOIN CMS_CUSTOMER c ON c.USERID = u.USERID
    JOIN CMS_PERMEMP pe ON pe.CUSTOMERID = c.CUSTOMERID
    JOIN CMS_LVLMAP lm ON lm.EMPLEVEL = pe.LEVEL AND lm.ISACTIVE = 1
    WHERE u.USERID = VTGTAPPROVER AND u.ISACTIVE = 1 AND c.STATUSID = 10;

    IF VAPPRLVL IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Selected approver is not mapped to an active approval level';
    END IF;

    IF VREQAPPRLVL = 'L2' AND VAPPRLVL != 'L2' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'This service requires Level 2 approval. You must select a Level 2 approver.';
    END IF;

    -- Cutoff validation
    SET VLEADHOURS = TIMESTAMPDIFF(MINUTE, CURRENT_TIMESTAMP, VTGTEVENTTIME) / 60.0;
    IF VLEADHOURS < VCUTOFFHOURS THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Booking cutoff violation: The service notice time prior to event has expired.';
    END IF;

    -- Price recalculation
    SELECT GROSSPRICE, HANDLINGCHARGE, COMBOPRICE
    INTO VGROSSPRICE, VHANDLING, VCOMBOPRICE
    FROM CMS_OFFCOMBO
    WHERE OFFCOMBOID = VTGTCOMBO;

    SET VGROSSUNIT = COALESCE(VGROSSPRICE, VCOMBOPRICE, 0.00);
    SET VHANDLING = COALESCE(VHANDLING, 0.00);
    SET VTOTALAMOUNT = ROUND((VTGTQTY * VGROSSUNIT) + VHANDLING, 2);

    UPDATE CMS_OFFBOOK
    SET OFFCOMBOID     = VTGTCOMBO,
        PURPOSE        = COALESCE(PPURPOSE, PURPOSE),
        VENUE          = COALESCE(PVENUE, VENUE),
        EVENTDATETIME  = VTGTEVENTTIME,
        QUANTITY       = VTGTQTY,
        NOOFPEOPLE     = COALESCE(PNOOFPEOPLE, NOOFPEOPLE),
        UNITPRICE      = VGROSSUNIT,
        HANDLINGCHARGE = VHANDLING,
        TOTALAMOUNT    = VTOTALAMOUNT,
        APPRLVL        = VAPPRLVL,
        APPROVERID     = VTGTAPPROVER,
        STATUSID       = 35, -- SUBMITTED
        UPDATEDBY      = PUSERID,
        UPDATEDAT      = CURRENT_TIMESTAMP
    WHERE OFFBOOKID    = PBOOKINGID;

    INSERT INTO CMS_OFFAPPR (OFFBOOKID, ACTIONBY, ACTIONROLE, ACTION, REJREASON)
    VALUES (PBOOKINGID, PUSERID, 'EMPLOYEE', 'RESUBMITTED', 'Request modified and resubmitted');

    COMMIT;

    SELECT 
        PBOOKINGID AS OFFBOOKID,
        35 AS STATUSID,
        'Submitted' AS STATUS,
        VGROSSUNIT AS UNITPRICE,
        VHANDLING AS HANDLINGCHARGE,
        VTOTALAMOUNT AS TOTALAMOUNT;
END$$

