    FOR UPDATE;

    IF VCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking not found';
    END IF;

    IF VSTATUSCODE <> 'CRT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only confirmed bookings in CRT status can be edited';
    END IF;

    SELECT DM.MENUITEMID, MI.ITEMNAME, DM.BOOKUNTIL, DM.MAXQTY, DM.AVAILQTY, DS.SERVICEID, DS.SERVDATE, DS.CANTEENID
      INTO VMENUITEMID, VITEMNAME, VBOOKUNTIL, VMAXQTY, VAVAILQTY, VSLOTID, VSLOTSERVDATE, VCANTEENID
    FROM CMS_DAYMENU DM
    JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    WHERE DM.DAYMENUID = PDAYMENUID;

    IF VMENUITEMID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Day menu item not found';
    END IF;

    IF CURRENT_TIMESTAMP > VBOOKUNTIL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking window has closed for this item';
    END IF;

    -- Check Capacity
    SELECT COALESCE(SUM(BI.QTY), 0) INTO VBOOKEDQTY
    FROM CMS_BOOKITEM BI
    JOIN CMS_STATUS BIST ON BIST.STATUSID = BI.STATUSID
    WHERE BI.DAYMENUID = PDAYMENUID AND BIST.STATUSCODE IN ('CRT', 'SRV', 'NOS');

    IF (VBOOKEDQTY + PQTY) > VMAXQTY THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Requested quantity exceeds kitchen preparation capacity';
    END IF;

    -- Resolve Price
    SELECT d.PRICE INTO VRATE
    FROM CMS_ITEMPRICE p
    JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
    JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
    WHERE p.MENUITEMID = VMENUITEMID
      AND d.CTYPECODE = VCTYPECODE
      AND p.EFFFROM <= VSERVICEDATE
      AND IP_ST.STATUSCODE = 'ACT'
    ORDER BY p.EFFFROM DESC
    LIMIT 1;

    IF VRATE IS NULL THEN
        SELECT d.PRICE INTO VRATE
        FROM CMS_ITEMPRICE p
        JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
        JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
        WHERE p.MENUITEMID = VMENUITEMID
          AND d.CTYPECODE = 'VIS'
          AND p.EFFFROM <= VSERVICEDATE
          AND IP_ST.STATUSCODE = 'ACT'
        ORDER BY p.EFFFROM DESC
        LIMIT 1;
    END IF;

    IF VRATE IS NULL THEN SET VRATE = 0.00; END IF;
    SET VAMOUNT = PQTY * VRATE;

    -- Wallet debit if applicable
    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') AND VAMOUNT > 0 THEN
        SELECT W.WALLETID, W.BALANCE, W.RESERVEDAMT
          INTO VWALLETID, VWALLETBAL, VWALLETRES
        FROM CMS_WALLET W
        JOIN CMS_STATUS WST ON WST.STATUSID = W.STATUSID
        WHERE W.CUSTOMERID = VCUSTOMERID AND WST.STATUSCODE = 'ACT'
        FOR UPDATE;

        IF VWALLETID IS NULL OR VWALLETBAL < VAMOUNT THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient available wallet balance to add item';
        END IF;

        UPDATE CMS_WALLET SET BALANCE = BALANCE - VAMOUNT WHERE WALLETID = VWALLETID;

        CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);
        INSERT INTO CMS_WALLETTRAN (
            WALLETID, BOOKINGID, TRANSTYPE, SOURCECODE, AMOUNT, BALBEFORE, BALAFTER,
            PAYMENTMETHOD, REFNO, STATUSID, CREATEDBY, REMARKS
        ) VALUES (
            VWALLETID, PBOOKID, 'DEBIT', 'BOOKING_ADD_ITEM', VAMOUNT, VWALLETBAL, VWALLETBAL - VAMOUNT,
            'WALLET', VAUTOREFNO, 40, PUSERID, COALESCE(PREMARKS, 'Item addition')
        );
    END IF;

    -- Check if item already exists in booking
    SELECT BOOKITEMID, QTY INTO VEXISTING_ITEMID, VEXISTING_QTY
    FROM CMS_BOOKITEM
    WHERE BOOKID = PBOOKID AND DAYMENUID = PDAYMENUID AND STATUSID = 30
    LIMIT 1;

    IF VEXISTING_ITEMID IS NOT NULL THEN
        UPDATE CMS_BOOKITEM
        SET QTY = QTY + PQTY,
            AMOUNT = (QTY + PQTY) * RATE,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKITEMID = VEXISTING_ITEMID;
    ELSE
        INSERT INTO CMS_BOOKITEM (BOOKID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, STATUSID)
        VALUES (PBOOKID, PDAYMENUID, VMENUITEMID, PQTY, VRATE, VAMOUNT, 30);
    END IF;

    -- Update daymenu available qty
    UPDATE CMS_DAYMENU
    SET AVAILQTY = GREATEST(0, AVAILQTY - PQTY),
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE DAYMENUID = PDAYMENUID;

    -- Recalculate Booking Totals
    UPDATE CMS_BOOKING
    SET TOTALITEMS = (SELECT COUNT(*) FROM CMS_BOOKITEM WHERE BOOKID = PBOOKID AND STATUSID = 30),
        TOTALQTY   = (SELECT COALESCE(SUM(QTY), 0) FROM CMS_BOOKITEM WHERE BOOKID = PBOOKID AND STATUSID = 30),
        TOTALAMOUNT = (SELECT COALESCE(SUM(AMOUNT), 0) FROM CMS_BOOKITEM WHERE BOOKID = PBOOKID AND STATUSID = 30),
        UPDATEDBY  = PUSERID,
        UPDATEDAT  = CURRENT_TIMESTAMP
    WHERE BOOKID = PBOOKID;

    -- Audit History
    INSERT INTO CMS_BOOKHIST (
        BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
        TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
        SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT,
        CHANGEDBY, CHGREASON
    )
    SELECT BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
           TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
           SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, PUSERID, CURRENT_TIMESTAMP,
           PUSERID, 'Added item to booking'
    FROM CMS_BOOKING WHERE BOOKID = PBOOKID;
    SET VBOOKHISTID = LAST_INSERT_ID();

    INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
    SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
    FROM CMS_BOOKITEM WHERE BOOKID = PBOOKID;

    COMMIT;

    SELECT PBOOKID AS BOOKID, 'SUCCESS' AS RESULT;
END$$


/* ============================================================
   CMSUPDBOOKINGITEMQTY — Granular Item Quantity Update on Existing Booking
   ============================================================ */
CREATE PROCEDURE CMSUPDBOOKINGITEMQTY (
    IN PBOOKITEMID INT,
    IN PNEWQTY     INT,
    IN PUSERID     INT,
    IN PREMARKS    VARCHAR(255)
)
BEGIN
    DECLARE VBOOKID INT;
    DECLARE VDAYMENUID INT;
    DECLARE VMENUITEMID INT;
    DECLARE VOLDQTY INT;
    DECLARE VRATE DECIMAL(10,2);
    DECLARE VDIFFQTY INT;
    DECLARE VDIFFAMT DECIMAL(12,2);
    DECLARE VCUSTOMERID INT;
    DECLARE VSTATUSCODE VARCHAR(10);
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VBOOKUNTIL DATETIME;
    DECLARE VMAXQTY INT;
    DECLARE VAVAILQTY INT;
    DECLARE VBOOKEDQTY INT DEFAULT 0;
    DECLARE VWALLETID INT;
    DECLARE VWALLETBAL DECIMAL(12,2);
    DECLARE VAUTOREFNO VARCHAR(80);
    DECLARE VBOOKHISTID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PBOOKITEMID IS NULL OR PNEWQTY IS NULL OR PNEWQTY <= 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Valid BookItem ID and positive new quantity required';
    END IF;

    START TRANSACTION;

    SELECT BI.BOOKID, BI.DAYMENUID, BI.MENUITEMID, BI.QTY, BI.RATE, ST.STATUSCODE,
           DM.BOOKUNTIL, DM.MAXQTY, DM.AVAILQTY
      INTO VBOOKID, VDAYMENUID, VMENUITEMID, VOLDQTY, VRATE, VSTATUSCODE,
           VBOOKUNTIL, VMAXQTY, VAVAILQTY
    FROM CMS_BOOKITEM BI
    JOIN CMS_STATUS ST ON ST.STATUSID = BI.STATUSID
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
    WHERE BI.BOOKITEMID = PBOOKITEMID
    FOR UPDATE;

    IF VBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking item not found';
    END IF;

    IF VSTATUSCODE <> 'CRT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only active items in CRT status can be updated';
    END IF;

    IF CURRENT_TIMESTAMP > VBOOKUNTIL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking window has closed for this item';
    END IF;

    SET VDIFFQTY = PNEWQTY - VOLDQTY;
    IF VDIFFQTY = 0 THEN
        COMMIT;
        SELECT VBOOKID AS BOOKID, 'NO_CHANGE' AS RESULT;
    ELSE
        -- Check Capacity if increasing
        IF VDIFFQTY > 0 THEN
            SELECT COALESCE(SUM(BI2.QTY), 0) INTO VBOOKEDQTY
            FROM CMS_BOOKITEM BI2
            JOIN CMS_STATUS BIST2 ON BIST2.STATUSID = BI2.STATUSID
            WHERE BI2.DAYMENUID = VDAYMENUID AND BIST2.STATUSCODE IN ('CRT', 'SRV', 'NOS');

            IF (VBOOKEDQTY + VDIFFQTY) > VMAXQTY THEN
                SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Requested quantity exceeds kitchen preparation capacity';
            END IF;
        END IF;

        SET VDIFFAMT = VDIFFQTY * VRATE;

        -- Check Customer & Wallet
        SELECT B.CUSTOMERID, C.CTYPECODE
          INTO VCUSTOMERID, VCTYPECODE
        FROM CMS_BOOKING B
        JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
        WHERE B.BOOKID = VBOOKID;

        IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') AND VDIFFAMT <> 0 THEN
            SELECT W.WALLETID, W.BALANCE
              INTO VWALLETID, VWALLETBAL
            FROM CMS_WALLET W
            JOIN CMS_STATUS WST ON WST.STATUSID = W.STATUSID
            WHERE W.CUSTOMERID = VCUSTOMERID AND WST.STATUSCODE = 'ACT'
            FOR UPDATE;

            IF VDIFFAMT > 0 AND (VWALLETID IS NULL OR VWALLETBAL < VDIFFAMT) THEN
                SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient available wallet balance to increase quantity';
            END IF;

            UPDATE CMS_WALLET SET BALANCE = BALANCE - VDIFFAMT WHERE WALLETID = VWALLETID;

            CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);
            INSERT INTO CMS_WALLETTRAN (
                WALLETID, BOOKINGID, TRANSTYPE, SOURCECODE, AMOUNT, BALBEFORE, BALAFTER,
                PAYMENTMETHOD, REFNO, STATUSID, CREATEDBY, REMARKS
            ) VALUES (
                VWALLETID, VBOOKID, (CASE WHEN VDIFFAMT > 0 THEN 'DEBIT' ELSE 'CREDIT' END),
                'BOOKING_UPDATE_QTY', ABS(VDIFFAMT), VWALLETBAL, VWALLETBAL - VDIFFAMT,
                'WALLET', VAUTOREFNO, 40, PUSERID, COALESCE(PREMARKS, 'Item quantity update')
            );
        END IF;

        -- Update Item
        UPDATE CMS_BOOKITEM
        SET QTY = PNEWQTY,
            AMOUNT = PNEWQTY * RATE,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKITEMID = PBOOKITEMID;

        -- Update Daymenu Availability
        UPDATE CMS_DAYMENU
        SET AVAILQTY = GREATEST(0, AVAILQTY - VDIFFQTY),
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE DAYMENUID = VDAYMENUID;

        -- Recalculate Booking Header
        UPDATE CMS_BOOKING
        SET TOTALQTY    = (SELECT COALESCE(SUM(QTY), 0) FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID AND STATUSID = 30),
            TOTALAMOUNT = (SELECT COALESCE(SUM(AMOUNT), 0) FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID AND STATUSID = 30),
            UPDATEDBY   = PUSERID,
            UPDATEDAT   = CURRENT_TIMESTAMP
        WHERE BOOKID = VBOOKID;

        -- Audit History
        INSERT INTO CMS_BOOKHIST (
            BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
            TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
            SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT,
            CHANGEDBY, CHGREASON
        )
        SELECT BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
               TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
               SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, PUSERID, CURRENT_TIMESTAMP,
               PUSERID, 'Updated item quantity'
        FROM CMS_BOOKING WHERE BOOKID = VBOOKID;
        SET VBOOKHISTID = LAST_INSERT_ID();

        INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
        SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
        FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID;

        COMMIT;
        SELECT VBOOKID AS BOOKID, 'SUCCESS' AS RESULT;
    END IF;
END$$


/* ============================================================
   CMSCANCELBOOKINGITEM — Granular Item Cancellation from Existing Booking
   ============================================================ */
CREATE PROCEDURE CMSCANCELBOOKINGITEM (
    IN PBOOKITEMID INT,
    IN PUSERID     INT,
    IN PREMARKS    VARCHAR(255)
)
BEGIN
    DECLARE VBOOKID INT;
    DECLARE VDAYMENUID INT;
    DECLARE VITEMQTY INT;
    DECLARE VITEMAMT DECIMAL(12,2);
    DECLARE VITEMSTATUSID INT;
    DECLARE VSTATUSCODE VARCHAR(10);
    DECLARE VCUSTOMERID INT;
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VCANCELUNTIL DATETIME;
    DECLARE VACTIVEITEMS INT DEFAULT 0;
    DECLARE VWALLETID INT;
    DECLARE VWALLETBAL DECIMAL(12,2);
    DECLARE VAUTOREFNO VARCHAR(80);
    DECLARE VBOOKHISTID INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PBOOKITEMID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking Item ID is required';
    END IF;

    START TRANSACTION;

    SELECT BI.BOOKID, BI.DAYMENUID, BI.QTY, BI.AMOUNT, BI.STATUSID, ST.STATUSCODE, DM.CANCELUNTIL
      INTO VBOOKID, VDAYMENUID, VITEMQTY, VITEMAMT, VITEMSTATUSID, VSTATUSCODE, VCANCELUNTIL
    FROM CMS_BOOKITEM BI
    JOIN CMS_STATUS ST ON ST.STATUSID = BI.STATUSID
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
    WHERE BI.BOOKITEMID = PBOOKITEMID
    FOR UPDATE;

    IF VBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking item not found';
    END IF;

    IF VSTATUSCODE <> 'CRT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only active items in CRT status can be cancelled';
    END IF;

    IF CURRENT_TIMESTAMP > VCANCELUNTIL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cancellation cutoff window has passed for this item';
    END IF;

    -- Cancel Item (33 = 'CAN')
    UPDATE CMS_BOOKITEM
    SET STATUSID = 33,
        REMARKS = COALESCE(PREMARKS, 'Item cancelled'),
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKITEMID = PBOOKITEMID;

    -- Restore Daymenu Availability
    UPDATE CMS_DAYMENU
    SET AVAILQTY = AVAILQTY + VITEMQTY,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE DAYMENUID = VDAYMENUID;

    -- Check Customer & Wallet Refund
    SELECT B.CUSTOMERID, C.CTYPECODE
      INTO VCUSTOMERID, VCTYPECODE
    FROM CMS_BOOKING B
    JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    WHERE B.BOOKID = VBOOKID;

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') AND VITEMAMT > 0 THEN
        SELECT W.WALLETID, W.BALANCE
          INTO VWALLETID, VWALLETBAL
        FROM CMS_WALLET W
        JOIN CMS_STATUS WST ON WST.STATUSID = W.STATUSID
        WHERE W.CUSTOMERID = VCUSTOMERID AND WST.STATUSCODE = 'ACT'
        FOR UPDATE;

        IF VWALLETID IS NOT NULL THEN
            UPDATE CMS_WALLET SET BALANCE = BALANCE + VITEMAMT WHERE WALLETID = VWALLETID;

            CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);
            INSERT INTO CMS_WALLETTRAN (
                WALLETID, BOOKINGID, TRANSTYPE, SOURCECODE, AMOUNT, BALBEFORE, BALAFTER,
                PAYMENTMETHOD, REFNO, STATUSID, CREATEDBY, REMARKS
            ) VALUES (
                VWALLETID, VBOOKID, 'CREDIT', 'BOOKING_CANCEL_ITEM', VITEMAMT, VWALLETBAL, VWALLETBAL + VITEMAMT,
                'WALLET', VAUTOREFNO, 40, PUSERID, COALESCE(PREMARKS, 'Item cancellation refund')
            );
        END IF;
    END IF;

    -- Check Remaining Active Items
    SELECT COUNT(*) INTO VACTIVEITEMS
    FROM CMS_BOOKITEM
    WHERE BOOKID = VBOOKID AND STATUSID = 30;

    IF VACTIVEITEMS = 0 THEN
        -- Cancel Entire Booking Header (33 = 'CAN')
        UPDATE CMS_BOOKING
        SET STATUSID = 33,
            TOTALITEMS = 0,
            TOTALQTY = 0,
            TOTALAMOUNT = 0.00,
            CANCELLEDBY = PUSERID,
            CANCELLEDON = CURRENT_TIMESTAMP,
            REMARKS = COALESCE(PREMARKS, 'All items cancelled'),
            UPDATEDBY = PUSERID,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKID = VBOOKID;

        DELETE FROM CMS_PBACTIVE WHERE BOOKID = VBOOKID;
    ELSE
        -- Update Totals
        UPDATE CMS_BOOKING
        SET TOTALITEMS  = VACTIVEITEMS,
            TOTALQTY    = (SELECT COALESCE(SUM(QTY), 0) FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID AND STATUSID = 30),
            TOTALAMOUNT = (SELECT COALESCE(SUM(AMOUNT), 0) FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID AND STATUSID = 30),
            UPDATEDBY   = PUSERID,
            UPDATEDAT   = CURRENT_TIMESTAMP
        WHERE BOOKID = VBOOKID;
    END IF;

    -- Audit History
    INSERT INTO CMS_BOOKHIST (
        BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
        TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
        SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT,
        CHANGEDBY, CHGREASON
    )
    SELECT BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID, BOOKSEQNO,
           TOTALITEMS, TOTALQTY, TOTALAMOUNT, BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON,
           SERVEDBY, SERVEDON, NOSHOWON, KIOSKID, REMARKS, CREATEDBY, CREATEDAT, PUSERID, CURRENT_TIMESTAMP,
           PUSERID, 'Cancelled booking item'
    FROM CMS_BOOKING WHERE BOOKID = VBOOKID;
    SET VBOOKHISTID = LAST_INSERT_ID();

    INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
    SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
    FROM CMS_BOOKITEM WHERE BOOKID = VBOOKID;

    COMMIT;

    SELECT VBOOKID AS BOOKID, (CASE WHEN VACTIVEITEMS = 0 THEN 'BOOKING_CANCELLED' ELSE 'ITEM_CANCELLED' END) AS RESULT;
END$$

