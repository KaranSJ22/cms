-- Creates a PB or KS booking header plus its items in one transaction.
CREATE PROCEDURE CMSADDBOOK (
    IN PBOOKTYPECODE VARCHAR(10),
    IN PCUSTOMERID INT,
    IN PSERVICEID INT,
    IN PSERVICEDATE DATE,
    IN PITEMSJSON JSON,
    IN PBOOKEDBY INT,
    IN PREMARKS VARCHAR(255)
)
BEGIN
    DECLARE VBOOKTYPEID INT;
    DECLARE VBOOKTYPESTATUSID INT;
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VCUSTSTATUSID INT;
    DECLARE VSERVPFX VARCHAR(5);
    DECLARE VSERVSTATUSID INT;
    DECLARE VEXISTINGPB INT DEFAULT 0;
    DECLARE VITEMCOUNT INT DEFAULT 0;
    DECLARE VDISTINCTCOUNT INT DEFAULT 0;
    DECLARE VINVALIDCOUNT INT DEFAULT 0;
    DECLARE VBOOKID INT;
    DECLARE VBOOKNO VARCHAR(30);
    DECLARE VBOOKSEQ BIGINT;
    DECLARE VTOTALITEMS INT DEFAULT 0;
    DECLARE VTOTALQTY INT DEFAULT 0;
    DECLARE VTOTALAMOUNT DECIMAL(12,2) DEFAULT 0.00;
    DECLARE VLASTNO BIGINT;
    DECLARE VWALLETID INT;
    DECLARE VWALLETBALANCE DECIMAL(12,2);
    DECLARE VWALLETRESERVED DECIMAL(12,2);
    DECLARE VAUTOREFNO VARCHAR(80);
    DECLARE VCAPACITY_EXCEEDED INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PBOOKTYPECODE IS NULL OR PBOOKTYPECODE NOT IN ('PB','KS') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking type must be PB or KS';
    END IF;

    IF PCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer is required';
    END IF;

    IF PSERVICEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service is required';
    END IF;

    IF PSERVICEDATE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service date is required';
    END IF;

    IF PITEMSJSON IS NULL OR JSON_TYPE(PITEMSJSON) <> 'ARRAY' OR JSON_LENGTH(PITEMSJSON) = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'At least one booking item is required';
    END IF;

    SELECT BT.BOOKTYPEID, BT.STATUSID INTO VBOOKTYPEID, VBOOKTYPESTATUSID
    FROM CMS_BOOKTYPE BT WHERE BT.BOOKTYPECODE = PBOOKTYPECODE;

    IF VBOOKTYPEID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking type not found';
    END IF;

    -- 10 = 'ACT'
    IF VBOOKTYPESTATUSID <> 10 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking type is inactive';
    END IF;

    SELECT C.CTYPECODE, C.STATUSID INTO VCTYPECODE, VCUSTSTATUSID
    FROM CMS_CUSTOMER C WHERE C.CUSTOMERID = PCUSTOMERID;

    IF VCTYPECODE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer not found';
    END IF;

    IF VCUSTSTATUSID <> 10 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer is not active';
    END IF;

    SELECT UPPER(LEFT(S.SERVCODE, 2)), S.STATUSID INTO VSERVPFX, VSERVSTATUSID
    FROM CMS_SERVICE S WHERE S.SERVICEID = PSERVICEID;

    IF VSERVPFX IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service not found';
    END IF;

    IF VSERVSTATUSID <> 10 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Service is not active';
    END IF;

    IF PBOOKTYPECODE IN ('PB', 'KS') THEN
        SELECT COUNT(*) INTO VEXISTINGPB
        FROM CMS_BOOKING B
        JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
        WHERE B.CUSTOMERID = PCUSTOMERID
          AND B.SERVICEID = PSERVICEID
          AND B.SERVICEDATE = PSERVICEDATE
          AND ST.STATUSCODE <> 'CAN'; -- 33 = CAN

        IF VEXISTINGPB > 0 THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'An active booking already exists for this service and date; duplicate bookings are not allowed';
        END IF;
    END IF;

    SET VITEMCOUNT = JSON_LENGTH(PITEMSJSON);

    SELECT COUNT(DISTINCT JT.DAYMENUID) INTO VDISTINCTCOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID'
    )) AS JT;

    IF VDISTINCTCOUNT <> VITEMCOUNT THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Duplicate day menu items in the same booking are not allowed';
    END IF;

    SELECT COUNT(*) INTO VINVALIDCOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    LEFT JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    LEFT JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    LEFT JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    LEFT JOIN CMS_STATUS DS_AST ON DS_AST.STATUSID = DS.APPRSTATUSID
    LEFT JOIN CMS_STATUS DS_ST ON DS_ST.STATUSID = DS.STATUSID
    LEFT JOIN CMS_STATUS MI_ST ON MI_ST.STATUSID = MI.STATUSID
    WHERE JT.DAYMENUID IS NULL
       OR JT.QTY IS NULL OR JT.QTY < 1
       OR DM.DAYMENUID IS NULL
       OR DS_AST.STATUSCODE <> 'APR'
       OR DS.SERVICEID <> PSERVICEID
       OR DS.SERVDATE <> PSERVICEDATE
       OR DS_ST.STATUSCODE <> 'ACT'
       OR MI_ST.STATUSCODE <> 'ACT'
       OR CURRENT_TIMESTAMP > DM.BOOKUNTIL
       OR (PBOOKTYPECODE = 'PB' AND (DM.ISPREBOOK <> 1 OR JT.QTY > DM.MAXQTY))
       OR (PBOOKTYPECODE = 'KS' AND DM.ISKIOSK <> 1);

    IF VINVALIDCOUNT > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more booking items are invalid, inactive, unavailable, or outside the booking window';
    END IF;

    START TRANSACTION;

    SELECT COUNT(*) INTO @dummy
    FROM CMS_DAYMENU
    WHERE DAYMENUID IN (
        SELECT DAYMENUID FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (DAYMENUID INT PATH '$.DAYMENUID')) AS JT
    ) FOR UPDATE;

    SELECT COUNT(*) INTO VCAPACITY_EXCEEDED
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    WHERE DM.AVAILQTY IS NOT NULL
      AND (
          SELECT COALESCE(SUM(BI.QTY), 0)
          FROM CMS_BOOKITEM BI
          JOIN CMS_BOOKING B ON B.BOOKID = BI.BOOKID
          JOIN CMS_STATUS B_ST2 ON B_ST2.STATUSID = B.STATUSID
          WHERE BI.DAYMENUID = JT.DAYMENUID
            AND B_ST2.STATUSCODE IN ('CRT', 'SRV', 'NOS')
      ) + JT.QTY > DM.AVAILQTY;

    IF VCAPACITY_EXCEEDED > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more items have insufficient available capacity';
    END IF;

    INSERT INTO CMS_BOOKCTR (BOOKTYPEID, SERVICEID, LASTNO)
    VALUES (VBOOKTYPEID, PSERVICEID, 0)
    ON DUPLICATE KEY UPDATE LASTNO = LASTNO;

    SELECT LASTNO INTO VLASTNO
    FROM CMS_BOOKCTR
    WHERE BOOKTYPEID = VBOOKTYPEID AND SERVICEID = PSERVICEID
    FOR UPDATE;

    SET VBOOKSEQ = VLASTNO + 1;

    UPDATE CMS_BOOKCTR SET LASTNO = VBOOKSEQ
    WHERE BOOKTYPEID = VBOOKTYPEID AND SERVICEID = PSERVICEID;

    SET VBOOKNO = CONCAT(PBOOKTYPECODE, '-', VSERVPFX, LPAD(VBOOKSEQ, 3, '0'));

    SELECT COUNT(*), SUM(JT.QTY), SUM(JT.QTY * COALESCE(
        (SELECT d.PRICE
         FROM CMS_ITEMPRICE p
         JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
         JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
         WHERE p.MENUITEMID = DM.MENUITEMID
           AND d.CTYPECODE = VCTYPECODE
           AND p.EFFFROM <= PSERVICEDATE
           AND IP_ST.STATUSCODE = 'ACT'
         ORDER BY p.EFFFROM DESC LIMIT 1),
        0))
    INTO VTOTALITEMS, VTOTALQTY, VTOTALAMOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID;

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
        SELECT W.WALLETID, W.BALANCE, W.RESERVEDAMT
        INTO VWALLETID, VWALLETBALANCE, VWALLETRESERVED
        FROM CMS_WALLET W
        JOIN CMS_STATUS W_ST ON W_ST.STATUSID = W.STATUSID
        WHERE W.CUSTOMERID = PCUSTOMERID AND W_ST.STATUSCODE = 'ACT'
        FOR UPDATE;

        IF VWALLETID IS NULL THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Active wallet not found for customer';
        END IF;

        IF VTOTALAMOUNT > (VWALLETBALANCE - VWALLETRESERVED) THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient available wallet balance to place booking';
        END IF;

        UPDATE CMS_WALLET
        SET BALANCE = BALANCE - VTOTALAMOUNT
        WHERE WALLETID = VWALLETID;
    END IF;

    -- 30 = 'CRT' (Created)
    INSERT INTO CMS_BOOKING (
        BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE, STATUSID,
        BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
        BOOKEDBY, BOOKEDON, REMARKS, CREATEDBY
    )
    VALUES (
        VBOOKNO, VBOOKTYPEID, PCUSTOMERID, PSERVICEID, PSERVICEDATE, 30,
        VBOOKSEQ, VTOTALITEMS, VTOTALQTY, VTOTALAMOUNT,
        PBOOKEDBY, CURRENT_TIMESTAMP, PREMARKS, PBOOKEDBY
    );

    SET VBOOKID = LAST_INSERT_ID();

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
        CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);

        -- 44 = DBT (Debit)
        INSERT INTO CMS_WALLETTRAN
        (
            WALLETID,
            BOOKINGID,
            TRANSTYPE,
            SOURCECODE,
            AMOUNT,
            BALBEFORE,
            BALAFTER,
            PAYMENTMETHOD,
            REFNO,
            STATUSID,
            CREATEDBY,
            REMARKS
        )
        VALUES
        (
            VWALLETID,
            VBOOKID,
            'DEBIT',
            'BOOKING',
            VTOTALAMOUNT,
            VWALLETBALANCE,
            VWALLETBALANCE - VTOTALAMOUNT,
            'WALLET',
            VAUTOREFNO,
            44,
            PBOOKEDBY,
            CONCAT('Pre-booking #', VBOOKNO)
        );
    END IF;

    INSERT INTO CMS_BOOKITEM (BOOKID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, STATUSID)
    SELECT
        VBOOKID,
        DM.DAYMENUID,
        DM.MENUITEMID,
        JT.QTY,
        COALESCE(
            (SELECT d.PRICE
             FROM CMS_ITEMPRICE p
             JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
             JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
             WHERE p.MENUITEMID = DM.MENUITEMID
               AND d.CTYPECODE = VCTYPECODE
               AND p.EFFFROM <= PSERVICEDATE
               AND IP_ST.STATUSCODE = 'ACT'
             ORDER BY p.EFFFROM DESC LIMIT 1),
            0),
        JT.QTY * COALESCE(
            (SELECT d.PRICE
             FROM CMS_ITEMPRICE p
             JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
             JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
             WHERE p.MENUITEMID = DM.MENUITEMID
               AND d.CTYPECODE = VCTYPECODE
               AND p.EFFFROM <= PSERVICEDATE
               AND IP_ST.STATUSCODE = 'ACT'
             ORDER BY p.EFFFROM DESC LIMIT 1),
            0),
        30
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID;

    IF PBOOKTYPECODE = 'PB' THEN
        INSERT INTO CMS_PBACTIVE (CUSTOMERID, SERVICEID, SERVICEDATE, BOOKID)
        VALUES (PCUSTOMERID, PSERVICEID, PSERVICEDATE, VBOOKID);
    END IF;

    COMMIT;

    SELECT VBOOKID AS BOOKID, VBOOKNO AS BOOKNO;
END$$

-- Full replacement of a PB booking's items, pre-cutoff only.
CREATE PROCEDURE CMSUPDBOOKITEM (
    IN PBOOKID INT,
    IN PITEMSJSON JSON,
    IN PCHANGEDBY INT
)
BEGIN
    DECLARE VBOOKTYPECODE VARCHAR(10);
    DECLARE VCUSTOMERID INT;
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VSERVICEID INT;
    DECLARE VSERVICEDATE DATE;
    DECLARE VSTATUSCODE VARCHAR(10);
    DECLARE VCUTOFF DATETIME;
    DECLARE VITEMCOUNT INT DEFAULT 0;
    DECLARE VDISTINCTCOUNT INT DEFAULT 0;
    DECLARE VINVALIDCOUNT INT DEFAULT 0;
    DECLARE VTOTALITEMS INT DEFAULT 0;
    DECLARE VTOTALQTY INT DEFAULT 0;
    DECLARE VTOTALAMOUNT DECIMAL(12,2) DEFAULT 0.00;
    DECLARE VOLDTOTALAMOUNT DECIMAL(12,2) DEFAULT 0.00;
    DECLARE VWALLETID INT;
    DECLARE VWALLETBALANCE DECIMAL(12,2);
    DECLARE VWALLETRESERVED DECIMAL(12,2);
    DECLARE VAUTOREFNO VARCHAR(80);
    DECLARE VCAPACITY_EXCEEDED INT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking ID is required';
    END IF;

    IF PITEMSJSON IS NULL OR JSON_TYPE(PITEMSJSON) <> 'ARRAY' OR JSON_LENGTH(PITEMSJSON) = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'At least one booking item is required';
    END IF;

    SELECT BT.BOOKTYPECODE, BK.CUSTOMERID, BK.SERVICEID, BK.SERVICEDATE, ST.STATUSCODE, BK.TOTALAMOUNT
    INTO VBOOKTYPECODE, VCUSTOMERID, VSERVICEID, VSERVICEDATE, VSTATUSCODE, VOLDTOTALAMOUNT
    FROM CMS_BOOKING BK
    JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = BK.BOOKTYPEID
    JOIN CMS_STATUS ST ON ST.STATUSID = BK.STATUSID
    WHERE BK.BOOKID = PBOOKID;

    IF VBOOKTYPECODE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking not found';
    END IF;

    IF VBOOKTYPECODE NOT IN ('PB', 'KS') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only pre-bookings can be edited';
    END IF;

    IF VSTATUSCODE <> 'CRT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking is not in an editable state';
    END IF;

    SELECT MIN(DM.CANCELUNTIL) INTO VCUTOFF
    FROM CMS_BOOKITEM BI
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
    WHERE BI.BOOKID = PBOOKID;

    IF VCUTOFF IS NOT NULL AND CURRENT_TIMESTAMP > VCUTOFF THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking cutoff time has passed; this booking can no longer be edited';
    END IF;

    SELECT C.CTYPECODE INTO VCTYPECODE FROM CMS_CUSTOMER C WHERE C.CUSTOMERID = VCUSTOMERID;

    SET VITEMCOUNT = JSON_LENGTH(PITEMSJSON);

    SELECT COUNT(DISTINCT JT.DAYMENUID) INTO VDISTINCTCOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID'
    )) AS JT;

    IF VDISTINCTCOUNT <> VITEMCOUNT THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Duplicate day menu items in the same booking are not allowed';
    END IF;

    SELECT COUNT(*) INTO VINVALIDCOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    LEFT JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    LEFT JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
    LEFT JOIN CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    LEFT JOIN CMS_STATUS DS_AST ON DS_AST.STATUSID = DS.APPRSTATUSID
    LEFT JOIN CMS_STATUS DS_ST ON DS_ST.STATUSID = DS.STATUSID
    LEFT JOIN CMS_STATUS MI_ST ON MI_ST.STATUSID = MI.STATUSID
    WHERE JT.DAYMENUID IS NULL
       OR JT.QTY IS NULL OR JT.QTY < 1
       OR DM.DAYMENUID IS NULL
       OR DS_AST.STATUSCODE <> 'APR'
       OR DS.SERVICEID <> VSERVICEID
       OR DS.SERVDATE <> VSERVICEDATE
       OR DS_ST.STATUSCODE <> 'ACT'
       OR MI_ST.STATUSCODE <> 'ACT'
       OR CURRENT_TIMESTAMP > DM.CANCELUNTIL
       OR (VBOOKTYPECODE = 'PB' AND (DM.ISPREBOOK <> 1 OR JT.QTY > DM.MAXQTY))
       OR (VBOOKTYPECODE = 'KS' AND DM.ISKIOSK <> 1);

    IF VINVALIDCOUNT > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more booking items are invalid, inactive, unavailable, or past cutoff';
    END IF;

    START TRANSACTION;

    SELECT COUNT(*) INTO @dummy
    FROM CMS_DAYMENU
    WHERE DAYMENUID IN (
        SELECT DAYMENUID FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (DAYMENUID INT PATH '$.DAYMENUID')) AS JT
    ) FOR UPDATE;

    SELECT COUNT(*) INTO VCAPACITY_EXCEEDED
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID
    WHERE DM.AVAILQTY IS NOT NULL
      AND (
          SELECT COALESCE(SUM(BI.QTY), 0)
          FROM CMS_BOOKITEM BI
          JOIN CMS_BOOKING B ON B.BOOKID = BI.BOOKID
          JOIN CMS_STATUS B_ST2 ON B_ST2.STATUSID = B.STATUSID
          WHERE BI.DAYMENUID = JT.DAYMENUID
            AND B_ST2.STATUSCODE IN ('CRT', 'SRV', 'NOS')
            AND B.BOOKID <> PBOOKID
      ) + JT.QTY > DM.AVAILQTY;

    IF VCAPACITY_EXCEEDED > 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'One or more items have insufficient available capacity';
    END IF;

    DELETE FROM CMS_BOOKITEM WHERE BOOKID = PBOOKID;

    SELECT COUNT(*), SUM(JT.QTY), SUM(JT.QTY * COALESCE(
        (SELECT d.PRICE
         FROM CMS_ITEMPRICE p
         JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
         JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
         WHERE p.MENUITEMID = DM.MENUITEMID
           AND d.CTYPECODE = VCTYPECODE
           AND p.EFFFROM <= VSERVICEDATE
           AND IP_ST.STATUSCODE = 'ACT'
         ORDER BY p.EFFFROM DESC LIMIT 1),
        0))
    INTO VTOTALITEMS, VTOTALQTY, VTOTALAMOUNT
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID;

    INSERT INTO CMS_BOOKITEM (BOOKID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, STATUSID)
    SELECT
        PBOOKID,
        DM.DAYMENUID,
        DM.MENUITEMID,
        JT.QTY,
        COALESCE(
            (SELECT d.PRICE
             FROM CMS_ITEMPRICE p
             JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
             JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
             WHERE p.MENUITEMID = DM.MENUITEMID
               AND d.CTYPECODE = VCTYPECODE
               AND p.EFFFROM <= VSERVICEDATE
               AND IP_ST.STATUSCODE = 'ACT'
             ORDER BY p.EFFFROM DESC LIMIT 1),
            0),
        JT.QTY * COALESCE(
            (SELECT d.PRICE
             FROM CMS_ITEMPRICE p
             JOIN CMS_STATUS IP_ST ON IP_ST.STATUSID = p.STATUSID
             JOIN CMS_ITEMPRICEDT d ON d.ITEMPRICEID = p.ITEMPRICEID
             WHERE p.MENUITEMID = DM.MENUITEMID
               AND d.CTYPECODE = VCTYPECODE
               AND p.EFFFROM <= VSERVICEDATE
               AND IP_ST.STATUSCODE = 'ACT'
             ORDER BY p.EFFFROM DESC LIMIT 1),
            0),
        30 -- 30 = 'CRT'
    FROM JSON_TABLE(PITEMSJSON, '$[*]' COLUMNS (
        DAYMENUID INT PATH '$.DAYMENUID',
        QTY INT PATH '$.QTY'
    )) AS JT
    JOIN CMS_DAYMENU DM ON DM.DAYMENUID = JT.DAYMENUID;

    UPDATE CMS_BOOKING
    SET TOTALITEMS = VTOTALITEMS,
        TOTALQTY = VTOTALQTY,
        TOTALAMOUNT = VTOTALAMOUNT,
        UPDATEDBY = PCHANGEDBY,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKID = PBOOKID;

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
        SET VWALLETID = NULL;
        SELECT W.WALLETID, W.BALANCE INTO VWALLETID, VWALLETBALANCE
        FROM CMS_WALLET W
        JOIN CMS_STATUS W_ST ON W_ST.STATUSID = W.STATUSID
        WHERE W.CUSTOMERID = VCUSTOMERID AND W_ST.STATUSCODE = 'ACT'
        FOR UPDATE;

        IF VWALLETID IS NOT NULL THEN
            IF VTOTALAMOUNT > VOLDTOTALAMOUNT THEN
                IF (VWALLETBALANCE - VWALLETRESERVED) < (VTOTALAMOUNT - VOLDTOTALAMOUNT) THEN
                    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient available wallet balance for edited items';
                END IF;

                UPDATE CMS_WALLET
                SET BALANCE = BALANCE - (VTOTALAMOUNT - VOLDTOTALAMOUNT)
                WHERE WALLETID = VWALLETID;

                CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);

                -- 44 = DBT (Debit)
                INSERT INTO CMS_WALLETTRAN
                (
                    WALLETID,
                    BOOKINGID,
                    TRANSTYPE,
                    SOURCECODE,
                    AMOUNT,
                    BALBEFORE,
                    BALAFTER,
                    PAYMENTMETHOD,
                    REFNO,
                    STATUSID,
                    CREATEDBY,
                    REMARKS
                )
                VALUES
                (
                    VWALLETID,
                    PBOOKID,
                    'DEBIT',
                    'BOOKING_EDIT',
                    (VTOTALAMOUNT - VOLDTOTALAMOUNT),
                    VWALLETBALANCE,
                    VWALLETBALANCE - (VTOTALAMOUNT - VOLDTOTALAMOUNT),
                    'WALLET',
                    VAUTOREFNO,
                    44,
                    PCHANGEDBY,
                    'Booking items edited (additional charge)'
                );

            ELSEIF VTOTALAMOUNT < VOLDTOTALAMOUNT THEN
                UPDATE CMS_WALLET
                SET BALANCE = BALANCE + (VOLDTOTALAMOUNT - VTOTALAMOUNT)
                WHERE WALLETID = VWALLETID;

                CALL CMSGENAUTO('CMS_WALLETTRAN', 'REFNO', VAUTOREFNO);

                -- 40 = DEP (Credit)
                INSERT INTO CMS_WALLETTRAN
                (
                    WALLETID,
                    BOOKINGID,
                    TRANSTYPE,
                    SOURCECODE,
                    AMOUNT,
                    BALBEFORE,
                    BALAFTER,
                    PAYMENTMETHOD,
                    REFNO,
                    STATUSID,
                    CREATEDBY,
                    REMARKS
                )
                VALUES
                (
                    VWALLETID,
                    PBOOKID,
                    'CREDIT',
                    'REFUND',
                    (VOLDTOTALAMOUNT - VTOTALAMOUNT),
                    VWALLETBALANCE,
                    VWALLETBALANCE + (VOLDTOTALAMOUNT - VTOTALAMOUNT),
                    'WALLET',
                    VAUTOREFNO,
                    40,
                    PCHANGEDBY,
                    'Booking items edited (refund excess)'
                );
            END IF;
        END IF;
    END IF;

    COMMIT;
END$$

-- Cancels a booking.
CREATE PROCEDURE CMSCANCELBOOK (
    IN PBOOKID INT,
    IN PCANCELLEDBY INT,
    IN PISSTAFFOVERRIDE TINYINT,
    IN PCHGREASON VARCHAR(255)
)
BEGIN
    DECLARE VSTATUSCODE VARCHAR(10);
    DECLARE VCUTOFF DATETIME;
    DECLARE VBOOKHISTID INT;
    DECLARE VTOTALAMOUNT DECIMAL(12,2);
    DECLARE VCUSTOMERID INT;
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VWALLETID INT;
    DECLARE VWALLETBALANCE DECIMAL(12,2);
    DECLARE VAUTOREFNO VARCHAR(80);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
