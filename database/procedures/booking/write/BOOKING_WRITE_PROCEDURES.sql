-- Marks an individual booking item as served. If all active items are served, finalizes booking header as Served.
CREATE PROCEDURE CMSSERVEBOOKITEM (
    IN PBOOKID     INT,
    IN PBOOKITEMID INT,
    IN PSERVEDBY   INT,
    IN PKIOSKID    INT,
    IN PCHGREASON  VARCHAR(255)
)
PROC_BLOCK: BEGIN
    DECLARE VITEMSTATUSID   INT;
    DECLARE VITEMSTATUSCODE VARCHAR(10);
    DECLARE VBOOKSTATUSID   INT;
    DECLARE VBOOKSTATUSCODE VARCHAR(10);
    DECLARE VSERVICEDATE    DATE;
    DECLARE VCUSTOMERID     INT;
    DECLARE VCTYPECODE      VARCHAR(20);
    DECLARE VTOTALAMOUNT    DECIMAL(12,2);
    DECLARE VUNSERVED_COUNT INT DEFAULT 0;
    DECLARE VBOOKHISTID     INT;
    DECLARE VALL_SERVED     TINYINT DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking ID is required';
    END IF;
    IF PBOOKITEMID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking Item ID is required';
    END IF;
    IF PSERVEDBY IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Served By user ID is required';
    END IF;

    -- Retrieve item and parent booking info
    SELECT BI.STATUSID, BIST.STATUSCODE, B.STATUSID, BST.STATUSCODE, B.SERVICEDATE, B.CUSTOMERID, C.CTYPECODE, B.TOTALAMOUNT
    INTO   VITEMSTATUSID, VITEMSTATUSCODE, VBOOKSTATUSID, VBOOKSTATUSCODE, VSERVICEDATE, VCUSTOMERID, VCTYPECODE, VTOTALAMOUNT
    FROM   CMS_BOOKITEM BI
    JOIN   CMS_BOOKING B    ON B.BOOKID = BI.BOOKID
    JOIN   CMS_CUSTOMER C   ON C.CUSTOMERID = B.CUSTOMERID
    JOIN   CMS_STATUS BIST  ON BIST.STATUSID = BI.STATUSID
    JOIN   CMS_STATUS BST   ON BST.STATUSID = B.STATUSID
    WHERE  BI.BOOKITEMID = PBOOKITEMID AND BI.BOOKID = PBOOKID;

    IF VITEMSTATUSID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking item not found for this booking';
    END IF;

    -- Idempotent check: if already served (32 = 'SRV'), return cleanly
    IF VITEMSTATUSCODE = 'SRV' THEN
        SELECT PBOOKID AS BOOKID, PBOOKITEMID AS BOOKITEMID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 1 AS ALREADY_SERVED, 
               (CASE WHEN VBOOKSTATUSCODE = 'SRV' THEN 1 ELSE 0 END) AS ALL_SERVED;
        LEAVE PROC_BLOCK;
    END IF;

    IF VITEMSTATUSCODE = 'CAN' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot serve a cancelled booking item';
    END IF;

    IF VBOOKSTATUSCODE = 'CAN' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot serve an item from a cancelled booking';
    END IF;

    IF VSERVICEDATE <> CURDATE() THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only bookings for today can be served';
    END IF;

    START TRANSACTION;

    -- 1. Mark this specific item as Served (32 = 'SRV')
    UPDATE CMS_BOOKITEM
    SET STATUSID = 32,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKITEMID = PBOOKITEMID;

    -- 2. Check how many items remain unserved in this booking (30 = 'CRT')
    SELECT COUNT(*) INTO VUNSERVED_COUNT
    FROM CMS_BOOKITEM
    WHERE BOOKID = PBOOKID AND STATUSID = 30;

    -- 3. If no active unserved items remain, finalize the booking header as Served
    IF VUNSERVED_COUNT = 0 THEN
        INSERT INTO CMS_BOOKHIST (
            BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
            STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
            BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
            KIOSKID,
            REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, CHANGEDBY, CHGREASON
        )
        SELECT
            BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
            STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
            BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
            PKIOSKID,
            REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, PSERVEDBY, COALESCE(PCHGREASON, 'All items served')
        FROM CMS_BOOKING
        WHERE BOOKID = PBOOKID;

        SET VBOOKHISTID = LAST_INSERT_ID();

        INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
        SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
        FROM CMS_BOOKITEM
        WHERE BOOKID = PBOOKID;

        UPDATE CMS_BOOKING
        SET STATUSID = 32,
            SERVEDBY = PSERVEDBY,
            SERVEDON = CURRENT_TIMESTAMP,
            KIOSKID = COALESCE(PKIOSKID, KIOSKID),
            UPDATEDBY = PSERVEDBY,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE BOOKID = PBOOKID;

        DELETE FROM CMS_PBACTIVE WHERE BOOKID = PBOOKID;

        IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
            UPDATE CMS_WALLET
            SET RESERVEDAMT = GREATEST(0, RESERVEDAMT - VTOTALAMOUNT),
                UPDATEDBY = PSERVEDBY,
                UPDATEDAT = CURRENT_TIMESTAMP
            WHERE CUSTOMERID = VCUSTOMERID;
        END IF;

        SET VALL_SERVED = 1;
    ELSE
        SET VALL_SERVED = 0;
    END IF;

    COMMIT;

    SELECT PBOOKID AS BOOKID, PBOOKITEMID AS BOOKITEMID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 0 AS ALREADY_SERVED, VALL_SERVED AS ALL_SERVED;
END$$

-- End-of-day batch job for No Shows.
