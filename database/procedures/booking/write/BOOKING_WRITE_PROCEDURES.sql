        RESIGNAL;
    END;

    IF PBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking ID is required';
    END IF;

    SELECT ST.STATUSCODE, B.CUSTOMERID, B.TOTALAMOUNT, C.CTYPECODE 
    INTO VSTATUSCODE, VCUSTOMERID, VTOTALAMOUNT, VCTYPECODE 
    FROM CMS_BOOKING B
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    WHERE B.BOOKID = PBOOKID;

