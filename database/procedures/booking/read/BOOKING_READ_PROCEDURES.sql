-- Fetch a single booking header and its items
CREATE PROCEDURE CMSGETBOOK(
    IN PBOOKID INT
)
BEGIN
    SELECT 
        B.BOOKID, B.BOOKNO, B.BOOKTYPEID, BT.BOOKTYPECODE, BT.BOOKTYPENAME,
        B.CUSTOMERID, C.CTYPECODE, C.DISPNAME AS CUSTOMERNAME,
        BK_CAN.CANTEENID, BK_CAN.CANTEENNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE AS STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT,
        B.BOOKEDBY, U.FULLNAME AS BOOKEDBYNAME, B.BOOKEDON,
        B.CANCELLEDBY, B.CANCELLEDON, B.SERVEDBY, B.SERVEDON, B.NOSHOWON, B.REMARKS
    FROM CMS_BOOKING B
    INNER JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    INNER JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    INNER JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    INNER JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    LEFT JOIN CMS_USER U ON U.USERID = B.BOOKEDBY
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
        FROM CMS_BOOKITEM BI
        JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN CMS_CANTEEN C  ON C.CANTEENID  = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE B.BOOKID = PBOOKID;

    SELECT 
        BI.BOOKITEMID, BI.DAYMENUID, BI.MENUITEMID, MI.MENUCODE, MI.ITEMNAME,
        BI.QTY, BI.RATE, BI.AMOUNT, BI.REMARKS, BI.STATUSID, BIST.STATUSCODE AS STATUSCODE
    FROM CMS_BOOKITEM BI
    INNER JOIN CMS_MENUITEM MI ON MI.MENUITEMID = BI.MENUITEMID
    INNER JOIN CMS_STATUS BIST ON BIST.STATUSID = BI.STATUSID
    WHERE BI.BOOKID = PBOOKID;
END$$

-- List bookings with optional filters (including Canteen scope)
CREATE PROCEDURE CMSLISTBOOK(
    IN PCUSTOMERID INT,
    IN PSERVICEID INT,
    IN PSTARTDATE DATE,
    IN PENDDATE DATE,
    IN PSTATUSCODE VARCHAR(10),
    IN PCANTEENID INT
)
BEGIN
    SELECT 
        B.BOOKID, B.BOOKNO, BT.BOOKTYPECODE, 
        B.CUSTOMERID, C.DISPNAME AS CUSTOMERNAME, CU.LOGINID,
        BK_CAN.CANTEENID, BK_CAN.CANTEENNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE AS STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT
    FROM CMS_BOOKING B
    INNER JOIN CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    INNER JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    INNER JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    LEFT JOIN CMS_USER CU ON CU.USERID = C.USERID
    INNER JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
        FROM CMS_BOOKITEM BI
        JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN CMS_CANTEEN C  ON C.CANTEENID  = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE (PCUSTOMERID IS NULL OR B.CUSTOMERID = PCUSTOMERID)
      AND (PSERVICEID IS NULL OR B.SERVICEID = PSERVICEID)
      AND (PSTARTDATE IS NULL OR B.SERVICEDATE >= PSTARTDATE)
      AND (PENDDATE IS NULL OR B.SERVICEDATE <= PENDDATE)
      AND (PSTATUSCODE IS NULL OR ST.STATUSCODE = PSTATUSCODE)
      AND (PCANTEENID IS NULL OR BK_CAN.CANTEENID = PCANTEENID)
    ORDER BY B.SERVICEDATE DESC, B.BOOKNO DESC;
END$$

-- Kitchen Prep summary
CREATE PROCEDURE CMSLISTKITCHENPREP (IN PDAYSLOTID INT)
BEGIN
    SELECT DM.DAYMENUID,
           DM.MENUITEMID,
           MI.ITEMNAME,
           MI.SHORTNAME,
           DM.MAXQTY AS PLANNED_QTY,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT', 'SRV', 'NOS') THEN BI.QTY ELSE 0 END), 0) AS TOTAL_BOOKED,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE = 'SRV' THEN BI.QTY ELSE 0 END), 0) AS TOTAL_SERVED,
           COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT', 'NOS') THEN BI.QTY ELSE 0 END), 0) AS REMAINING_QTY
    FROM   CMS_DAYMENU DM
    JOIN   CMS_STATUS DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN   CMS_MENUITEM MI ON MI.MENUITEMID = DM.MENUITEMID
    LEFT JOIN CMS_BOOKITEM BI ON BI.DAYMENUID = DM.DAYMENUID
    LEFT JOIN CMS_STATUS B_ST ON B_ST.STATUSID = BI.STATUSID AND B_ST.STATUSCODE IN ('CRT', 'SRV', 'NOS')
    WHERE  DM.DAYSLOTID = PDAYSLOTID
      AND  DM_ST.STATUSCODE = 'ACT'
    GROUP BY DM.DAYMENUID, DM.MENUITEMID, MI.ITEMNAME, MI.SHORTNAME, DM.MAXQTY
    ORDER BY MI.ITEMNAME;
END$$

-- Quick check of booking header for authorization and validation
CREATE PROCEDURE CMSGETBOOKINGBASIC (
    IN PBOOKID INT
)
BEGIN
    SELECT BOOKID, CUSTOMERID, STATUSID, SERVICEDATE, SERVICEID
    FROM CMS_BOOKING
    WHERE BOOKID = PBOOKID
    LIMIT 1;
END$$

-- List existing confirmed bookings for a customer in a date range (for prebooking calendar indicators)
CREATE PROCEDURE CMSLISTBOOKINGSOFRANGE (
    IN PCUSTOMERID INT,
    IN PSTARTDATE  DATE,
    IN PENDDATE    DATE
)
BEGIN
    SELECT B.BOOKID, B.BOOKNO, B.SERVICEID, S.SERVNAME, 
           DATE_FORMAT(B.SERVICEDATE, '%Y-%m-%d') AS SERVICEDATE, 
           B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT, ST.STATUSCODE
    FROM CMS_BOOKING B
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    WHERE B.CUSTOMERID = PCUSTOMERID
      AND B.SERVICEDATE BETWEEN PSTARTDATE AND PENDDATE
      AND ST.STATUSCODE NOT IN ('CAN')
    ORDER BY B.SERVICEDATE ASC, S.STARTTIME ASC;
END$$

-- Fetch single active confirmed booking for a customer in a meal slot context
CREATE PROCEDURE CMSGETACTIVEBOOKINGCTX (
    IN PCUSTOMERID INT,
    IN PCANTEENID  INT,
    IN PSERVICEID  INT,
    IN PSERVICEDATE DATE
)
BEGIN
    SELECT B.BOOKID, B.BOOKNO, B.CUSTOMERID, B.SERVICEID, B.SERVICEDATE,
           B.STATUSID, ST.STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT, B.BOOKEDON,
           BK_CAN.CANTEENID, BK_CAN.CANTEENNAME
    FROM CMS_BOOKING B
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
        FROM CMS_BOOKITEM BI
        JOIN CMS_DAYMENU DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN CMS_DAYSLOT DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN CMS_CANTEEN C  ON C.CANTEENID  = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, C.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE B.CUSTOMERID = PCUSTOMERID
      AND B.SERVICEDATE = PSERVICEDATE
      AND B.SERVICEID = PSERVICEID
      AND ST.STATUSCODE IN ('CRT')
      AND (PCANTEENID IS NULL OR BK_CAN.CANTEENID = PCANTEENID)
    ORDER BY B.BOOKID DESC
    LIMIT 1;
END$$

