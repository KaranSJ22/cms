USE cms_db;

DROP PROCEDURE IF EXISTS CMSGETWALLET;
DROP PROCEDURE IF EXISTS CMSLISTWALLETTRAN;
DROP PROCEDURE IF EXISTS CMSLISTWALLETWD;

DELIMITER $$

/* ============================================================
   PROCEDURE: CMSGETWALLET
   Returns current balance, reserved amount, and status
   ============================================================ */
CREATE PROCEDURE CMSGETWALLET
(
    IN PCUSTOMERID INT
)
BEGIN
    SELECT
        W.WALLETID,
        W.CUSTOMERID,
        W.BALANCE,
        W.RESERVEDAMT,
        (W.BALANCE - W.RESERVEDAMT) AS AVAILABLEBALANCE,
        W.STATUSID,
        ST.STATUSCODE AS STATUSCODE,
        W.CREATEDAT,
        W.UPDATEDAT
    FROM CMS_WALLET W
    JOIN CMS_STATUS ST ON ST.STATUSID = W.STATUSID
    WHERE W.CUSTOMERID = PCUSTOMERID;
END$$


/* ============================================================
   PROCEDURE: CMSLISTWALLETTRAN
   Returns wallet statement/passbook with optional pagination
   ============================================================ */
CREATE PROCEDURE CMSLISTWALLETTRAN
(
    IN PCUSTOMERID INT,
    IN PFROMDATE DATE,
    IN PTODATE DATE,
    IN PPAGE INT,
    IN PPAGESIZE INT
)
BEGIN
    DECLARE VOFFSET INT DEFAULT 0;
    DECLARE VTOTAL  INT DEFAULT 0;

    IF PPAGE IS NOT NULL AND PPAGESIZE IS NOT NULL THEN
        IF PPAGE < 1 THEN SET PPAGE = 1; END IF;
        IF PPAGESIZE < 1 THEN SET PPAGESIZE = 20; END IF;
        IF PPAGESIZE > 100 THEN SET PPAGESIZE = 100; END IF;
        SET VOFFSET = (PPAGE - 1) * PPAGESIZE;

        SELECT COUNT(*) INTO VTOTAL
        FROM CMS_WALLETTRAN WT
        JOIN CMS_WALLET W ON W.WALLETID = WT.WALLETID
        WHERE W.CUSTOMERID = PCUSTOMERID
          AND (PFROMDATE IS NULL OR DATE(WT.CREATEDAT) >= PFROMDATE)
          AND (PTODATE IS NULL OR DATE(WT.CREATEDAT) <= PTODATE);

        SELECT
            WT.WALLETTRANID,
            WT.WALLETID,
            WT.BOOKID,
            WT.BOOKID AS BOOKINGID,
            WT.TRANSTYPE,
            WT.SOURCECODE,
            WT.AMOUNT,
            WT.BALBEFORE,
            WT.BALAFTER,
            WT.PAYMENTMETHOD,
            WT.REFNO,
            WT.STATUSID,
            ST.STATUSCODE AS STATUSCODE,
            WT.CREATEDBY,
            WT.CREATEDAT,
            WT.REMARKS,

            B.SERVICEDATE,
            B.SERVICEDATE AS SERVDATE,
            B_ST.STATUSCODE AS BOOKINGSTATUSCODE,
            VTOTAL AS TOTALROWS,
            PPAGE AS CURRENTPAGE,
            PPAGESIZE AS PAGESIZE,
            CEIL(VTOTAL / PPAGESIZE) AS TOTALPAGES

        FROM CMS_WALLETTRAN WT
        JOIN CMS_WALLET W
          ON W.WALLETID = WT.WALLETID
        JOIN CMS_STATUS ST
          ON ST.STATUSID = WT.STATUSID

        LEFT JOIN CMS_BOOKING B
          ON B.BOOKID = WT.BOOKID
        LEFT JOIN CMS_STATUS B_ST
          ON B_ST.STATUSID = B.STATUSID

        WHERE W.CUSTOMERID = PCUSTOMERID
          AND (PFROMDATE IS NULL OR DATE(WT.CREATEDAT) >= PFROMDATE)
          AND (PTODATE IS NULL OR DATE(WT.CREATEDAT) <= PTODATE)

        ORDER BY WT.CREATEDAT DESC, WT.WALLETTRANID DESC
        LIMIT PPAGESIZE OFFSET VOFFSET;
    ELSE
        SELECT
            WT.WALLETTRANID,
            WT.WALLETID,
            WT.BOOKID,
            WT.BOOKID AS BOOKINGID,
            WT.TRANSTYPE,
            WT.SOURCECODE,
            WT.AMOUNT,
            WT.BALBEFORE,
            WT.BALAFTER,
            WT.PAYMENTMETHOD,
            WT.REFNO,
            WT.STATUSID,
            ST.STATUSCODE AS STATUSCODE,
            WT.CREATEDBY,
            WT.CREATEDAT,
            WT.REMARKS,

            B.SERVICEDATE,
            B.SERVICEDATE AS SERVDATE,
            B_ST.STATUSCODE AS BOOKINGSTATUSCODE

        FROM CMS_WALLETTRAN WT
        JOIN CMS_WALLET W
          ON W.WALLETID = WT.WALLETID
        JOIN CMS_STATUS ST
          ON ST.STATUSID = WT.STATUSID

        LEFT JOIN CMS_BOOKING B
          ON B.BOOKID = WT.BOOKID
        LEFT JOIN CMS_STATUS B_ST
          ON B_ST.STATUSID = B.STATUSID

        WHERE W.CUSTOMERID = PCUSTOMERID
          AND (PFROMDATE IS NULL OR DATE(WT.CREATEDAT) >= PFROMDATE)
          AND (PTODATE IS NULL OR DATE(WT.CREATEDAT) <= PTODATE)

        ORDER BY WT.CREATEDAT DESC, WT.WALLETTRANID DESC;
    END IF;
END$$


/* ============================================================
   PROCEDURE: CMSLISTWALLETWD
   Lists withdrawal requests for audit and processing.
   Supports customer-scoped view, canteen-scoped manager queue,
   and global admin view.
   ============================================================ */
CREATE PROCEDURE CMSLISTWALLETWD
(
    IN PCUSTOMERID INT,
    IN PSTATUSCODE VARCHAR(20),
    IN PCANTEENID INT
)
BEGIN
    SELECT
        WD.WALLETWDID,
        WD.WALLETID,
        W.CUSTOMERID,
        C.DISPNAME AS CUSTOMERNAME,
        C.DISPNAME,
        COALESCE(CE.CONTCODE, REQ_U.LOGINID) AS CONTCODE,
        CE.VENDORNAME,
        CE.DEFAULTCANTEENID AS CANTEENID,
        CN.CANTEENNAME,
        CN.CANTEENCODE,
        WD.AMOUNT,
        WD.STATUSID,
        ST.STATUSCODE AS STATUSCODE,
        WD.REQUESTEDBY,
        REQ_U.FULLNAME AS REQUESTEDBYNAME,
        WD.REQUESTEDAT,
        WD.PROCESSEDBY,
        PROC_U.FULLNAME AS PROCESSEDBYNAME,
        WD.PROCESSEDAT,
        WD.PAYMENTMETHOD,
        WD.REFNO,
        WD.REMARKS
    FROM CMS_WALLETWD WD
    JOIN CMS_WALLET W
      ON W.WALLETID = WD.WALLETID
    JOIN CMS_CUSTOMER C
      ON C.CUSTOMERID = W.CUSTOMERID
    LEFT JOIN CMS_CONTEMP CE
      ON CE.CUSTOMERID = W.CUSTOMERID
    LEFT JOIN CMS_CANTEEN CN
      ON CN.CANTEENID = CE.DEFAULTCANTEENID
    JOIN CMS_STATUS ST
      ON ST.STATUSID = WD.STATUSID
    LEFT JOIN CMS_USER REQ_U
      ON REQ_U.USERID = WD.REQUESTEDBY
    LEFT JOIN CMS_USER PROC_U
      ON PROC_U.USERID = WD.PROCESSEDBY
    WHERE (PCUSTOMERID IS NULL OR W.CUSTOMERID = PCUSTOMERID)
      AND (PSTATUSCODE IS NULL OR ST.STATUSCODE = PSTATUSCODE)
      AND (PCUSTOMERID IS NOT NULL OR PCANTEENID IS NULL OR CE.DEFAULTCANTEENID = PCANTEENID)
    ORDER BY WD.REQUESTEDAT DESC, WD.WALLETWDID DESC;
END$$

DELIMITER ;
