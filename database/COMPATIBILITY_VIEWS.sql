USE cms_db;

/* ============================================================
   BACKWARD-COMPATIBILITY VIEWS
   These views ensure zero downtime during rollout so that existing 
   raw queries and clients continuing to use legacy table and column 
   names do not fail with ER_NO_SUCH_TABLE or missing column errors.
   ============================================================ */

-- 1. Legacy CMS_CONSUMERROLE mapped to CMS_USERROLE
CREATE OR REPLACE VIEW CMS_CONSUMERROLE AS 
SELECT 
    USERROLEID AS USRROLEID,
    USERROLEID,
    USERID,
    ROLEID,
    ASSIGNEDBY,
    ASSIGNEDAT,
    VALIDFROM,
    VALIDUNTIL,
    ISACTIVE
FROM CMS_USERROLE;

-- 2. Legacy CMS_KIOSK_DEVICE mapped to CMS_KIOSK
CREATE OR REPLACE VIEW CMS_KIOSK_DEVICE AS 
SELECT 
    KIOSKID,
    DEVICECODE,
    DEVICENAME,
    IPADDRESS,
    MACADDRESS,
    CANTEENID,
    KIOSKTYPE,
    STATUSID,
    1 AS ISACTIVE,
    LASTHEARTBEATAT,
    LASTSEENIP,
    CREATEDBY,
    CREATEDAT,
    UPDATEDBY,
    UPDATEDAT
FROM CMS_KIOSK;

-- 3. Legacy CMS_ITEMPRICEDT mapped to CMS_ITMPRICDT
CREATE OR REPLACE VIEW CMS_ITEMPRICEDT AS 
SELECT 
    ITMPRICDTID AS ITEMPRICEDTID,
    ITMPRICDTID,
    ITEMPRICEID,
    CTYPEID,
    CTYPECODE,
    PRICE
FROM CMS_ITMPRICDT;

-- 4. Legacy CMS_OFFCOMBO_ITEM mapped to CMS_OFFCOMBDT
CREATE OR REPLACE VIEW CMS_OFFCOMBO_ITEM AS 
SELECT 
    OFFCOMBDTID AS COMBOITEMID,
    OFFCOMBDTID,
    OFFCOMBOID,
    MENUITEMID,
    QTY
FROM CMS_OFFCOMBDT;

-- 5. Legacy CMS_BOOKITMHS mapped to CMS_BOOKITMHST
CREATE OR REPLACE VIEW CMS_BOOKITMHS AS 
SELECT 
    BOOKITMHSTID AS BOOKITMHSID,
    BOOKITMHSTID,
    BOOKHISTID,
    BOOKITEMID,
    DAYMENUID,
    MENUITEMID,
    QTY,
    RATE,
    AMOUNT,
    REMARKS,
    CHANGEDAT,
    STATUSID
FROM CMS_BOOKITMHST;

-- 6. Legacy CMS_ROLESCN mapped to CMS_SCRNROLE
CREATE OR REPLACE VIEW CMS_ROLESCN AS 
SELECT 
    SCRNROLEID AS ROLESCNID,
    SCRNROLEID,
    ROLEID,
    SCREENID,
    CANREAD AS CANVIEW,
    CANWRITE AS CANCREATE,
    CANWRITE AS CANUPDATE,
    CANWRITE AS CANDELETE,
    1 AS ISACTIVE,
    CREATEDBY,
    CREATEDAT,
    UPDATEDAT
FROM CMS_SCRNROLE;
