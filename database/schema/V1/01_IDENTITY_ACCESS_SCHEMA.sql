   ============================================================ */

USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_ROLESCN;
DROP TABLE IF EXISTS CMS_APPLVL;
DROP TABLE IF EXISTS CMS_ACCKEY;
DROP TABLE IF EXISTS CMS_VISITOR;
DROP TABLE IF EXISTS CMS_OCEEMP;
DROP TABLE IF EXISTS CMS_CONTEMP;
DROP TABLE IF EXISTS CMS_PERMEMP;
DROP TABLE IF EXISTS CMS_CUSTOMER;
DROP TABLE IF EXISTS CMS_USRROLE;
DROP TABLE IF EXISTS CMS_ROLE;
DROP TABLE IF EXISTS CMS_USER;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE CMS_USER (
    USERID INT AUTO_INCREMENT PRIMARY KEY,
    LOGINID VARCHAR(50) NOT NULL UNIQUE,
    FULLNAME VARCHAR(120) NOT NULL,
    EMAIL VARCHAR(120) NULL UNIQUE,
    MOBILENO VARCHAR(20) NULL,
    PWDHASH VARCHAR(255) NOT NULL,
    AUTHPROV VARCHAR(20) NOT NULL DEFAULT 'LOCAL',
    AUTHID VARCHAR(120) NULL,
    ISACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE CMS_ROLE (
    ROLEID INT AUTO_INCREMENT PRIMARY KEY,
    ROLECODE VARCHAR(50) NOT NULL UNIQUE,
    ROLENAME VARCHAR(100) NOT NULL,
    DESCR VARCHAR(255),
    ISACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE CMS_USRROLE (
    USRROLEID INT AUTO_INCREMENT PRIMARY KEY,
    USERID INT NOT NULL,
    ROLEID INT NOT NULL,
    ASSIGNEDBY INT NULL,
    ASSIGNEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    ISACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    UNIQUE KEY UQ_USRROLE (USERID, ROLEID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USERID) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID),
    CONSTRAINT FK_UR_BY FOREIGN KEY (ASSIGNEDBY) REFERENCES CMS_USER(USERID)
) ENGINE=InnoDB;

CREATE TABLE CMS_ROLESCN (
    ROLESCNID INT AUTO_INCREMENT PRIMARY KEY,
    ROLEID INT NOT NULL,
    SCREENID INT NOT NULL,
    CANVIEW TINYINT(1) NOT NULL DEFAULT 0,
    CANCREATE TINYINT(1) NOT NULL DEFAULT 0,
    CANUPDATE TINYINT(1) NOT NULL DEFAULT 0,
    CANDELETE TINYINT(1) NOT NULL DEFAULT 0,
    ISACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_ROLESCN (ROLEID, SCREENID),
    CONSTRAINT FK_RS_ROLE FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID),
    CONSTRAINT FK_RS_SCREEN FOREIGN KEY (SCREENID) REFERENCES CMS_SCREEN(SCREENID)
) ENGINE=InnoDB;

CREATE TABLE CMS_CUSTOMER (
    CUSTOMERID INT AUTO_INCREMENT PRIMARY KEY,
    USERID INT NULL UNIQUE,
    CTYPECODE VARCHAR(20) NOT NULL,
    DISPNAME VARCHAR(120) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'A',
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_CUST_USER FOREIGN KEY (USERID) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_CUST_TYPE FOREIGN KEY (CTYPECODE) REFERENCES CMS_CUSTTYPE(CTYPECODE)
) ENGINE=InnoDB;

CREATE TABLE CMS_PERMEMP (
    PERMEMPID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMERID INT NOT NULL UNIQUE,
    EMPCODE VARCHAR(50) NOT NULL UNIQUE,
    DEPT VARCHAR(100) NOT NULL,
    DESIG VARCHAR(100) NOT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_PE_CUST FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID)
) ENGINE=InnoDB;

CREATE TABLE CMS_CONTEMP (
    CONTEMPID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMERID INT NOT NULL UNIQUE,
    CONTCODE VARCHAR(50) NOT NULL UNIQUE,
    VENDORNAME VARCHAR(150) NOT NULL,
    CONTSTART DATE NOT NULL,
    CONTEND DATE NOT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_CE_CUST FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID),
    CONSTRAINT CK_CONT_DATES CHECK (CONTEND >= CONTSTART)
) ENGINE=InnoDB;

CREATE TABLE CMS_OCEEMP (
    OCEEMPID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMERID INT NOT NULL UNIQUE,
    EMPCODE VARCHAR(50) NOT NULL,
    CENTRENAME VARCHAR(120) NOT NULL,
    DEPT VARCHAR(100),
    DESIG VARCHAR(100),
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_OCE_CODE_CENTRE (EMPCODE, CENTRENAME),
    CONSTRAINT FK_OCE_CUST FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID)
) ENGINE=InnoDB;

CREATE TABLE CMS_VISITOR (
    VISITORID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMERID INT NOT NULL UNIQUE,
    VISNAME VARCHAR(120) NOT NULL,
    VISMOBILE VARCHAR(20),
    VISORG VARCHAR(150),
    VISPURPOSE VARCHAR(255),
    VISDATE DATE NOT NULL,
    VALIDUNTIL DATETIME NOT NULL,
    CREATEDBY INT NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'A',
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_VIS_CUST FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID),
    CONSTRAINT FK_VIS_BY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID)
) ENGINE=InnoDB;

CREATE TABLE CMS_ACCKEY (
    ACCKEYID INT AUTO_INCREMENT PRIMARY KEY,
    CUSTOMERID INT NOT NULL,
    KEYTYPE VARCHAR(30) NOT NULL,
    KEYVALUE VARCHAR(255) NOT NULL UNIQUE,
    EXPIRESAT DATETIME NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'A',
    CREATEDBY INT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    LASTUSEDAT DATETIME NULL,
    CONSTRAINT FK_AK_CUST FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID),
    CONSTRAINT FK_AK_BY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT CK_KEYTYPE CHECK (KEYTYPE IN ('QR','RFID','EMPCARD','VISPASS','TEMPTOKEN'))
) ENGINE=InnoDB;

CREATE TABLE CMS_APPLVL (
    APPLVLID INT AUTO_INCREMENT PRIMARY KEY,
    LEVELNO INT NOT NULL UNIQUE,
    LEVELNAME VARCHAR(100) NOT NULL,
    ROLEID INT NOT NULL,
    DESCR VARCHAR(255),
    ISACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_AL_ROLE FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID)
) ENGINE=InnoDB;

