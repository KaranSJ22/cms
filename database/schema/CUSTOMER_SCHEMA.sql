USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_CUSTOMER;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE CMS_CUSTOMER (
    CUSTOMERID INT AUTO_INCREMENT PRIMARY KEY,
    USERID INT NULL UNIQUE,
    CTYPEID INT NOT NULL,
    DISPNAME VARCHAR(120) NOT NULL,
    STATUSID INT NOT NULL DEFAULT 10,
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    CREATEDBY INT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_CUSTOMER_USERID FOREIGN KEY (USERID) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_CUSTOMER_CTYPEID FOREIGN KEY (CTYPEID) REFERENCES CMS_CUSTTYPE(CTYPEID),
    CONSTRAINT FK_CUSTOMER_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT FK_CUSTOMER_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID)
) ENGINE=InnoDB;
