USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_KIOSK;
DROP TABLE IF EXISTS CMS_KIOSK_DEVICE;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_KIOSK -- Hardware Kiosk Device Registry
   Maps Raspberry Pi network IPs and physical stations to canteens
   ============================================================ */
CREATE TABLE CMS_KIOSK (
    KIOSKID INT AUTO_INCREMENT PRIMARY KEY,
    DEVICECODE VARCHAR(30) NOT NULL UNIQUE,                -- e.g. 'KSK-COUNTER-01', 'KSK-LOBBY-01'
    DEVICENAME VARCHAR(100) NOT NULL,                      -- e.g. 'Canteen A Serving Counter 1'
    IPADDRESS VARCHAR(45) NOT NULL UNIQUE,                 -- Raspberry Pi Static IPv4 / IPv6
    MACADDRESS VARCHAR(17) NULL,                           -- Hardware MAC address
    CANTEENID INT NOT NULL,                                -- Scoped Canteen Facility
    KIOSKTYPE VARCHAR(30) NOT NULL DEFAULT 'EMP_SELF_SERVICE',
    STATUSID INT NOT NULL DEFAULT 10,                      -- 10 = 'ACT' (Active)
    LASTHEARTBEATAT DATETIME NULL,
    LASTSEENIP VARCHAR(45) NULL,
    CREATEDBY INT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDBY INT NULL,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_KIOSK_CANTEENID FOREIGN KEY (CANTEENID) REFERENCES CMS_CANTEEN(CANTEENID),
    CONSTRAINT FK_KIOSK_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT FK_KIOSK_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_KIOSK_UPDATEDBY FOREIGN KEY (UPDATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT CK_KIOSK_TYPE CHECK (KIOSKTYPE IN ('STAFF_COUNTER', 'EMP_SELF_SERVICE')),
    KEY IX_KIOSK_CANTEEN_TYPE (CANTEENID, KIOSKTYPE)
) ENGINE=InnoDB;
