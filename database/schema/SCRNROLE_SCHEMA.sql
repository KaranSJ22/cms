USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_SCRNROLE;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_SCRNROLE -- Maps user roles to allowable application screens
   ============================================================ */
CREATE TABLE CMS_SCRNROLE (
    SCRNROLEID INT AUTO_INCREMENT PRIMARY KEY,
    ROLEID     INT NOT NULL,
    SCREENID   INT NOT NULL,
    CANREAD    BOOLEAN NOT NULL DEFAULT 1,
    CANWRITE   BOOLEAN NOT NULL DEFAULT 0,
    CREATEDBY  INT NULL,
    CREATEDAT  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT  DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_SCRNROLE (ROLEID, SCREENID),
    CONSTRAINT FK_SCRNROLE_ROLEID FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID),
    CONSTRAINT FK_SCRNROLE_SCREENID FOREIGN KEY (SCREENID) REFERENCES CMS_SCREEN(SCREENID),
    CONSTRAINT FK_SCRNROLE_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT CK_SCRNROLE_PERMS CHECK (CANREAD IN (0, 1) AND CANWRITE IN (0, 1))
) ENGINE=InnoDB;
