USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_ITMPRICDT;
DROP TABLE IF EXISTS CMS_ITEMPRICEDT;
DROP TABLE IF EXISTS CMS_ITEMPRICE;
DROP TABLE IF EXISTS CMS_MENUHIST;
DROP TABLE IF EXISTS CMS_MENUITEM;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_MENUITEM -- Shared catalog, no price columns (see CMS_ITEMPRICE)
   ============================================================ */
CREATE TABLE CMS_MENUITEM (
    MENUITEMID INT AUTO_INCREMENT PRIMARY KEY,
    SERVICEID  INT NULL,                             -- Primary Service / Meal Category (NULL = All Services/Generic)
    MENUCODE   VARCHAR(20) NOT NULL UNIQUE,          -- Auto-generated via CMSGENAUTO (Prefix: ITM)
    SHORTNAME  VARCHAR(30) NOT NULL,
    ITEMNAME   VARCHAR(100) NOT NULL,
    DESCR      VARCHAR(255),
    ISSPECIAL  BOOLEAN NOT NULL DEFAULT 0,
    ISOFFSER   BOOLEAN NOT NULL DEFAULT 0,
    STATUSID   INT NOT NULL DEFAULT 10,              -- 10 = 'ACT' (Active)
    CREATEDBY  INT NOT NULL,
    CREATEDAT  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT  DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_MENUITEM_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_MENUITEM_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_MENUITEM_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_MENUITEM_FLAGS CHECK (ISSPECIAL IN (0, 1) AND ISOFFSER IN (0, 1)),
    INDEX IX_MI_SERVICEID (SERVICEID)
) ENGINE=InnoDB;

CREATE TABLE CMS_MENUHIST (
    MENUHISTID INT AUTO_INCREMENT PRIMARY KEY,
    MENUITEMID INT NOT NULL,
    SERVICEID  INT NULL,
    MENUCODE   VARCHAR(20) NOT NULL,
    SHORTNAME  VARCHAR(30) NOT NULL,
    ITEMNAME   VARCHAR(100) NOT NULL,
    DESCR      VARCHAR(255),
    ISSPECIAL  BOOLEAN NOT NULL,
    ISOFFSER   BOOLEAN NOT NULL DEFAULT 0,
    STATUSID   INT NOT NULL,
    CHANGEDBY  INT NOT NULL,
    CHANGEDAT  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHGREASON  VARCHAR(255),
    CONSTRAINT FK_MENUHIST_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_MENUHIST_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_MENUHIST_CHANGEDBY FOREIGN KEY (CHANGEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_MENUHIST_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_MENUHIST_FLAGS CHECK (ISSPECIAL IN (0, 1) AND ISOFFSER IN (0, 1))
) ENGINE=InnoDB;

/* ============================================================
   CMS_ITEMPRICE (header) + CMS_ITMPRICDT (per customer-type detail)
   ============================================================ */
CREATE TABLE CMS_ITEMPRICE (
    ITEMPRICEID INT AUTO_INCREMENT PRIMARY KEY,
    MENUITEMID  INT NOT NULL,
    EFFFROM     DATE NOT NULL,
    STATUSID    INT NOT NULL DEFAULT 10,              -- 10 = 'ACT' (Active)
    CREATEDBY   INT NOT NULL,
    CREATEDAT   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT   DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_ITEMPRICE (MENUITEMID, EFFFROM),
    CONSTRAINT FK_ITEMPRICE_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_ITEMPRICE_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_ITEMPRICE_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID)
) ENGINE=InnoDB;

CREATE TABLE CMS_ITMPRICDT (
    ITMPRICDTID INT AUTO_INCREMENT PRIMARY KEY,
    ITEMPRICEID INT NOT NULL,
    CTYPEID     INT NOT NULL,
    PRICE       DECIMAL(10,2) NOT NULL,
    UNIQUE KEY UQ_ITMPRICDT (ITEMPRICEID, CTYPEID),
    CONSTRAINT FK_ITMPRICDT_ITEMPRICEID FOREIGN KEY (ITEMPRICEID) REFERENCES CMS_ITEMPRICE(ITEMPRICEID),
    CONSTRAINT FK_ITMPRICDT_CTYPEID FOREIGN KEY (CTYPEID) REFERENCES CMS_CUSTTYPE(CTYPEID),
    CONSTRAINT CK_ITMPRICDT_PRICE CHECK (PRICE >= 0)
) ENGINE=InnoDB;