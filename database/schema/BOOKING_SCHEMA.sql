USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_BOOKITMHST;
DROP TABLE IF EXISTS CMS_BOOKITMHS;
DROP TABLE IF EXISTS CMS_BOOKHIST;
DROP TABLE IF EXISTS CMS_PBACTIVE;
DROP TABLE IF EXISTS CMS_BOOKITEM;
DROP TABLE IF EXISTS CMS_BOOKING;
DROP TABLE IF EXISTS CMS_BOOKCTR;
DROP TABLE IF EXISTS CMS_BOOKTYPE;

SET FOREIGN_KEY_CHECKS = 1;

-- ------------------------------------------------------------
-- Booking type master (PB = Pre-Booking, KS = Kiosk, WI = Walk-in)
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKTYPE (
    BOOKTYPEID INT AUTO_INCREMENT PRIMARY KEY,
    BOOKTYPECODE VARCHAR(10) NOT NULL UNIQUE,
    BOOKTYPENAME VARCHAR(50) NOT NULL,
    STATUSID INT NOT NULL DEFAULT 10,                     -- 10 = 'ACT' (Active)
    CREATEDBY INT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDBY INT NULL,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_BOOKTYPE_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKTYPE_UPDATEDBY FOREIGN KEY (UPDATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKTYPE_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Lifetime booking-number counter, scoped per booking type + service.
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKCTR (
    BOOKTYPEID INT NOT NULL,
    SERVICEID INT NOT NULL,
    LASTNO BIGINT NOT NULL DEFAULT 0,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (BOOKTYPEID, SERVICEID),
    CONSTRAINT FK_BOOKCTR_BOOKTYPEID FOREIGN KEY (BOOKTYPEID) REFERENCES CMS_BOOKTYPE(BOOKTYPEID),
    CONSTRAINT FK_BOOKCTR_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Booking header
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKING (
    BOOKID INT AUTO_INCREMENT PRIMARY KEY,
    BOOKNO VARCHAR(35) NOT NULL UNIQUE,
    BOOKTYPEID INT NOT NULL,
    CUSTOMERID INT NOT NULL,
    SERVICEID INT NOT NULL,
    SERVICEDATE DATE NOT NULL,
    STATUSID INT NOT NULL DEFAULT 30,                     -- 30 = 'CRT' (Created)
    BOOKSEQNO BIGINT NOT NULL,
    TOTALITEMS INT NOT NULL DEFAULT 0,
    TOTALQTY INT NOT NULL DEFAULT 0,
    TOTALAMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    BOOKEDBY INT NOT NULL,
    BOOKEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CANCELLEDBY INT NULL,
    CANCELLEDAT DATETIME NULL,
    SERVEDBY INT NULL,
    SERVEDAT DATETIME NULL,
    NOSHOWAT DATETIME NULL,
    KIOSKID INT NULL,
    REMARKS VARCHAR(255),
    CREATEDBY INT NOT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDBY INT NULL,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_BOOKING_BOOKTYPEID FOREIGN KEY (BOOKTYPEID) REFERENCES CMS_BOOKTYPE(BOOKTYPEID),
    CONSTRAINT FK_BOOKING_CUSTOMERID FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID),
    CONSTRAINT FK_BOOKING_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_BOOKING_BOOKEDBY FOREIGN KEY (BOOKEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKING_CANCELLEDBY FOREIGN KEY (CANCELLEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKING_SERVEDBY FOREIGN KEY (SERVEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKING_KIOSKID FOREIGN KEY (KIOSKID) REFERENCES CMS_KIOSK(KIOSKID),
    CONSTRAINT FK_BOOKING_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKING_UPDATEDBY FOREIGN KEY (UPDATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKING_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_BK_TOTALS CHECK (TOTALITEMS >= 0 AND TOTALQTY >= 0 AND TOTALAMOUNT >= 0),
    KEY IX_BK_CUST_SVC_DATE (CUSTOMERID, SERVICEID, SERVICEDATE),
    KEY IX_BK_SVC_DATE_STATUS (SERVICEID, SERVICEDATE, STATUSID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Booking detail
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKITEM (
    BOOKITEMID BIGINT AUTO_INCREMENT PRIMARY KEY,
    BOOKID INT NOT NULL,
    DAYMENUID INT NOT NULL,
    MENUITEMID INT NOT NULL,
    QTY INT NOT NULL,
    RATE DECIMAL(10,2) NOT NULL,
    AMOUNT DECIMAL(12,2) NOT NULL,
    REMARKS VARCHAR(255),
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    STATUSID INT NOT NULL DEFAULT 30,                     -- 30 = 'CRT' (Created)
    UNIQUE KEY UQ_BOOKITEM (BOOKID, DAYMENUID),
    CONSTRAINT FK_BOOKITEM_BOOKID FOREIGN KEY (BOOKID) REFERENCES CMS_BOOKING(BOOKID),
    CONSTRAINT FK_BOOKITEM_DAYMENUID FOREIGN KEY (DAYMENUID) REFERENCES CMS_DAYMENU(DAYMENUID),
    CONSTRAINT FK_BOOKITEM_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_BOOKITEM_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_BI_QTY CHECK (QTY >= 1),
    CONSTRAINT CK_BI_RATE CHECK (RATE >= 0),
    CONSTRAINT CK_BI_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT CK_BI_AMOUNT_CALC CHECK (AMOUNT = QTY * RATE),
    KEY IX_BI_DAYMENU (DAYMENUID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Active Pre-Booking constraint table (PB = Pre-Booking)
-- ------------------------------------------------------------
CREATE TABLE CMS_PBACTIVE (
    CUSTOMERID INT NOT NULL,
    SERVICEID INT NOT NULL,
    SERVICEDATE DATE NOT NULL,
    BOOKID INT NOT NULL UNIQUE,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (CUSTOMERID, SERVICEID, SERVICEDATE),
    CONSTRAINT FK_PBACTIVE_CUSTOMERID FOREIGN KEY (CUSTOMERID) REFERENCES CMS_CUSTOMER(CUSTOMERID),
    CONSTRAINT FK_PBACTIVE_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_PBACTIVE_BOOKID FOREIGN KEY (BOOKID) REFERENCES CMS_BOOKING(BOOKID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Booking header history
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKHIST (
    BOOKHISTID BIGINT AUTO_INCREMENT PRIMARY KEY,
    BOOKID INT NOT NULL,
    BOOKNO VARCHAR(35) NOT NULL,
    BOOKTYPEID INT NOT NULL,
    CUSTOMERID INT NOT NULL,
    SERVICEID INT NOT NULL,
    SERVICEDATE DATE NOT NULL,
    STATUSID INT NOT NULL,
    BOOKSEQNO BIGINT NOT NULL,
    TOTALITEMS INT NOT NULL,
    TOTALQTY INT NOT NULL,
    TOTALAMOUNT DECIMAL(12,2) NOT NULL,
    BOOKEDBY INT NOT NULL,
    BOOKEDAT DATETIME NOT NULL,
    CANCELLEDBY INT NULL,
    CANCELLEDAT DATETIME NULL,
    SERVEDBY INT NULL,
    SERVEDAT DATETIME NULL,
    NOSHOWAT DATETIME NULL,
    KIOSKID INT NULL,
    REMARKS VARCHAR(255),
    CREATEDBY INT NOT NULL,
    CREATEDAT DATETIME NOT NULL,
    UPDATEDBY INT NULL,
    UPDATEDAT DATETIME NULL,
    CHANGEDBY INT NOT NULL,
    CHGREASON VARCHAR(255),
    CHANGEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BOOKHIST_BOOKID FOREIGN KEY (BOOKID) REFERENCES CMS_BOOKING(BOOKID),
    CONSTRAINT FK_BOOKHIST_CHANGEDBY FOREIGN KEY (CHANGEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_BOOKHIST_KIOSKID FOREIGN KEY (KIOSKID) REFERENCES CMS_KIOSK(KIOSKID),
    CONSTRAINT FK_BOOKHIST_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    KEY IX_BH_BOOK (BOOKID)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- Booking item history
-- ------------------------------------------------------------
CREATE TABLE CMS_BOOKITMHST (
    BOOKITMHSTID BIGINT AUTO_INCREMENT PRIMARY KEY,
    BOOKHISTID BIGINT NOT NULL,
    BOOKITEMID BIGINT NOT NULL,
    DAYMENUID INT NOT NULL,
    MENUITEMID INT NOT NULL,
    QTY INT NOT NULL,
    RATE DECIMAL(10,2) NOT NULL,
    AMOUNT DECIMAL(12,2) NOT NULL,
    REMARKS VARCHAR(255),
    CHANGEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    STATUSID INT NOT NULL DEFAULT 30,
    CONSTRAINT FK_BOOKITMHST_BOOKHISTID FOREIGN KEY (BOOKHISTID) REFERENCES CMS_BOOKHIST(BOOKHISTID),
    CONSTRAINT FK_BOOKITMHST_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_BOOKITMHST_DAYMENUID FOREIGN KEY (DAYMENUID) REFERENCES CMS_DAYMENU(DAYMENUID),
    CONSTRAINT FK_BOOKITMHST_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    KEY IX_BOOKITMHST_BOOKHISTID (BOOKHISTID)
) ENGINE=InnoDB;