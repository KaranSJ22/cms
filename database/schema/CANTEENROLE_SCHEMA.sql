USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_CANTEENROLE;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE CMS_CANTEENROLE (
    CANTEENROLEID INT AUTO_INCREMENT PRIMARY KEY,
    USERID INT NOT NULL,
    ROLEID INT NOT NULL,
    CANTEENID INT NOT NULL,
    ISDEFAULT BOOLEAN NOT NULL DEFAULT 0,
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    ISACTIVE BOOLEAN NOT NULL DEFAULT 1,
    ASSIGNEDBY INT NULL,
    ASSIGNEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_CANTEENROLE (USERID, ROLEID, CANTEENID),
    CONSTRAINT FK_CANTEENROLE_USERID FOREIGN KEY (USERID) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_CANTEENROLE_ROLEID FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID),
    CONSTRAINT FK_CANTEENROLE_CANTEENID FOREIGN KEY (CANTEENID) REFERENCES CMS_CANTEEN(CANTEENID),
    CONSTRAINT FK_CANTEENROLE_ASSIGNEDBY FOREIGN KEY (ASSIGNEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT CK_CANTEENROLE_FLAGS CHECK (ISDEFAULT IN (0, 1) AND ISACTIVE IN (0, 1))
) ENGINE=InnoDB;
