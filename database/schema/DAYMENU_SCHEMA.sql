USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_DMENUHIST;
DROP TABLE IF EXISTS CMS_DAYMENU;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_DAYMENU -- Item offered on a specific day-slot.
   STATUSID    = Operational availability (10=ACT, 11=DIS)
   ============================================================ */

CREATE TABLE CMS_DAYMENU (
    DAYMENUID   INT AUTO_INCREMENT PRIMARY KEY,
    DMENUNO     VARCHAR(20) NOT NULL UNIQUE,          -- Auto-generated via CMSGENAUTO
    DAYSLOTID   INT NOT NULL,
    MENUITEMID  INT NOT NULL,
    ISBASE      BOOLEAN NOT NULL DEFAULT 1,
    ISSPECIAL   BOOLEAN NOT NULL DEFAULT 0,
    ISPREBOOK   BOOLEAN NOT NULL DEFAULT 1,
    ISKIOSK     BOOLEAN NOT NULL DEFAULT 1,
    BOOKUNTIL   DATETIME NOT NULL,
    CANCELUNTIL DATETIME NOT NULL,   
    AVAILQTY    INT NULL,
    MAXQTY      INT NOT NULL DEFAULT 1,
    STATUSID    INT NOT NULL DEFAULT 10,              -- 10 = 'ACT' (Active)
    CREATEDAT   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATEDBY   INT NOT NULL,
    UPDATEDAT   DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_DAYMENU (DAYSLOTID, MENUITEMID),
    CONSTRAINT FK_DAYMENU_DAYSLOTID FOREIGN KEY (DAYSLOTID) REFERENCES CMS_DAYSLOT(DAYSLOTID),
    CONSTRAINT FK_DAYMENU_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_DAYMENU_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_DAYMENU_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_DM_QTY CHECK (MAXQTY >= 1 AND (AVAILQTY IS NULL OR AVAILQTY >= 0)),
    CONSTRAINT CK_DM_CHANNELS CHECK (ISBASE IN (0, 1) AND ISPREBOOK IN (0, 1) AND ISKIOSK IN (0, 1) AND ISSPECIAL IN (0, 1)),
    CONSTRAINT CK_DM_TIMES CHECK (CANCELUNTIL <= BOOKUNTIL)
) ENGINE=InnoDB;

CREATE TABLE CMS_DMENUHIST (
    DMENUHISTID INT AUTO_INCREMENT PRIMARY KEY,
    DAYMENUID   INT NOT NULL,                         -- Historical reference (no FK constraint to permit parent deletion)
    DMENUNO     VARCHAR(20) NOT NULL,                 -- Historical tracking of generated ID
    DAYSLOTID   INT NOT NULL,
    MENUITEMID  INT NOT NULL,
    ISSPECIAL   BOOLEAN NOT NULL,
    ISPREBOOK   BOOLEAN NOT NULL,
    ISKIOSK     BOOLEAN NOT NULL,
    ISBASE      BOOLEAN NOT NULL,
    BOOKUNTIL   DATETIME NOT NULL,
    CANCELUNTIL DATETIME NOT NULL,
    AVAILQTY    INT NULL,
    MAXQTY      INT NOT NULL,
    STATUSID    INT NOT NULL,
    CHANGEDBY   INT NOT NULL,
    CHANGEDAT   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHGREASON   VARCHAR(255),
    CONSTRAINT FK_DMENUHIST_DAYSLOTID FOREIGN KEY (DAYSLOTID) REFERENCES CMS_DAYSLOT(DAYSLOTID),
    CONSTRAINT FK_DMENUHIST_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT FK_DMENUHIST_CHANGEDBY FOREIGN KEY (CHANGEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_DMENUHIST_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_DMH_CHANNELS CHECK (ISBASE IN (0, 1) AND ISPREBOOK IN (0, 1) AND ISKIOSK IN (0, 1) AND ISSPECIAL IN (0, 1))
) ENGINE=InnoDB;