USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_SLOTHIST;
DROP TABLE IF EXISTS CMS_DAYSLOT;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_DAYSLOT -- Dated instance of a service, explicitly scoped
   to a facility by CANTEENID and meal timing by SERVICEID.
   ============================================================ */

CREATE TABLE CMS_DAYSLOT (
    DAYSLOTID INT AUTO_INCREMENT PRIMARY KEY,
    SLOTNO VARCHAR(30) NOT NULL UNIQUE,             -- Auto-generated ID (e.g., SLT202608220001)
    SERVICEID INT NOT NULL,
    SERVICEDATE DATE NOT NULL,
    CANTEENID INT NOT NULL,
    STARTTIME TIME NOT NULL,
    ENDTIME   TIME NOT NULL,
    STATUSID  INT NOT NULL DEFAULT 10,              -- 10 = 'ACT'
    APPRSTATUSID INT NOT NULL DEFAULT 20,           -- 20 = 'DRF'
    MENUSUBMITTEDBY INT NULL,
    MENUSUBMITTEDAT DATETIME NULL,
    MENUAPPROVEDBY INT NULL,
    MENUAPPROVEDAT DATETIME NULL,
    MENUREMARKS VARCHAR(255) NULL,
    CREATEDBY INT NOT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_DAYSLOT (CANTEENID, SERVICEID, SERVICEDATE),
    CONSTRAINT FK_DAYSLOT_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_DAYSLOT_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_DAYSLOT_CANTEENID FOREIGN KEY (CANTEENID) REFERENCES CMS_CANTEEN(CANTEENID),
    CONSTRAINT FK_DAYSLOT_MENUSUBMITTEDBY FOREIGN KEY (MENUSUBMITTEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_DAYSLOT_MENUAPPROVEDBY FOREIGN KEY (MENUAPPROVEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_DAYSLOT_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT FK_DAYSLOT_APPRSTATUSID FOREIGN KEY (APPRSTATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_DS_TIME CHECK (ENDTIME > STARTTIME)
) ENGINE=InnoDB;

CREATE TABLE CMS_SLOTHIST (
    SLOTHISTID INT AUTO_INCREMENT PRIMARY KEY,
    DAYSLOTID  INT NOT NULL,
    SLOTNO     VARCHAR(30) NOT NULL,
    SERVICEID  INT NOT NULL,
    CANTEENID  INT NOT NULL,
    SERVICEDATE DATE NOT NULL,
    STARTTIME  TIME NOT NULL,
    ENDTIME    TIME NOT NULL,
    STATUSID   INT NOT NULL,
    APPRSTATUSID INT NOT NULL,
    MENUSUBMITTEDBY INT NULL,
    MENUSUBMITTEDAT DATETIME NULL,
    MENUAPPROVEDBY INT NULL,
    MENUAPPROVEDAT DATETIME NULL,
    MENUREMARKS VARCHAR(255) NULL,
    CHANGEDBY  INT NOT NULL,
    CHANGEDAT  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHGREASON  VARCHAR(255),
    CONSTRAINT FK_SLOTHIST_DAYSLOTID FOREIGN KEY (DAYSLOTID) REFERENCES CMS_DAYSLOT(DAYSLOTID),
    CONSTRAINT FK_SLOTHIST_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_SLOTHIST_CHANGEDBY FOREIGN KEY (CHANGEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_SLOTHIST_CANTEENID FOREIGN KEY (CANTEENID) REFERENCES CMS_CANTEEN(CANTEENID),
    CONSTRAINT FK_SLOTHIST_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT FK_SLOTHIST_APPRSTATUSID FOREIGN KEY (APPRSTATUSID) REFERENCES CMS_STATUS(STATUSID)
) ENGINE=InnoDB;
