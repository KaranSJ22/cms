USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_USERROLE;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE CMS_USERROLE (
    USERROLEID INT AUTO_INCREMENT PRIMARY KEY,
    USERID INT NOT NULL,
    ROLEID INT NOT NULL,
    ASSIGNEDBY INT NULL,
    ASSIGNEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    VALIDFROM DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    ISACTIVE BOOLEAN NOT NULL DEFAULT 1,
    UNIQUE KEY UQ_USERROLE (USERID, ROLEID),
    CONSTRAINT FK_USERROLE_USERID FOREIGN KEY (USERID) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_USERROLE_ROLEID FOREIGN KEY (ROLEID) REFERENCES CMS_ROLE(ROLEID),
    CONSTRAINT FK_USERROLE_ASSIGNEDBY FOREIGN KEY (ASSIGNEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT CK_USERROLE_ISACTIVE CHECK (ISACTIVE IN (0, 1))
) ENGINE=InnoDB;
