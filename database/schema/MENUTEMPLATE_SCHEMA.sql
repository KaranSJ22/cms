USE cms_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS CMS_MENUTPLDT;
DROP TABLE IF EXISTS CMS_MENUTPL;

SET FOREIGN_KEY_CHECKS = 1;

/* ============================================================
   CMS_MENUTPL / CMS_MENUTPLDT -- recurring templates so "copy previous
   day/week/month menu" is a materialization from a named
   template, not an ad-hoc row-copy.
   WEEKDAY: 1=Mon..7=Sun; NULL = ad-hoc/reusable template not
   tied to a specific weekday (e.g. a "festival day" template).
   ============================================================ */

CREATE TABLE CMS_MENUTPL (
    MENUTPLID INT AUTO_INCREMENT PRIMARY KEY,
    CANTEENID INT NOT NULL,
    SERVICEID INT NOT NULL,
    TPLNAME   VARCHAR(80) NOT NULL,
    WEEKDAY   TINYINT NULL,
    STATUSID  INT NOT NULL DEFAULT 10,
    CREATEDBY INT NOT NULL,
    CREATEDAT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATEDAT DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_MENUTPL (CANTEENID, SERVICEID, TPLNAME),
    CONSTRAINT FK_MENUTPL_CANTEENID FOREIGN KEY (CANTEENID) REFERENCES CMS_CANTEEN(CANTEENID),
    CONSTRAINT FK_MENUTPL_SERVICEID FOREIGN KEY (SERVICEID) REFERENCES CMS_SERVICE(SERVICEID),
    CONSTRAINT FK_MENUTPL_CREATEDBY FOREIGN KEY (CREATEDBY) REFERENCES CMS_USER(USERID),
    CONSTRAINT FK_MENUTPL_STATUSID FOREIGN KEY (STATUSID) REFERENCES CMS_STATUS(STATUSID),
    CONSTRAINT CK_MTPL_WEEKDAY CHECK (WEEKDAY IS NULL OR WEEKDAY BETWEEN 1 AND 7)
) ENGINE=InnoDB;

CREATE TABLE CMS_MENUTPLDT (
    MENUTPLDTID INT AUTO_INCREMENT PRIMARY KEY,
    MENUTPLID   INT NOT NULL,
    MENUITEMID  INT NOT NULL,
    ISSPECIAL   BOOLEAN NOT NULL DEFAULT 0,
    ISPREBOOK   BOOLEAN NOT NULL DEFAULT 1,
    ISKIOSK     BOOLEAN NOT NULL DEFAULT 1,
    MAXQTY      INT NOT NULL DEFAULT 1,
    DEFAVAILQTY INT NULL DEFAULT NULL,
    UNIQUE KEY UQ_MTPLDT (MENUTPLID, MENUITEMID),
    CONSTRAINT FK_MTPLDT_MENUTPLID FOREIGN KEY (MENUTPLID) REFERENCES CMS_MENUTPL(MENUTPLID),
    CONSTRAINT FK_MTPLDT_MENUITEMID FOREIGN KEY (MENUITEMID) REFERENCES CMS_MENUITEM(MENUITEMID),
    CONSTRAINT CK_MTPLDT_QTY CHECK (MAXQTY >= 1 AND (DEFAVAILQTY IS NULL OR DEFAVAILQTY >= 0)),
    CONSTRAINT CK_MTPLDT_CHANNELS CHECK (ISSPECIAL IN (0, 1) AND ISPREBOOK IN (0, 1) AND ISKIOSK IN (0, 1))
) ENGINE=InnoDB;
