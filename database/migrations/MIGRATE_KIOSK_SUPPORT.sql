CREATE PROCEDURE CMSKIOSKSCANSELFSERVICE (
    IN PIDENTIFIER VARCHAR(255),
    IN PCANTEENID   INT,
    IN PKIOSKID     INT
)
BEGIN
    DECLARE VCUSTOMERID INT DEFAULT NULL;
    DECLARE VIDENTIFIER VARCHAR(255);

    IF PIDENTIFIER IS NULL OR TRIM(PIDENTIFIER) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Identifier or card badge is required';
    END IF;

    SET VIDENTIFIER = TRIM(PIDENTIFIER);

    SELECT AK.CUSTOMERID INTO VCUSTOMERID
    FROM CMS_ACCKEY AK
    JOIN CMS_STATUS STAK ON STAK.STATUSID = AK.STATUSID
    WHERE AK.KEYVALUE = VIDENTIFIER
      AND STAK.STATUSCODE = 'ACT'
      AND (AK.EXPIRESAT IS NULL OR AK.EXPIRESAT > CURRENT_TIMESTAMP)
    LIMIT 1;

    IF VCUSTOMERID IS NULL THEN
        SELECT C.CUSTOMERID INTO VCUSTOMERID
        FROM CMS_USER U
        JOIN CMS_CUSTOMER C ON C.USERID = U.USERID
        WHERE U.LOGINID = VIDENTIFIER
        LIMIT 1;
    END IF;

    IF VCUSTOMERID IS NULL AND VIDENTIFIER REGEXP '^[0-9]+$' THEN
        SELECT C.CUSTOMERID INTO VCUSTOMERID
        FROM CMS_CUSTOMER C
        WHERE C.CUSTOMERID = CAST(VIDENTIFIER AS UNSIGNED)
        LIMIT 1;
    END IF;

    IF VCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Employee or badge not recognized';
    END IF;

    -- Result Set 1: Customer Profile + Wallet
    SELECT 
        C.CUSTOMERID,
        C.DISPNAME,
        C.CTYPECODE,
        U.LOGINID,
        (CASE WHEN C.CTYPECODE IN ('CONTEMP', 'CNT', 'VIS', 'VISITOR') THEN 1 ELSE 0 END) AS ISWALLETELIGIBLE,
        COALESCE(W.BALANCE, 0.00) AS WALLETBALANCE,
        COALESCE(W.RESERVEDAMT, 0.00) AS RESERVEDAMT,
        W.STATUSID AS WALLETSTATUSID
    FROM CMS_CUSTOMER C
    LEFT JOIN CMS_USER U ON U.USERID = C.USERID
    LEFT JOIN CMS_WALLET W ON W.CUSTOMERID = C.CUSTOMERID
    WHERE C.CUSTOMERID = VCUSTOMERID;

    -- Result Set 2: Today's Bookings
    SELECT 
        B.BOOKID,
        B.BOOKNO,
        B.SERVICEID,
        S.SERVNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.SERVEDON,
        B.SERVEDBY
    FROM CMS_BOOKING B
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    WHERE B.CUSTOMERID = VCUSTOMERID
      AND B.SERVICEDATE = CURDATE()
    ORDER BY B.BOOKID DESC;

    -- Result Set 3: Upcoming Pre-Bookings
    SELECT 
        B.BOOKID,
        B.BOOKNO,
        B.SERVICEID,
        S.SERVNAME,
        B.SERVICEDATE,
        B.STATUSID,
        ST.STATUSCODE,
        B.TOTALITEMS,
        B.TOTALQTY,
        B.TOTALAMOUNT,
        B.BOOKEDON
    FROM CMS_BOOKING B
    JOIN CMS_SERVICE S ON S.SERVICEID = B.SERVICEID
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    WHERE B.CUSTOMERID = VCUSTOMERID
      AND B.SERVICEDATE > CURDATE()
      AND ST.STATUSCODE = 'CRT'
    ORDER BY B.SERVICEDATE ASC, B.BOOKID ASC;

END$$

