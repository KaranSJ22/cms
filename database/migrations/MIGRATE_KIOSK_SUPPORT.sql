CREATE PROCEDURE CMSSERVEBOOK (
    IN PBOOKID INT,
    IN PSERVEDBY INT,
    IN PKIOSKID INT
)
PROC_BLOCK: BEGIN
    DECLARE VSTATUSCODE VARCHAR(10);
    DECLARE VSERVICEDATE DATE;
    DECLARE VBOOKHISTID INT;
    DECLARE VTOTALAMOUNT DECIMAL(12,2);
    DECLARE VCUSTOMERID INT;
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VWALLETID INT;
    DECLARE VWALLETBALANCE DECIMAL(12,2);
    DECLARE VWALLETRESERVED DECIMAL(12,2);
    DECLARE VNEWBALANCE DECIMAL(12,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    IF PBOOKID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking ID is required';
    END IF;

    SELECT ST.STATUSCODE, B.SERVICEDATE, B.CUSTOMERID, B.TOTALAMOUNT, C.CTYPECODE 
    INTO VSTATUSCODE, VSERVICEDATE, VCUSTOMERID, VTOTALAMOUNT, VCTYPECODE 
    FROM CMS_BOOKING B
    JOIN CMS_STATUS ST ON ST.STATUSID = B.STATUSID
    JOIN CMS_CUSTOMER C ON C.CUSTOMERID = B.CUSTOMERID
    WHERE B.BOOKID = PBOOKID;

    IF VSTATUSCODE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking not found';
    END IF;

    -- Idempotent check: If already served, return success with ALREADY_SERVED flag
    IF VSTATUSCODE = 'SRV' THEN
        SELECT PBOOKID AS BOOKID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 1 AS ALREADY_SERVED;
        LEAVE PROC_BLOCK;
    END IF;

    IF VSTATUSCODE <> 'CRT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Booking cannot be served from its current state';
    END IF;

    IF VSERVICEDATE <> CURDATE() THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only bookings for today can be served';
    END IF;

    START TRANSACTION;

    INSERT INTO CMS_BOOKHIST (
        BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
        STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
        BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
        KIOSKID,
        REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, CHANGEDBY, CHGREASON
    )
    SELECT
        BOOKID, BOOKNO, BOOKTYPEID, CUSTOMERID, SERVICEID, SERVICEDATE,
        STATUSID, BOOKSEQNO, TOTALITEMS, TOTALQTY, TOTALAMOUNT,
        BOOKEDBY, BOOKEDON, CANCELLEDBY, CANCELLEDON, SERVEDBY, SERVEDON, NOSHOWON,
        PKIOSKID,
        REMARKS, CREATEDBY, CREATEDAT, UPDATEDBY, UPDATEDAT, PSERVEDBY, 'Served'
    FROM CMS_BOOKING
    WHERE BOOKID = PBOOKID;

    SET VBOOKHISTID = LAST_INSERT_ID();

    INSERT INTO CMS_BOOKITMHS (BOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID)
    SELECT VBOOKHISTID, BOOKITEMID, DAYMENUID, MENUITEMID, QTY, RATE, AMOUNT, REMARKS, STATUSID
    FROM CMS_BOOKITEM
    WHERE BOOKID = PBOOKID;

    -- 32 = 'SRV' (Served)
    UPDATE CMS_BOOKING
    SET STATUSID = 32,
        SERVEDBY = PSERVEDBY,
        SERVEDON = CURRENT_TIMESTAMP,
        KIOSKID = COALESCE(PKIOSKID, KIOSKID),
        UPDATEDBY = PSERVEDBY,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKID = PBOOKID;

    UPDATE CMS_BOOKITEM
    SET STATUSID = 32,
        UPDATEDAT = CURRENT_TIMESTAMP
    WHERE BOOKID = PBOOKID AND STATUSID = 30;

    DELETE FROM CMS_PBACTIVE WHERE BOOKID = PBOOKID;

    IF VCTYPECODE IN ('CNT', 'VIS', 'CONTEMP', 'VISITOR') THEN
        UPDATE CMS_WALLET
        SET RESERVEDAMT = GREATEST(0, RESERVEDAMT - VTOTALAMOUNT),
            UPDATEDBY = PSERVEDBY,
            UPDATEDAT = CURRENT_TIMESTAMP
        WHERE CUSTOMERID = VCUSTOMERID;
    END IF;

    COMMIT;

    SELECT PBOOKID AS BOOKID, 32 AS STATUSID, 'SRV' AS STATUSCODE, 0 AS ALREADY_SERVED;
END$$

