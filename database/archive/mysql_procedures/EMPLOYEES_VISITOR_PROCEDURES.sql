/* ============================================================
   CMS_PERMEMP — Permanent Employee Profile
   ============================================================ */

CREATE PROCEDURE CMSADDPERM (
    IN PCUSTOMERID INT,
    IN PEMPCODE    VARCHAR(50),
    IN PDEPT       VARCHAR(100),
    IN PDESIG      VARCHAR(100)
)
BEGIN
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VPERMEMPID INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer ID is required';
    END IF;
    IF PEMPCODE IS NULL OR TRIM(PEMPCODE) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Employee Code is required';
    END IF;
    IF PDEPT IS NULL OR TRIM(PDEPT) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Department is required';
    END IF;
    IF PDESIG IS NULL OR TRIM(PDESIG) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Designation is required';
    END IF;

    SELECT CTYPECODE INTO VCTYPECODE FROM CMS_CUSTOMER WHERE CUSTOMERID = PCUSTOMERID;
    IF VCTYPECODE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer not found';
    END IF;
    IF VCTYPECODE <> 'PERMANENT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer type must be PERMANENT';
    END IF;

    START TRANSACTION;
    INSERT INTO CMS_PERMEMP (CUSTOMERID, EMPCODE, DEPT, DESIG)
    VALUES (PCUSTOMERID, TRIM(PEMPCODE), TRIM(PDEPT), TRIM(PDESIG));
    SET VPERMEMPID = LAST_INSERT_ID();
    COMMIT;

    SELECT VPERMEMPID AS PERMEMPID;
END$$


CREATE PROCEDURE CMSUPDPERM (
    IN PCUSTOMERID INT,
    IN PDEPT       VARCHAR(100),
    IN PDESIG      VARCHAR(100)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer ID is required';
    END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_PERMEMP WHERE CUSTOMERID = PCUSTOMERID;
    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Permanent employee profile not found';
    END IF;

    START TRANSACTION;
    UPDATE CMS_PERMEMP
    SET    DEPT      = COALESCE(PDEPT, DEPT),
           DESIG     = COALESCE(PDESIG, DESIG),
           UPDATEDAT = CURRENT_TIMESTAMP
    WHERE  CUSTOMERID = PCUSTOMERID;
    COMMIT;
    SELECT PCUSTOMERID AS CUSTOMERID;
END$$


CREATE PROCEDURE CMSGETPERM (IN PCUSTOMERID INT)
BEGIN
    SELECT PE.PERMEMPID, PE.CUSTOMERID, PE.EMPCODE, PE.DEPT, PE.DESIG,
           C.DISPNAME, C.STATUS, U.USERID, U.LOGINID, U.FULLNAME
    FROM   CMS_PERMEMP PE
    JOIN   CMS_CUSTOMER C ON C.CUSTOMERID = PE.CUSTOMERID
    LEFT JOIN CMS_USER U  ON U.USERID     = C.USERID
    WHERE  PE.CUSTOMERID = PCUSTOMERID;
END$$


