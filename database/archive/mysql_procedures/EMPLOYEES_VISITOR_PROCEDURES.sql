    IN PVISORG     VARCHAR(150),
    IN PVISPURPOSE VARCHAR(255),
    IN PVISDATE    DATE,
    IN PVALIDUNTIL DATETIME,
    IN PKEYTYPE    VARCHAR(30),
    IN PKEYVALUE   VARCHAR(255),
    IN PCREATEDBY  INT
)
BEGIN
    DECLARE VCUSTOMERID INT;
    DECLARE VVISITORID  INT;
    DECLARE VACCKEYID   INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PVISNAME IS NULL OR TRIM(PVISNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Visitor Name is required'; END IF;
    IF PVISDATE IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Visit Date is required'; END IF;
    IF PVALIDUNTIL IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Valid Until is required'; END IF;
    IF PCREATEDBY IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Created By is required'; END IF;
    IF PVALIDUNTIL < TIMESTAMP(PVISDATE, '00:00:00') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Valid until must be >= visit date';
    END IF;

    START TRANSACTION;

    -- Visitors may not have a CMS_USER; USERID is NULL
    INSERT INTO CMS_CUSTOMER (USERID, CTYPECODE, DISPNAME, STATUSID, VALIDFROM, VALIDUNTIL)
    VALUES (NULL, 'VIS', TRIM(PVISNAME), 10, CURRENT_TIMESTAMP, PVALIDUNTIL);
    SET VCUSTOMERID = LAST_INSERT_ID();

    INSERT INTO CMS_VISITOR (CUSTOMERID, VISNAME, VISMOBILE, VISORG, VISPURPOSE, VISDATE, VALIDUNTIL, CREATEDBY, STATUSID)
    VALUES (VCUSTOMERID, TRIM(PVISNAME), PVISMOBILE, PVISORG, PVISPURPOSE, PVISDATE, PVALIDUNTIL, PCREATEDBY, 10);
    SET VVISITORID = LAST_INSERT_ID();

    IF PKEYVALUE IS NOT NULL AND TRIM(PKEYVALUE) <> '' THEN
        INSERT INTO CMS_ACCKEY (CUSTOMERID, KEYTYPE, KEYVALUE, EXPIRESAT, STATUSID, CREATEDBY)
        VALUES (VCUSTOMERID, COALESCE(PKEYTYPE, 'VISPASS'), TRIM(PKEYVALUE), PVALIDUNTIL, 10, PCREATEDBY);
        SET VACCKEYID = LAST_INSERT_ID();
    END IF;

    COMMIT;
    SELECT VCUSTOMERID AS CUSTOMERID, VVISITORID AS VISITORID, VACCKEYID AS ACCKEYID;
END$$



