/* ============================================================
   CMS_VISITOR — Visitor Profile
   ============================================================ */

CREATE PROCEDURE CMSADDVIS (
    IN PCUSTOMERID INT,
    IN PVISNAME    VARCHAR(120),
    IN PVISMOBILE  VARCHAR(20),
    IN PVISORG     VARCHAR(150),
    IN PVISPURPOSE VARCHAR(255),
    IN PVISDATE    DATE,
    IN PVALIDUNTIL DATETIME,
    IN PCREATEDBY  INT
)
BEGIN
    DECLARE VCTYPECODE VARCHAR(20);
    DECLARE VVISITORID INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer ID is required';
    END IF;
    IF PVISNAME IS NULL OR TRIM(PVISNAME) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Visitor Name is required';
    END IF;
    IF PVISDATE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Visit Date is required';
    END IF;
    IF PVALIDUNTIL IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Valid Until is required';
    END IF;
    IF PCREATEDBY IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Created By is required';
    END IF;
    IF PVALIDUNTIL < TIMESTAMP(PVISDATE, '00:00:00') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Valid until must be >= visit date';
    END IF;

    SELECT CTYPECODE INTO VCTYPECODE FROM CMS_CUSTOMER WHERE CUSTOMERID = PCUSTOMERID;
    IF VCTYPECODE IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer not found';
    END IF;
    IF VCTYPECODE <> 'VIS' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only visitors can be created without a User ID';
    END IF;

    START TRANSACTION;
    INSERT INTO CMS_VISITOR (CUSTOMERID, VISNAME, VISMOBILE, VISORG, VISPURPOSE, VISDATE, VALIDUNTIL, CREATEDBY, STATUSID)
    VALUES (PCUSTOMERID, TRIM(PVISNAME), PVISMOBILE, PVISORG, PVISPURPOSE, PVISDATE, PVALIDUNTIL, PCREATEDBY, 10);
    SET VVISITORID = LAST_INSERT_ID();
    COMMIT;
    SELECT VVISITORID AS VISITORID;
END$$


CREATE PROCEDURE CMSUPDVIS (
    IN PCUSTOMERID INT,
    IN PVISMOBILE  VARCHAR(20),
    IN PVISORG     VARCHAR(150),
    IN PVISPURPOSE VARCHAR(255),
    IN PVALIDUNTIL DATETIME,
    IN PSTATUSCODE VARCHAR(20)
)
BEGIN
    DECLARE VCOUNT INT DEFAULT 0;
    DECLARE VSTATUSID INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    IF PCUSTOMERID IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Customer ID is required';
    END IF;
    SELECT COUNT(*) INTO VCOUNT FROM CMS_VISITOR WHERE CUSTOMERID = PCUSTOMERID;
    IF VCOUNT = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Visitor profile not found';
    END IF;

    IF PSTATUSCODE IS NOT NULL THEN
        SELECT STATUSID INTO VSTATUSID FROM CMS_STATUS WHERE STATUSCODE = PSTATUSCODE AND STATUSGRP = 'SYS';
        IF VSTATUSID IS NULL THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid Status Code';
        END IF;
    END IF;

    START TRANSACTION;
    UPDATE CMS_VISITOR
    SET    VISMOBILE  = COALESCE(PVISMOBILE, VISMOBILE),
           VISORG     = COALESCE(PVISORG, VISORG),
           VISPURPOSE = COALESCE(PVISPURPOSE, VISPURPOSE),
           VALIDUNTIL = COALESCE(PVALIDUNTIL, VALIDUNTIL),
           STATUSID   = COALESCE(VSTATUSID, STATUSID),
           UPDATEDAT  = CURRENT_TIMESTAMP
    WHERE  CUSTOMERID = PCUSTOMERID;
    COMMIT;
    SELECT PCUSTOMERID AS CUSTOMERID;
END$$


CREATE PROCEDURE CMSGETVIS (IN PCUSTOMERID INT)
BEGIN
    SELECT V.VISITORID, V.CUSTOMERID, V.VISNAME, V.VISMOBILE,
           V.VISORG, V.VISPURPOSE, V.VISDATE, V.VALIDUNTIL,
           V.CREATEDBY, V.STATUSID, STV.STATUSCODE AS STATUSCODE,
           C.DISPNAME, U.USERID, U.LOGINID
    FROM   CMS_VISITOR V
    JOIN   CMS_STATUS STV ON STV.STATUSID = V.STATUSID
    JOIN   CMS_CUSTOMER C ON C.CUSTOMERID = V.CUSTOMERID
    LEFT JOIN CMS_USER U  ON U.USERID     = C.USERID
    WHERE  V.CUSTOMERID = PCUSTOMERID;
END$$


/* ============================================================
   COMPOSITE REGISTRATION PROCEDURES

   Each creates User + Customer + Profile + Access Key
   in a single transaction for data integrity.
   ============================================================ */

CREATE PROCEDURE CMSREGPERM (
    IN PLOGINID   VARCHAR(50),
    IN PFULLNAME  VARCHAR(120),
    IN PEMAIL     VARCHAR(120),
    IN PMOBILENO  VARCHAR(20),
    IN PPWDHASH   VARCHAR(255),
    IN PEMPCODE   VARCHAR(50),
    IN PDEPT      VARCHAR(100),
    IN PDESIG     VARCHAR(100),
    IN PKEYTYPE   VARCHAR(30),
    IN PKEYVALUE  VARCHAR(255),
    IN PCREATEDBY INT
)
BEGIN
    DECLARE VUSERID     INT;
    DECLARE VCUSTOMERID INT;
    DECLARE VPERMEMPID  INT;
    DECLARE VACCKEYID   INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

    -- Validate required fields
    IF PLOGINID IS NULL OR TRIM(PLOGINID) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Login ID is required'; END IF;
    IF PFULLNAME IS NULL OR TRIM(PFULLNAME) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Full Name is required'; END IF;
    IF PPWDHASH IS NULL OR TRIM(PPWDHASH) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Password hash is required'; END IF;
    IF PEMPCODE IS NULL OR TRIM(PEMPCODE) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Employee Code is required'; END IF;
    IF PDEPT IS NULL OR TRIM(PDEPT) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Department is required'; END IF;
    IF PDESIG IS NULL OR TRIM(PDESIG) = '' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Designation is required'; END IF;

    START TRANSACTION;

    INSERT INTO CMS_USER (LOGINID, FULLNAME, EMAIL, MOBILENO, PWDHASH, AUTHPROV)
    VALUES (TRIM(PLOGINID), TRIM(PFULLNAME), PEMAIL, PMOBILENO, PPWDHASH, 'LOCAL');
    SET VUSERID = LAST_INSERT_ID();

    INSERT INTO CMS_CUSTOMER (USERID, CTYPECODE, DISPNAME, STATUSID, VALIDFROM)
    VALUES (VUSERID, 'PERMANENT', TRIM(PFULLNAME), 10, CURRENT_TIMESTAMP);
    SET VCUSTOMERID = LAST_INSERT_ID();

    INSERT INTO CMS_PERMEMP (CUSTOMERID, EMPCODE, DEPT, DESIG)
    VALUES (VCUSTOMERID, TRIM(PEMPCODE), TRIM(PDEPT), TRIM(PDESIG));
    SET VPERMEMPID = LAST_INSERT_ID();

    IF PKEYVALUE IS NOT NULL AND TRIM(PKEYVALUE) <> '' THEN
        INSERT INTO CMS_ACCKEY (CUSTOMERID, KEYTYPE, KEYVALUE, STATUSID, CREATEDBY)
        VALUES (VCUSTOMERID, COALESCE(PKEYTYPE, 'EMPCARD'), TRIM(PKEYVALUE), 10, PCREATEDBY);
        SET VACCKEYID = LAST_INSERT_ID();
    END IF;

    COMMIT;

    SELECT VUSERID AS USERID, VCUSTOMERID AS CUSTOMERID, VPERMEMPID AS PERMEMPID, VACCKEYID AS ACCKEYID;
END$$


