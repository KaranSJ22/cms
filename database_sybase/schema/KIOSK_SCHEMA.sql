/* ============================================================
   FILE    : KIOSK_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Kiosk & Terminal Device Management
   TABLES  : CMS_KIOSK_DEVICE
   ORDER   : Execute ELEVENTH (after CANTEEN_SCHEMA.sql)
   NOTES   :
   - MySQL ENUM('STAFF_COUNTER','EMP_SELF_SERVICE') replaced
     with VARCHAR(20) + CHECK CONSTRAINT (Sybase has no ENUM).
   - KEY IX_... (non-unique index) replaced with CREATE INDEX.
   - ISACTIVE TINYINT(1) → TINYINT.
   - Duplicate STATUSID and ISACTIVE consolidated: STATUSID is
     canonical (ISACTIVE kept for legacy API parity).
   ============================================================ */

USE CMS_DB
GO

IF OBJECT_ID('dbo.CMS_KIOSK_DEVICE') IS NOT NULL
    DROP TABLE dbo.CMS_KIOSK_DEVICE
GO

CREATE TABLE dbo.CMS_KIOSK_DEVICE (
    KIOSKID         INT          IDENTITY NOT NULL,
    DEVICECODE      VARCHAR(30)  NOT NULL,
    DEVICENAME      VARCHAR(100) NOT NULL,
    IPADDRESS       VARCHAR(45)  NOT NULL,
    MACADDRESS      VARCHAR(17)  NULL,
    CANTEENID       INT          NOT NULL,
    KIOSKTYPE       VARCHAR(20)  NOT NULL DEFAULT 'EMP_SELF_SERVICE',
    STATUSID        INT          NOT NULL DEFAULT 10,
    ISACTIVE        TINYINT      NOT NULL DEFAULT 1,
    LASTHEARTBEATAT DATETIME     NULL,
    LASTSEENIP      VARCHAR(45)  NULL,
    CREATEDBY       INT          NULL,
    CREATEDAT       DATETIME     NOT NULL DEFAULT GETDATE(),
    UPDATEDBY       INT          NULL,
    UPDATEDAT       DATETIME     NULL,
    PRIMARY KEY (KIOSKID),
    CONSTRAINT CK_KD_KIOSKTYPE CHECK (KIOSKTYPE IN ('STAFF_COUNTER', 'EMP_SELF_SERVICE'))
)
LOCK DATAROWS
GO

-- Unique indexes replacing UNIQUE KEY declarations
CREATE UNIQUE INDEX UQ_KD_DEVICECODE
    ON dbo.CMS_KIOSK_DEVICE (DEVICECODE)
GO

CREATE UNIQUE INDEX UQ_KD_IPADDRESS
    ON dbo.CMS_KIOSK_DEVICE (IPADDRESS)
GO

-- Non-unique indexes replacing MySQL KEY declarations
CREATE INDEX IX_KD_IP
    ON dbo.CMS_KIOSK_DEVICE (IPADDRESS)
GO

CREATE INDEX IX_KD_CANTEEN_TYPE
    ON dbo.CMS_KIOSK_DEVICE (CANTEENID, KIOSKTYPE)
GO

ALTER TABLE dbo.CMS_KIOSK_DEVICE
    ADD CONSTRAINT FK_KD_CANTEEN
    FOREIGN KEY (CANTEENID) REFERENCES dbo.CMS_CANTEEN(CANTEENID)
GO

ALTER TABLE dbo.CMS_KIOSK_DEVICE
    ADD CONSTRAINT FK_KD_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

ALTER TABLE dbo.CMS_KIOSK_DEVICE
    ADD CONSTRAINT FK_KD_CREATEDBY
    FOREIGN KEY (CREATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_KIOSK_DEVICE
    ADD CONSTRAINT FK_KD_UPDATEDBY
    FOREIGN KEY (UPDATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

PRINT 'KIOSK_SCHEMA created successfully.'
GO
