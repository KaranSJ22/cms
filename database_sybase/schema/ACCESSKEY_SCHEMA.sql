/* ============================================================
   FILE    : ACCESSKEY_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Access Keys (RFID / QR Badge Tokens)
   TABLES  : CMS_ACCKEY
   ORDER   : Execute FIFTH (after CUSTOMER_SCHEMA.sql)
   NOTES   :
   - CHECK CONSTRAINT on KEYTYPE uses Sybase T-SQL syntax.
   - UNIQUE index on KEYVALUE enforces one token per card.
   ============================================================ */

USE CMS_DB
GO

IF OBJECT_ID('dbo.CMS_ACCKEY') IS NOT NULL
    DROP TABLE dbo.CMS_ACCKEY
GO

CREATE TABLE dbo.CMS_ACCKEY (
    ACCKEYID   INT          IDENTITY NOT NULL,
    CUSTOMERID INT          NOT NULL,
    KEYTYPE    VARCHAR(30)  NOT NULL,
    KEYVALUE   VARCHAR(255) NOT NULL,
    EXPIRESAT  DATETIME     NULL,
    STATUSID   INT          NOT NULL DEFAULT 10,
    CREATEDBY  INT          NULL,
    CREATEDAT  DATETIME     NOT NULL DEFAULT GETDATE(),
    UPDATEDAT  DATETIME     NULL,
    LASTUSEDAT DATETIME     NULL,
    PRIMARY KEY (ACCKEYID),
    CONSTRAINT CK_ACCKEY_KEYTYPE CHECK (KEYTYPE IN ('QR','RFID','EMPCARD','VISPASS','TEMPTOKEN'))
)
LOCK DATAROWS
GO

CREATE UNIQUE INDEX UQ_ACCKEY_KEYVALUE
    ON dbo.CMS_ACCKEY (KEYVALUE)
GO

ALTER TABLE dbo.CMS_ACCKEY
    ADD CONSTRAINT FK_AK_CUST
    FOREIGN KEY (CUSTOMERID) REFERENCES dbo.CMS_CUSTOMER(CUSTOMERID)
GO

ALTER TABLE dbo.CMS_ACCKEY
    ADD CONSTRAINT FK_AK_BY
    FOREIGN KEY (CREATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_ACCKEY
    ADD CONSTRAINT FK_AK_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

PRINT 'ACCESSKEY_SCHEMA created successfully.'
GO
