/* ============================================================
   FILE    : OFFICIAL_REQUEST.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Official Catering Workflow
   TABLES  : CMS_LVLMAP, CMS_OFFSERV, CMS_OFFCOMBO,
             CMS_OFFCOMBO_ITEM, CMS_OFFBOOKCTR,
             CMS_OFFBOOK, CMS_OFFAPPR
   ORDER   : Execute TWENTIETH (after MENUITEM_PRICE_SCHEMA.sql
             and CANTEEN_SCHEMA.sql)
   NOTES   :
   - MySQL ON DELETE CASCADE on CMS_OFFCOMBO_ITEM and CMS_OFFAPPR
     replaced with explicit DELETE in stored procedures
     (CASCADE in Sybase triggers page-lock escalation).
   - CMS_OFFBOOKCTR: natural composite PK (CANTEENID, BOOKDATE).
     BOOKDATE: DATETIME normalised to midnight.
   - CMS_OFFAPPR: approval audit trail — non-IDENTITY PK
     (@@IDENTITY trigger hazard protocol).
   - TINYINT(1) → TINYINT for ISACTIVE.
   - All ON UPDATE CURRENT_TIMESTAMP removed.
   - UNIQUE KEY inside CREATE TABLE → separate CREATE UNIQUE INDEX.
   ============================================================ */

