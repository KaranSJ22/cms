-- ============================================================
-- CMS_LVLMAP
-- Maps employee grade/level to an approval tier (L1 or L2).
-- Used by CMSOFFCREATEBOOKING to auto-select approver.
-- ============================================================
CREATE TABLE dbo.CMS_LVLMAP (
    LVLMAPID  INT         IDENTITY NOT NULL,
    EMPLEVEL  INT         NOT NULL,
    APPRLVL   VARCHAR(10) NOT NULL,
    ISACTIVE  TINYINT     NOT NULL DEFAULT 1,
    CREATEDBY INT         NULL,
    CREATEDAT DATETIME    NOT NULL DEFAULT GETDATE(),
    UPDATEDBY INT         NULL,
    UPDATEDAT DATETIME    NULL,
    PRIMARY KEY (LVLMAPID),
    CONSTRAINT CK_LM_APPRLVL CHECK (APPRLVL IN ('L1', 'L2'))
)
LOCK DATAROWS
GO

CREATE UNIQUE INDEX UQ_LVLMAP_EMPLEVEL
    ON dbo.CMS_LVLMAP (EMPLEVEL)
GO

ALTER TABLE dbo.CMS_LVLMAP
    ADD CONSTRAINT FK_LM_CREATEDBY
    FOREIGN KEY (CREATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_LVLMAP
    ADD CONSTRAINT FK_LM_UPDATEDBY
    FOREIGN KEY (UPDATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

