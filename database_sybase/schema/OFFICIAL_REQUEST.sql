-- ============================================================
-- CMS_OFFBOOK
-- Official catering booking header.
-- APPRLVL / APPROVERID auto-resolved by CMSOFFCREATEBOOKING.
-- STATUSID: 35=Pending, 36=Approved, 37=Rejected, 38=Served.
-- ============================================================
CREATE TABLE dbo.CMS_OFFBOOK (
    OFFBOOKID      INT           IDENTITY NOT NULL,
    BOOKNO         VARCHAR(35)   NOT NULL,
    CANTEENID      INT           NOT NULL,
    OFFSERVID      INT           NOT NULL,
    OFFCOMBOID     INT           NOT NULL,
    CUSTOMERID     INT           NOT NULL,
    BOOKEDBY       INT           NOT NULL,
    PURPOSE        VARCHAR(255)  NOT NULL,
    VENUE          VARCHAR(255)  NOT NULL,
    EVENTDATETIME  DATETIME      NOT NULL,
    QUANTITY       INT           NOT NULL,
    NOOFPEOPLE     INT           NOT NULL,
    UNITPRICE      DECIMAL(10,2) NOT NULL,
    HANDLINGCHARGE DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    TOTALAMOUNT    DECIMAL(12,2) NOT NULL,
    APPRLVL        VARCHAR(10)   NOT NULL,
    APPROVERID     INT           NOT NULL,
    STATUSID       INT           NOT NULL DEFAULT 35,
    BOOKEDAT       DATETIME      NOT NULL DEFAULT GETDATE(),
    UPDATEDBY      INT           NULL,
    UPDATEDAT      DATETIME      NULL,
    PRIMARY KEY (OFFBOOKID),
    CONSTRAINT CK_OB_QTY    CHECK (QUANTITY >= 1),
    CONSTRAINT CK_OB_PEOPLE CHECK (NOOFPEOPLE >= 1),
    CONSTRAINT CK_OB_TOTAL  CHECK (TOTALAMOUNT >= 0)
)
LOCK DATAROWS
GO

