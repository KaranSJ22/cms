/* ============================================================
   FILE    : WALLET_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Wallet Ledger
   TABLES  : CMS_WALLET, CMS_WALLETTRAN, CMS_WALLETWD
   ORDER   : Execute NINETEENTH (after BOOKING_SCHEMA.sql
             and CUSTOMER_SCHEMA.sql)
   NOTES   :
   - CMS_WALLET: HOLDLOCK UPDLOCK MANDATORY in all balance-
     read procedures (CMSADDBOOK, wallet debit SPs) to prevent
     concurrent overdraft / phantom read on BALANCE.
   - CMS_WALLETTRAN: immutable ledger — rows NEVER updated.
     REFNO auto-generated via CMSGENAUTO (Prefix: TXN).
   - MySQL INDEX inside CREATE TABLE → separate CREATE INDEX.
   - ON DELETE CASCADE on CMS_OFFCOMBO_ITEM / CMS_OFFAPPR is
     replaced with explicit procedure-managed deletes (Sybase
     CASCADE DELETE can cause implicit lock escalation).
   - ON UPDATE CURRENT_TIMESTAMP removed from all tables.
   - All CHECK constraints preserved.
   ============================================================ */

USE CMS_DB
GO

-- Drop in reverse dependency order
IF OBJECT_ID('dbo.CMS_WALLETWD') IS NOT NULL
    DROP TABLE dbo.CMS_WALLETWD
GO

IF OBJECT_ID('dbo.CMS_WALLETTRAN') IS NOT NULL
    DROP TABLE dbo.CMS_WALLETTRAN
GO

IF OBJECT_ID('dbo.CMS_WALLET') IS NOT NULL
    DROP TABLE dbo.CMS_WALLET
GO

-- ============================================================
-- CMS_WALLET
-- One wallet per eligible customer (CNT / VIS).
-- BALANCE and RESERVEDAMT read with HOLDLOCK UPDLOCK in SPs.
-- ============================================================
CREATE TABLE dbo.CMS_WALLET (
    WALLETID    INT           IDENTITY NOT NULL,
    CUSTOMERID  INT           NOT NULL,
    BALANCE     DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    RESERVEDAMT DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    STATUSID    INT           NOT NULL DEFAULT 10,
    CREATEDAT   DATETIME      NOT NULL DEFAULT GETDATE(),
    UPDATEDAT   DATETIME      NOT NULL DEFAULT GETDATE(),
    PRIMARY KEY (WALLETID),
    CONSTRAINT CK_WAL_BALANCE  CHECK (BALANCE >= 0.00),
    CONSTRAINT CK_WAL_RESERVED CHECK (RESERVEDAMT >= 0.00),
    CONSTRAINT CK_WAL_RES_BAL  CHECK (RESERVEDAMT <= BALANCE)
)
LOCK DATAROWS
GO

CREATE UNIQUE INDEX UQ_WALLET_CUSTID
    ON dbo.CMS_WALLET (CUSTOMERID)
GO

CREATE INDEX IX_WAL_CUST
    ON dbo.CMS_WALLET (CUSTOMERID)
GO

CREATE INDEX IX_WAL_STATUSID
    ON dbo.CMS_WALLET (STATUSID)
GO

ALTER TABLE dbo.CMS_WALLET
    ADD CONSTRAINT FK_WAL_CUST
    FOREIGN KEY (CUSTOMERID) REFERENCES dbo.CMS_CUSTOMER(CUSTOMERID)
GO

ALTER TABLE dbo.CMS_WALLET
    ADD CONSTRAINT FK_WAL_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

-- ============================================================
-- CMS_WALLETTRAN
-- Immutable double-entry wallet ledger.
-- Rows are NEVER updated after INSERT.
-- REFNO is unique, auto-generated via CMSGENAUTO (Prefix: TXN).
-- TRANSTYPE examples: 'TOPUP', 'DEBIT', 'REFUND', 'FORFEIT'
-- ============================================================
CREATE TABLE dbo.CMS_WALLETTRAN (
    WALLETTRANID  INT           IDENTITY NOT NULL,
    WALLETID      INT           NOT NULL,
    BOOKINGID     INT           NULL,
    TRANSTYPE     VARCHAR(20)   NOT NULL,
    SOURCECODE    VARCHAR(30)   NOT NULL,
    AMOUNT        DECIMAL(12,2) NOT NULL,
    BALBEFORE     DECIMAL(12,2) NOT NULL,
    BALAFTER      DECIMAL(12,2) NOT NULL,
    PAYMENTMETHOD VARCHAR(20)   NULL,
    REFNO         VARCHAR(80)   NULL,
    STATUSID      INT           NOT NULL DEFAULT 40,
    CREATEDBY     INT           NOT NULL,
    CREATEDAT     DATETIME      NOT NULL DEFAULT GETDATE(),
    REMARKS       VARCHAR(500)  NULL,
    PRIMARY KEY (WALLETTRANID),
    CONSTRAINT CK_WT_AMOUNT   CHECK (AMOUNT > 0.00),
    CONSTRAINT CK_WT_BALBEFORE CHECK (BALBEFORE >= 0.00),
    CONSTRAINT CK_WT_BALAFTER  CHECK (BALAFTER >= 0.00)
)
LOCK DATAROWS
GO

CREATE UNIQUE INDEX UQ_WT_REFNO
    ON dbo.CMS_WALLETTRAN (REFNO)
GO

CREATE INDEX IX_WT_WALLET
    ON dbo.CMS_WALLETTRAN (WALLETID, CREATEDAT)
GO

CREATE INDEX IX_WT_BOOKING
    ON dbo.CMS_WALLETTRAN (BOOKINGID)
GO

CREATE INDEX IX_WT_CREATEDBY
    ON dbo.CMS_WALLETTRAN (CREATEDBY)
GO

CREATE INDEX IX_WT_REFNO
    ON dbo.CMS_WALLETTRAN (REFNO)
GO

ALTER TABLE dbo.CMS_WALLETTRAN
    ADD CONSTRAINT FK_WT_WALLET
    FOREIGN KEY (WALLETID) REFERENCES dbo.CMS_WALLET(WALLETID)
GO

ALTER TABLE dbo.CMS_WALLETTRAN
    ADD CONSTRAINT FK_WT_BOOKING
    FOREIGN KEY (BOOKINGID) REFERENCES dbo.CMS_BOOKING(BOOKID)
GO

ALTER TABLE dbo.CMS_WALLETTRAN
    ADD CONSTRAINT FK_WT_USER
    FOREIGN KEY (CREATEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_WALLETTRAN
    ADD CONSTRAINT FK_WT_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

-- ============================================================
-- CMS_WALLETWD
-- Withdrawal (cash-out) request tracking.
-- Workflow: PENDING → PROCESSED / REJECTED via wallet SP.
-- ============================================================
CREATE TABLE dbo.CMS_WALLETWD (
    WALLETWDID    INT           IDENTITY NOT NULL,
    WALLETID      INT           NOT NULL,
    AMOUNT        DECIMAL(12,2) NOT NULL,
    STATUSID      INT           NOT NULL DEFAULT 40,
    REQUESTEDBY   INT           NOT NULL,
    REQUESTEDAT   DATETIME      NOT NULL DEFAULT GETDATE(),
    PROCESSEDBY   INT           NULL,
    PROCESSEDAT   DATETIME      NULL,
    PAYMENTMETHOD VARCHAR(20)   NULL,
    REFNO         VARCHAR(80)   NULL,
    REMARKS       VARCHAR(500)  NULL,
    PRIMARY KEY (WALLETWDID),
    CONSTRAINT CK_WD_AMOUNT CHECK (AMOUNT > 0.00)
)
LOCK DATAROWS
GO

CREATE INDEX IX_WD_WALLET
    ON dbo.CMS_WALLETWD (WALLETID, STATUSID)
GO

CREATE INDEX IX_WD_STATUSID
    ON dbo.CMS_WALLETWD (STATUSID)
GO

CREATE INDEX IX_WD_REQUESTEDAT
    ON dbo.CMS_WALLETWD (REQUESTEDAT)
GO

ALTER TABLE dbo.CMS_WALLETWD
    ADD CONSTRAINT FK_WD_WALLET
    FOREIGN KEY (WALLETID) REFERENCES dbo.CMS_WALLET(WALLETID)
GO

ALTER TABLE dbo.CMS_WALLETWD
    ADD CONSTRAINT FK_WD_REQUSER
    FOREIGN KEY (REQUESTEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_WALLETWD
    ADD CONSTRAINT FK_WD_PROCUSER
    FOREIGN KEY (PROCESSEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_WALLETWD
    ADD CONSTRAINT FK_WD_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

PRINT 'WALLET_SCHEMA created successfully.'
GO
