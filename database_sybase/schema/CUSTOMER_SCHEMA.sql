/* ============================================================
   FILE    : CUSTOMER_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Customer (Consumer Entity)
   TABLES  : CMS_CUSTOMER
   ORDER   : Execute FOURTH (after USER_SCHEMA.sql)
   NOTES   :
   - CTYPECODE VARCHAR(20) FK to CMS_CUSTTYPE (not INT surrogate)
     to allow direct code-based joins without extra lookup joins.
   - USERID is UNIQUE — one-to-one mapping with CMS_USER.
   ============================================================ */

USE CMS_DB
GO

IF OBJECT_ID('dbo.CMS_CUSTOMER') IS NOT NULL
    DROP TABLE dbo.CMS_CUSTOMER
GO

CREATE TABLE dbo.CMS_CUSTOMER (
    CUSTOMERID INT          IDENTITY NOT NULL,
    USERID     INT          NULL,
    CTYPECODE  VARCHAR(20)  NOT NULL,
    DISPNAME   VARCHAR(120) NOT NULL,
    STATUSID   INT          NOT NULL DEFAULT 10,
    VALIDFROM  DATETIME     NULL,
    VALIDUNTIL DATETIME     NULL,
    CREATEDAT  DATETIME     NOT NULL DEFAULT GETDATE(),
    UPDATEDAT  DATETIME     NULL,
    PRIMARY KEY (CUSTOMERID)
)
LOCK DATAROWS
GO

-- One CMS_USER can have at most one CMS_CUSTOMER record
CREATE UNIQUE INDEX UQ_CUSTOMER_USERID
    ON dbo.CMS_CUSTOMER (USERID)
GO

ALTER TABLE dbo.CMS_CUSTOMER
    ADD CONSTRAINT FK_CUST_USER
    FOREIGN KEY (USERID) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_CUSTOMER
    ADD CONSTRAINT FK_CUST_TYPE
    FOREIGN KEY (CTYPECODE) REFERENCES dbo.CMS_CUSTTYPE(CTYPECODE)
GO

ALTER TABLE dbo.CMS_CUSTOMER
    ADD CONSTRAINT FK_CUST_STATUS
    FOREIGN KEY (STATUSID) REFERENCES dbo.CMS_STATUS(STATUSID)
GO

PRINT 'CUSTOMER_SCHEMA created successfully.'
GO
