/* ============================================================
   FILE    : CONSUMERROLE_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Consumer (Customer) Role Assignments
   TABLES  : CMS_CONSUMERROLE
   ORDER   : Execute TENTH (after CANTEENROLE_SCHEMA.sql)
   NOTES   :
   - Grants canteen-agnostic roles to consumers (customers),
     e.g. PREBOOKER, KIOSK_USER, WALLET_USER.
   - Distinct from CMS_CANTEENROLE (staff-scoped).
   - Composite unique on (USERID, ROLEID).
   ============================================================ */

USE CMS_DB
GO

IF OBJECT_ID('dbo.CMS_CONSUMERROLE') IS NOT NULL
    DROP TABLE dbo.CMS_CONSUMERROLE
GO

CREATE TABLE dbo.CMS_CONSUMERROLE (
    USRROLEID  INT      IDENTITY NOT NULL,
    USERID     INT      NOT NULL,
    ROLEID     INT      NOT NULL,
    ASSIGNEDBY INT      NULL,
    ASSIGNEDAT DATETIME NOT NULL DEFAULT GETDATE(),
    VALIDFROM  DATETIME NULL,
    VALIDUNTIL DATETIME NULL,
    ISACTIVE   TINYINT  NOT NULL DEFAULT 1,
    PRIMARY KEY (USRROLEID)
)
LOCK DATAROWS
GO

CREATE UNIQUE INDEX UQ_USRROLE
    ON dbo.CMS_CONSUMERROLE (USERID, ROLEID)
GO

ALTER TABLE dbo.CMS_CONSUMERROLE
    ADD CONSTRAINT FK_UR_USER
    FOREIGN KEY (USERID) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_CONSUMERROLE
    ADD CONSTRAINT FK_UR_ROLE
    FOREIGN KEY (ROLEID) REFERENCES dbo.CMS_ROLE(ROLEID)
GO

ALTER TABLE dbo.CMS_CONSUMERROLE
    ADD CONSTRAINT FK_UR_BY
    FOREIGN KEY (ASSIGNEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

PRINT 'CONSUMERROLE_SCHEMA created successfully.'
GO
