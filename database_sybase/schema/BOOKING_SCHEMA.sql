-- ============================================================
-- CMS_BOOKING
-- Core booking header. High-frequency concurrent writes.
-- LOCK DATAROWS is MANDATORY.
-- ============================================================
CREATE TABLE dbo.CMS_BOOKING (
    BOOKID      INT           IDENTITY NOT NULL,
    BOOKNO      VARCHAR(30)   NOT NULL,
    BOOKTYPEID  INT           NOT NULL,
    CUSTOMERID  INT           NOT NULL,
    SERVICEID   INT           NOT NULL,
    SERVICEDATE DATETIME      NOT NULL,
    STATUSID    INT           NOT NULL DEFAULT 30,
    BOOKSEQNO   BIGINT        NOT NULL,
    TOTALITEMS  INT           NOT NULL DEFAULT 0,
    TOTALQTY    INT           NOT NULL DEFAULT 0,
    TOTALAMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    BOOKEDBY    INT           NOT NULL,
    BOOKEDON    DATETIME      NOT NULL DEFAULT GETDATE(),
    CANCELLEDBY INT           NULL,
    CANCELLEDON DATETIME      NULL,
    SERVEDBY    INT           NULL,
    SERVEDON    DATETIME      NULL,
    NOSHOWON    DATETIME      NULL,
    KIOSKID     INT           NULL,
    REMARKS     VARCHAR(255)  NULL,
    CREATEDBY   INT           NOT NULL,
    CREATEDAT   DATETIME      NOT NULL DEFAULT GETDATE(),
    UPDATEDBY   INT           NULL,
    UPDATEDAT   DATETIME      NULL,
    PRIMARY KEY (BOOKID),
    CONSTRAINT CK_BK_TOTALS CHECK (TOTALITEMS >= 0 AND TOTALQTY >= 0 AND TOTALAMOUNT >= 0)
)
LOCK DATAROWS
GO

