/* ============================================================
   FILE    : BOOKING_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Booking & Serving
   TABLES  : CMS_BOOKTYPE, CMS_BOOKCTR, CMS_BOOKING,
             CMS_BOOKITEM, CMS_PBACTIVE, CMS_BOOKHIST,
             CMS_BOOKITMHS
   ORDER   : Execute SIXTEENTH (after DAYMENU_SCHEMA.sql
             and KIOSK_SCHEMA.sql)
   NOTES   :
   - CMS_BOOKING and CMS_BOOKITEM MUST use LOCK DATAROWS —
     peak-hour concurrent kiosk/prebooking writes make
     LOCK ALLPAGES catastrophic (deadlock storm at lunch rush).
   - CMS_PBACTIVE: natural composite PK (CUSTOMERID, SERVICEID,
     SERVICEDATE) acts as the hardware-level duplicate booking
     guard. HOLDLOCK UPDLOCK is used in CMSADDBOOK.
   - CMS_BOOKHIST / CMS_BOOKITMHS: audit history tables —
     non-IDENTITY PKs (@@IDENTITY trigger hazard protocol).
   - SERVICEDATE: DATETIME normalised to midnight (DATE if
     ODBC driver reliably supports it).
   - MySQL KEY (non-unique index) → CREATE INDEX.
   - STATUSID codes: 30=Created, 31=Confirmed, 40=Served,
     50=NoShow, 60=Cancelled.
   ============================================================ */

