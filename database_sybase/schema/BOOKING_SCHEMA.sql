-- ============================================================
-- CMS_PBACTIVE
-- Active pre-booking slot guard table.
-- Natural composite PK (CUSTOMERID, SERVICEID, SERVICEDATE)
-- acts as the hardware-level uniqueness constraint that
-- CMSADDBOOK checks with HOLDLOCK UPDLOCK to prevent
-- race-condition double bookings.
-- ============================================================
CREATE TABLE dbo.CMS_PBACTIVE (
    CUSTOMERID  INT      NOT NULL,
    SERVICEID   INT      NOT NULL,
    SERVICEDATE DATETIME NOT NULL,
    BOOKID      INT      NOT NULL,
    CREATEDAT   DATETIME NOT NULL DEFAULT GETDATE(),
    PRIMARY KEY (CUSTOMERID, SERVICEID, SERVICEDATE)
)
LOCK DATAROWS
GO

