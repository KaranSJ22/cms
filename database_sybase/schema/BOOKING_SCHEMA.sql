-- ============================================================
-- CMS_BOOKITEM
-- Booking line items. Joined against #TMP_ITEMS in CMSADDBOOK.
-- LOCK DATAROWS mandatory — concurrent insert via cursor.
-- ============================================================
CREATE TABLE dbo.CMS_BOOKITEM (
    BOOKITEMID INT           IDENTITY NOT NULL,
    BOOKID     INT           NOT NULL,
    DAYMENUID  INT           NOT NULL,
    MENUITEMID INT           NOT NULL,
    QTY        INT           NOT NULL,
    RATE       DECIMAL(10,2) NOT NULL,
    AMOUNT     DECIMAL(12,2) NOT NULL,
    REMARKS    VARCHAR(255)  NULL,
    CREATEDAT  DATETIME      NOT NULL DEFAULT GETDATE(),
    UPDATEDAT  DATETIME      NULL,
    STATUSID   INT           NOT NULL DEFAULT 30,
    PRIMARY KEY (BOOKITEMID),
    CONSTRAINT CK_BI_QTY    CHECK (QTY >= 1),
    CONSTRAINT CK_BI_RATE   CHECK (RATE >= 0),
    CONSTRAINT CK_BI_AMOUNT CHECK (AMOUNT >= 0)
)
LOCK DATAROWS
GO

