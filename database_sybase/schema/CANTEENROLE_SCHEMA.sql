/* ============================================================
   FILE    : CANTEENROLE_SCHEMA.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   MODULE  : Canteen Staff Role Assignments
   TABLES  : CMS_CANTEENROLE
   ORDER   : Execute NINTH (after ROLE_SCHEMA.sql)
   NOTES   :
   - Scoped assignment: a user (staff) is granted a role
     within a specific canteen (e.g. cashier at Canteen 3).
   - ISACTIVE TINYINT(1) → TINYINT, ISDEFAULT similarly.
   - Composite unique on (USERID, ROLEID, CANTEENID).
   ============================================================ */

USE CMS_DB
GO

IF OBJECT_ID('dbo.CMS_CANTEENROLE') IS NOT NULL
    DROP TABLE dbo.CMS_CANTEENROLE
GO

CREATE TABLE dbo.CMS_CANTEENROLE (
    USRCANROLEID INT      IDENTITY NOT NULL,
    USERID       INT      NOT NULL,
    ROLEID       INT      NOT NULL,
    CANTEENID    INT      NOT NULL,
    ISDEFAULT    TINYINT  NOT NULL DEFAULT 0,
    VALIDFROM    DATETIME NULL,
    VALIDUNTIL   DATETIME NULL,
    ISACTIVE     TINYINT  NOT NULL DEFAULT 1,
    ASSIGNEDBY   INT      NULL,
    ASSIGNEDAT   DATETIME NOT NULL DEFAULT GETDATE(),
    UPDATEDAT    DATETIME NULL,
    PRIMARY KEY (USRCANROLEID)
)
LOCK DATAROWS
GO

-- Composite unique: one role assignment per user-role-canteen trio
CREATE UNIQUE INDEX UQ_USRCANROLE
    ON dbo.CMS_CANTEENROLE (USERID, ROLEID, CANTEENID)
GO

ALTER TABLE dbo.CMS_CANTEENROLE
    ADD CONSTRAINT FK_UCR_USER
    FOREIGN KEY (USERID) REFERENCES dbo.CMS_USER(USERID)
GO

ALTER TABLE dbo.CMS_CANTEENROLE
    ADD CONSTRAINT FK_UCR_ROLE
    FOREIGN KEY (ROLEID) REFERENCES dbo.CMS_ROLE(ROLEID)
GO

ALTER TABLE dbo.CMS_CANTEENROLE
    ADD CONSTRAINT FK_UCR_CANTEEN
    FOREIGN KEY (CANTEENID) REFERENCES dbo.CMS_CANTEEN(CANTEENID)
GO

ALTER TABLE dbo.CMS_CANTEENROLE
    ADD CONSTRAINT FK_UCR_BY
    FOREIGN KEY (ASSIGNEDBY) REFERENCES dbo.CMS_USER(USERID)
GO

PRINT 'CANTEENROLE_SCHEMA created successfully.'
GO
