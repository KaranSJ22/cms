/* ============================================================
   CMSLISTBOOKINGSOFRANGE
   Existing confirmed bookings for a customer in a date range
   (pre-booking calendar indicators)
   ============================================================ */

IF OBJECT_ID('dbo.CMSLISTBOOKINGSOFRANGE') IS NOT NULL DROP PROCEDURE dbo.CMSLISTBOOKINGSOFRANGE
GO
CREATE PROCEDURE dbo.CMSLISTBOOKINGSOFRANGE
    @PCUSTOMERID INT,
    @PSTARTDATE  DATETIME,
    @PENDDATE    DATETIME
AS
BEGIN
    SET NOCOUNT ON
    /* DATE_FORMAT('%Y-%m-%d') → CONVERT(VARCHAR(10),..,120) */
    SELECT B.BOOKID, B.BOOKNO, B.SERVICEID, S.SERVNAME,
           CONVERT(VARCHAR(10), B.SERVICEDATE, 120) AS SERVICEDATE,
           B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT,
           ST.STATUSCODE
    FROM   dbo.CMS_BOOKING B
    JOIN   dbo.CMS_SERVICE S  ON S.SERVICEID = B.SERVICEID
    JOIN   dbo.CMS_STATUS  ST ON ST.STATUSID = B.STATUSID
    WHERE  B.CUSTOMERID   = @PCUSTOMERID
      AND  B.SERVICEDATE BETWEEN @PSTARTDATE AND @PENDDATE
      AND  ST.STATUSCODE <> 'CAN'
    ORDER BY B.SERVICEDATE ASC, S.STARTTIME ASC
    RETURN 0
END
GO


/* ============================================================
   CMSGETACTIVEBOOKINGCTX
   Fetch single active confirmed booking for a customer
   in a meal slot context
   ============================================================ */

IF OBJECT_ID('dbo.CMSGETACTIVEBOOKINGCTX') IS NOT NULL DROP PROCEDURE dbo.CMSGETACTIVEBOOKINGCTX
GO
CREATE PROCEDURE dbo.CMSGETACTIVEBOOKINGCTX
    @PCUSTOMERID  INT,
    @PCANTEENID   INT = NULL,
    @PSERVICEID   INT,
    @PSERVICEDATE DATETIME
AS
BEGIN
    SET NOCOUNT ON
    SELECT TOP 1
        B.BOOKID, B.BOOKNO, B.CUSTOMERID, B.SERVICEID, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE, B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT, B.BOOKEDON,
        BK_CAN.CANTEENID, BK_CAN.CANTEENNAME
    FROM   dbo.CMS_BOOKING B
    JOIN   dbo.CMS_STATUS  ST ON ST.STATUSID = B.STATUSID
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
        FROM   dbo.CMS_BOOKITEM BI
        JOIN   dbo.CMS_DAYMENU  DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN   dbo.CMS_DAYSLOT  DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN   dbo.CMS_CANTEEN  CA ON CA.CANTEENID = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE  B.CUSTOMERID   = @PCUSTOMERID
      AND  B.SERVICEDATE  = @PSERVICEDATE
      AND  B.SERVICEID    = @PSERVICEID
      AND  ST.STATUSCODE IN ('CRT')
      AND  (@PCANTEENID IS NULL OR BK_CAN.CANTEENID = @PCANTEENID)
    ORDER BY B.BOOKID DESC
    RETURN 0
END
GO
