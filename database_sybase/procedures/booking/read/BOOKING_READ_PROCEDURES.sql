/* ============================================================
   CMSGETBOOK
   Fetch a single booking header and its items (2 result sets)
   ============================================================ */

IF OBJECT_ID('dbo.CMSGETBOOK') IS NOT NULL DROP PROCEDURE dbo.CMSGETBOOK
GO
CREATE PROCEDURE dbo.CMSGETBOOK
    @PBOOKID INT
AS
BEGIN
    SET NOCOUNT ON

    /* RS-1: Booking Header */
    SELECT
        B.BOOKID, B.BOOKNO, B.BOOKTYPEID, BT.BOOKTYPECODE, BT.BOOKTYPENAME,
        B.CUSTOMERID, C.CTYPECODE, C.DISPNAME AS CUSTOMERNAME,
        BK_CAN.CANTEENID, BK_CAN.CANTEENNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE,
        B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT,
        B.BOOKEDBY, U.FULLNAME AS BOOKEDBYNAME, B.BOOKEDON,
        B.CANCELLEDBY, B.CANCELLEDON, B.SERVEDBY, B.SERVEDON, B.NOSHOWON, B.REMARKS
    FROM   dbo.CMS_BOOKING   B
    JOIN   dbo.CMS_BOOKTYPE  BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    JOIN   dbo.CMS_STATUS    ST ON ST.STATUSID    = B.STATUSID
    JOIN   dbo.CMS_CUSTOMER  C  ON C.CUSTOMERID   = B.CUSTOMERID
    JOIN   dbo.CMS_SERVICE   S  ON S.SERVICEID    = B.SERVICEID
    LEFT JOIN dbo.CMS_USER   U  ON U.USERID        = B.BOOKEDBY
    LEFT JOIN (
        /* Derive canteen from items — GROUP BY produces one row per bookid */
        SELECT BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
        FROM   dbo.CMS_BOOKITEM BI
        JOIN   dbo.CMS_DAYMENU  DM ON DM.DAYMENUID  = BI.DAYMENUID
        JOIN   dbo.CMS_DAYSLOT  DS ON DS.DAYSLOTID  = DM.DAYSLOTID
        JOIN   dbo.CMS_CANTEEN  CA ON CA.CANTEENID  = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE  B.BOOKID = @PBOOKID

    /* RS-2: Booking Items */
    SELECT
        BI.BOOKITEMID, BI.DAYMENUID, BI.MENUITEMID, MI.MENUCODE, MI.ITEMNAME,
        BI.QTY, BI.RATE, BI.AMOUNT, BI.REMARKS,
        BI.STATUSID, BIST.STATUSCODE
    FROM   dbo.CMS_BOOKITEM BI
    JOIN   dbo.CMS_MENUITEM MI   ON MI.MENUITEMID  = BI.MENUITEMID
    JOIN   dbo.CMS_STATUS   BIST ON BIST.STATUSID  = BI.STATUSID
    WHERE  BI.BOOKID = @PBOOKID

    RETURN 0
END
GO


/* ============================================================
   CMSLISTBOOK
   List bookings with optional filters (including Canteen scope)
   ============================================================ */

IF OBJECT_ID('dbo.CMSLISTBOOK') IS NOT NULL DROP PROCEDURE dbo.CMSLISTBOOK
GO
CREATE PROCEDURE dbo.CMSLISTBOOK
    @PCUSTOMERID INT        = NULL,
    @PSERVICEID  INT        = NULL,
    @PSTARTDATE  DATETIME   = NULL,
    @PENDDATE    DATETIME   = NULL,
    @PSTATUSCODE VARCHAR(10) = NULL,
    @PCANTEENID  INT        = NULL
AS
BEGIN
    SET NOCOUNT ON
    SELECT
        B.BOOKID, B.BOOKNO, BT.BOOKTYPECODE,
        B.CUSTOMERID, C.DISPNAME AS CUSTOMERNAME, CU.LOGINID,
        BK_CAN.CANTEENID, BK_CAN.CANTEENNAME,
        B.SERVICEID, S.SERVNAME, B.SERVICEDATE,
        B.STATUSID, ST.STATUSCODE,
        B.TOTALITEMS, B.TOTALQTY, B.TOTALAMOUNT
    FROM   dbo.CMS_BOOKING  B
    JOIN   dbo.CMS_BOOKTYPE BT ON BT.BOOKTYPEID = B.BOOKTYPEID
    JOIN   dbo.CMS_STATUS   ST ON ST.STATUSID   = B.STATUSID
    JOIN   dbo.CMS_CUSTOMER C  ON C.CUSTOMERID  = B.CUSTOMERID
    LEFT JOIN dbo.CMS_USER  CU ON CU.USERID     = C.USERID
    JOIN   dbo.CMS_SERVICE  S  ON S.SERVICEID   = B.SERVICEID
    LEFT JOIN (
        SELECT BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
        FROM   dbo.CMS_BOOKITEM BI
        JOIN   dbo.CMS_DAYMENU  DM ON DM.DAYMENUID = BI.DAYMENUID
        JOIN   dbo.CMS_DAYSLOT  DS ON DS.DAYSLOTID = DM.DAYSLOTID
        JOIN   dbo.CMS_CANTEEN  CA ON CA.CANTEENID = DS.CANTEENID
        GROUP BY BI.BOOKID, DS.CANTEENID, CA.CANTEENNAME
    ) BK_CAN ON BK_CAN.BOOKID = B.BOOKID
    WHERE  (@PCUSTOMERID IS NULL OR B.CUSTOMERID = @PCUSTOMERID)
      AND  (@PSERVICEID  IS NULL OR B.SERVICEID  = @PSERVICEID)
      AND  (@PSTARTDATE  IS NULL OR B.SERVICEDATE >= @PSTARTDATE)
      AND  (@PENDDATE    IS NULL OR B.SERVICEDATE <= @PENDDATE)
      AND  (@PSTATUSCODE IS NULL OR ST.STATUSCODE = @PSTATUSCODE)
      AND  (@PCANTEENID  IS NULL OR BK_CAN.CANTEENID = @PCANTEENID)
    ORDER BY B.SERVICEDATE DESC, B.BOOKNO DESC
    RETURN 0
END
GO


/* ============================================================
   CMSLISTKITCHENPREP
   Kitchen Prep summary for a day slot
   ============================================================ */

IF OBJECT_ID('dbo.CMSLISTKITCHENPREP') IS NOT NULL DROP PROCEDURE dbo.CMSLISTKITCHENPREP
GO
CREATE PROCEDURE dbo.CMSLISTKITCHENPREP
    @PDAYSLOTID INT
AS
BEGIN
    SET NOCOUNT ON
    SELECT
        DM.DAYMENUID,
        DM.MENUITEMID,
        MI.ITEMNAME,
        MI.SHORTNAME,
        DM.MAXQTY AS PLANNED_QTY,
        COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT','SRV','NOS') THEN BI.QTY ELSE 0 END), 0) AS TOTAL_BOOKED,
        COALESCE(SUM(CASE WHEN B_ST.STATUSCODE = 'SRV' THEN BI.QTY ELSE 0 END), 0)               AS TOTAL_SERVED,
        COALESCE(SUM(CASE WHEN B_ST.STATUSCODE IN ('CRT','NOS') THEN BI.QTY ELSE 0 END), 0)      AS REMAINING_QTY
    FROM   dbo.CMS_DAYMENU  DM
    JOIN   dbo.CMS_STATUS   DM_ST ON DM_ST.STATUSID = DM.STATUSID
    JOIN   dbo.CMS_MENUITEM MI    ON MI.MENUITEMID  = DM.MENUITEMID
    LEFT JOIN dbo.CMS_BOOKITEM BI ON BI.DAYMENUID   = DM.DAYMENUID
    LEFT JOIN dbo.CMS_STATUS   B_ST ON B_ST.STATUSID = BI.STATUSID
                                   AND B_ST.STATUSCODE IN ('CRT','SRV','NOS')
    WHERE  DM.DAYSLOTID     = @PDAYSLOTID
      AND  DM_ST.STATUSCODE = 'ACT'
    GROUP BY DM.DAYMENUID, DM.MENUITEMID, MI.ITEMNAME, MI.SHORTNAME, DM.MAXQTY
    ORDER BY MI.ITEMNAME
    RETURN 0
END
GO


