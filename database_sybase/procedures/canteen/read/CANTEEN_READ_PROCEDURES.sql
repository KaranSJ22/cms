   1. CANTEEN QUERIES
   ============================================================ */

IF OBJECT_ID('dbo.CMSGETCANTEEN') IS NOT NULL DROP PROCEDURE dbo.CMSGETCANTEEN
GO
CREATE PROCEDURE dbo.CMSGETCANTEEN
    @PCANTEENID INT
AS
BEGIN
    SET NOCOUNT ON
    SELECT C.CANTEENID, C.CENTERID, CT.CENTERCODE, CT.CENTERNAME,
           C.CANTEENCODE, C.CANTEENNAME, C.LOCATION,
           C.STATUSID, ST.STATUSCODE, C.CREATEDAT, C.UPDATEDAT
    FROM   dbo.CMS_CANTEEN C
    JOIN   dbo.CMS_STATUS ST ON ST.STATUSID = C.STATUSID
    JOIN   dbo.CMS_CENTER CT ON CT.CENTERID = C.CENTERID
    WHERE  C.CANTEENID = @PCANTEENID
    RETURN 0
END
GO


IF OBJECT_ID('dbo.CMSLISTCANTEEN') IS NOT NULL DROP PROCEDURE dbo.CMSLISTCANTEEN
GO
CREATE PROCEDURE dbo.CMSLISTCANTEEN
    @PCENTERID INT = NULL
AS
BEGIN
    SET NOCOUNT ON
    SELECT C.CANTEENID, C.CENTERID, CT.CENTERCODE, CT.CENTERNAME,
           C.CANTEENCODE, C.CANTEENNAME, C.LOCATION,
           C.STATUSID, ST.STATUSCODE, C.CREATEDAT, C.UPDATEDAT
    FROM   dbo.CMS_CANTEEN C
    JOIN   dbo.CMS_STATUS ST ON ST.STATUSID = C.STATUSID
    JOIN   dbo.CMS_CENTER CT ON CT.CENTERID = C.CENTERID
    WHERE  (@PCENTERID IS NULL OR C.CENTERID = @PCENTERID)
    ORDER BY CT.CENTERNAME, C.CANTEENNAME
    RETURN 0
END
GO


