IF OBJECT_ID('dbo.CMSGETHOLIDAY') IS NOT NULL DROP PROCEDURE dbo.CMSGETHOLIDAY
GO
CREATE PROCEDURE dbo.CMSGETHOLIDAY
    @PHOLIDAYID INT
AS
BEGIN
    SET NOCOUNT ON
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   dbo.CMS_HOLIDAY H
    JOIN   dbo.CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  H.HOLIDAYID = @PHOLIDAYID
    RETURN 0
END
GO


IF OBJECT_ID('dbo.CMSLISTHOLIDAY') IS NOT NULL DROP PROCEDURE dbo.CMSLISTHOLIDAY
GO
CREATE PROCEDURE dbo.CMSLISTHOLIDAY
    @PYEAR INT = NULL
AS
BEGIN
    SET NOCOUNT ON
    /* YEAR()/MONTH()/DAY() are valid in Sybase ASE 16 */
    SELECT H.HOLIDAYID, H.HOLIDAYDATE, H.HOLIDAYNAME, H.HOLIDAYTYPE, H.ISRECURRING,
           H.STATUSID, ST.STATUSCODE, H.CREATEDAT, H.UPDATEDAT
    FROM   dbo.CMS_HOLIDAY H
    JOIN   dbo.CMS_STATUS ST ON ST.STATUSID = H.STATUSID
    WHERE  (@PYEAR IS NULL OR YEAR(H.HOLIDAYDATE) = @PYEAR OR H.ISRECURRING = 1)
    ORDER BY MONTH(H.HOLIDAYDATE), DAY(H.HOLIDAYDATE), YEAR(H.HOLIDAYDATE)
    RETURN 0
END
GO


IF OBJECT_ID('dbo.CMSLISTHOLIDAYRANGE') IS NOT NULL DROP PROCEDURE dbo.CMSLISTHOLIDAYRANGE
GO
CREATE PROCEDURE dbo.CMSLISTHOLIDAYRANGE
    @PSTARTDATE DATETIME,
    @PENDDATE   DATETIME
AS
BEGIN
    SET NOCOUNT ON
    /* DATE_FORMAT('%Y-%m-%d') → CONVERT(VARCHAR(10), ..., 120) in Sybase */
    SELECT H.HOLIDAYID, H.HOLIDAYNAME,
           CONVERT(VARCHAR(10), H.HOLIDAYDATE, 120) AS HOLIDAYDATE,
           H.ISRECURRING
    FROM   dbo.CMS_HOLIDAY H
    WHERE  H.STATUSID = 10
      AND  (
             (H.HOLIDAYDATE >= @PSTARTDATE AND H.HOLIDAYDATE <= @PENDDATE)
             OR H.ISRECURRING = 1
           )
    ORDER BY H.HOLIDAYDATE ASC
    RETURN 0
END
GO
