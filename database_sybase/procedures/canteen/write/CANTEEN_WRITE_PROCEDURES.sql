IF OBJECT_ID('dbo.CMSADDCANTEEN') IS NOT NULL DROP PROCEDURE dbo.CMSADDCANTEEN
GO
CREATE PROCEDURE dbo.CMSADDCANTEEN
    @PCENTERID    INT,
    @PCANTEENCODE VARCHAR(20),
    @PCANTEENNAME VARCHAR(120),
    @PLOCATION    VARCHAR(150),
    @PCREATEDBY   INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @VCANTEENID    INT
    DECLARE @VCENSTATUSID  INT
    DECLARE @VERR          INT

    IF @PCENTERID IS NULL
    BEGIN
        RAISERROR('Centre ID is required', 16, 1)
        RETURN 1
    END

    SELECT @VCENSTATUSID = STATUSID FROM dbo.CMS_CENTER WHERE CENTERID = @PCENTERID
    IF @VCENSTATUSID IS NULL
    BEGIN
        RAISERROR('Centre not found', 16, 1)
        RETURN 1
    END
    IF @VCENSTATUSID <> 10
    BEGIN
        RAISERROR('Centre must be active', 16, 1)
        RETURN 1
    END

    IF @PCANTEENCODE IS NULL OR LTRIM(RTRIM(@PCANTEENCODE)) = ''
    BEGIN
        RAISERROR('Canteen Code is required', 16, 1)
        RETURN 1
    END
    IF @PCANTEENNAME IS NULL OR LTRIM(RTRIM(@PCANTEENNAME)) = ''
    BEGIN
        RAISERROR('Canteen Name is required', 16, 1)
        RETURN 1
    END

    BEGIN TRANSACTION

    INSERT INTO dbo.CMS_CANTEEN (CENTERID, CANTEENCODE, CANTEENNAME, LOCATION, STATUSID, CREATEDBY)
    VALUES (@PCENTERID, LTRIM(RTRIM(@PCANTEENCODE)), LTRIM(RTRIM(@PCANTEENNAME)), @PLOCATION, 10, @PCREATEDBY)

    SELECT @VERR = @@error, @VCANTEENID = @@IDENTITY
    IF @VERR <> 0
    BEGIN
        ROLLBACK TRANSACTION
        RAISERROR('Failed to insert canteen', 16, 1)
        RETURN 1
    END

    COMMIT TRANSACTION
    SELECT @VCANTEENID AS CANTEENID
    RETURN 0
END
GO


