CREATE PROCEDURE dbo.CMSADDSERV
    @PSERVCODE  VARCHAR(20),
    @PSERVNAME  VARCHAR(80),
    @PDEFSTART  DATETIME,      /* TIME → DATETIME; only time portion used */
    @PDEFEND    DATETIME,
    @PCREATEDBY INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @VSERVICEID INT
    DECLARE @VERR       INT

    IF @PSERVCODE IS NULL OR LTRIM(RTRIM(@PSERVCODE)) = ''
    BEGIN
        RAISERROR('Service Code is required', 16, 1)
        RETURN 1
    END
    IF @PSERVNAME IS NULL OR LTRIM(RTRIM(@PSERVNAME)) = ''
    BEGIN
        RAISERROR('Service Name is required', 16, 1)
        RETURN 1
    END
    IF @PDEFSTART IS NULL OR @PDEFEND IS NULL
    BEGIN
        RAISERROR('Service default start and end time are required', 16, 1)
        RETURN 1
    END
    IF @PDEFEND <= @PDEFSTART
    BEGIN
        RAISERROR('Service end time must be after start time', 16, 1)
        RETURN 1
    END
    IF @PCREATEDBY IS NULL
    BEGIN
        RAISERROR('Created By is required', 16, 1)
        RETURN 1
    END

    BEGIN TRANSACTION
    INSERT INTO dbo.CMS_SERVICE (SERVCODE, SERVNAME, DEFSTART, DEFEND, STATUSID, CREATEDBY)
    VALUES (LTRIM(RTRIM(@PSERVCODE)), LTRIM(RTRIM(@PSERVNAME)), @PDEFSTART, @PDEFEND, 10, @PCREATEDBY)

    SELECT @VERR = @@error, @VSERVICEID = @@IDENTITY
    IF @VERR <> 0
    BEGIN
        ROLLBACK TRANSACTION
        RAISERROR('Failed to insert service', 16, 1)
        RETURN 1
    END
    COMMIT TRANSACTION
    SELECT @VSERVICEID AS SERVICEID
    RETURN 0
END
GO


IF OBJECT_ID('dbo.CMSUPDSERV') IS NOT NULL DROP PROCEDURE dbo.CMSUPDSERV
GO
CREATE PROCEDURE dbo.CMSUPDSERV
    @PSERVICEID  INT,
    @PSERVNAME   VARCHAR(80),
    @PDEFSTART   DATETIME,
    @PDEFEND     DATETIME,
    @PSTATUSCODE VARCHAR(20) = NULL,
    @PCHANGEDBY  INT,
    @PCHGREASON  VARCHAR(255)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @VCOUNT    INT
    DECLARE @VSTATUSID INT
    DECLARE @VERR      INT

    IF @PSERVICEID IS NULL
    BEGIN
        RAISERROR('Service ID is required', 16, 1)
        RETURN 1
    END
    SELECT @VCOUNT = COUNT(*) FROM dbo.CMS_SERVICE WHERE SERVICEID = @PSERVICEID
    IF @VCOUNT = 0
    BEGIN
        RAISERROR('Service not found', 16, 1)
        RETURN 1
    END
    IF @PSERVNAME IS NULL OR LTRIM(RTRIM(@PSERVNAME)) = ''
    BEGIN
        RAISERROR('Service Name is required', 16, 1)
        RETURN 1
    END
    IF @PDEFSTART IS NULL OR @PDEFEND IS NULL OR @PDEFEND <= @PDEFSTART
    BEGIN
        RAISERROR('Service end time must be after start time', 16, 1)
        RETURN 1
    END

    IF @PSTATUSCODE IS NOT NULL
    BEGIN
        SELECT @VSTATUSID = STATUSID FROM dbo.CMS_STATUS
        WHERE  STATUSCODE = @PSTATUSCODE AND STATUSGRP = 'SYS'
        IF @VSTATUSID IS NULL
        BEGIN
            RAISERROR('Invalid service status code', 16, 1)
            RETURN 1
        END
    END

    BEGIN TRANSACTION

    /* Archive current state before update */
    INSERT INTO dbo.CMS_SERVHIST
           (SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND,
            VALIDFROM, VALIDUNTIL, STATUSID, CHANGEDBY, CHGREASON)
    SELECT  SERVICEID, SERVCODE, SERVNAME, DEFSTART, DEFEND,
            NULL, NULL, STATUSID, @PCHANGEDBY, @PCHGREASON
    FROM    dbo.CMS_SERVICE
    WHERE   SERVICEID = @PSERVICEID

    SELECT @VERR = @@error
    IF @VERR <> 0
    BEGIN
        ROLLBACK TRANSACTION
        RAISERROR('Failed to archive service history', 16, 1)
        RETURN 1
    END

    UPDATE dbo.CMS_SERVICE
    SET    SERVNAME  = LTRIM(RTRIM(@PSERVNAME)),
           DEFSTART  = @PDEFSTART,
           DEFEND    = @PDEFEND,
           STATUSID  = COALESCE(@VSTATUSID, STATUSID),
           UPDATEDAT = GETDATE()
    WHERE  SERVICEID = @PSERVICEID

    SELECT @VERR = @@error
    IF @VERR <> 0
    BEGIN
        ROLLBACK TRANSACTION
        RAISERROR('Failed to update service', 16, 1)
        RETURN 1
    END

    COMMIT TRANSACTION
    SELECT @PSERVICEID AS SERVICEID
    RETURN 0
END
GO


