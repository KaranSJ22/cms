-- ============================================================
-- CMSLOGININFO
-- Returns 3 result sets:
--   RS1: User + Customer header
--   RS2: Active consumer roles
--   RS3: Active canteen (staff) roles
-- NOTE: Sybase does not support IF inside a proc emitting
-- multiple result sets differently — all 3 SELECTs always run.
-- Empty result sets are returned if VUSERID is NULL.
-- ============================================================
IF OBJECT_ID('dbo.CMSLOGININFO') IS NOT NULL DROP PROCEDURE dbo.CMSLOGININFO
GO
CREATE PROCEDURE dbo.CMSLOGININFO
    @PLOGINID VARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @VUSERID INT
    SELECT @VUSERID = NULL

    SELECT TOP 1 @VUSERID = USERID
    FROM dbo.CMS_USER
    WHERE LOGINID  = @PLOGINID
      AND ISACTIVE = 1

    -- RS1: User + Customer header
    SELECT
        U.USERID, U.LOGINID, U.FULLNAME, U.EMAIL, U.MOBILENO,
        U.PWDHASH, U.AUTHPROV, U.AUTHID, U.ISACTIVE,
        C.CUSTOMERID, C.CTYPECODE, C.DISPNAME,
        C.STATUSID AS CUSTOMERSTATUS,
        ce.DEFAULTCANTEENID
    FROM dbo.CMS_USER U
    LEFT JOIN dbo.CMS_CUSTOMER C ON C.USERID = U.USERID
    LEFT JOIN dbo.CMS_CONTEMP  ce ON ce.CUSTOMERID = C.CUSTOMERID
    WHERE U.USERID = @VUSERID

    -- RS2: Active consumer roles
    SELECT
        CR.USRROLEID, CR.ROLEID, R.ROLECODE, R.ROLENAME
    FROM dbo.CMS_CONSUMERROLE CR
    INNER JOIN dbo.CMS_ROLE R ON R.ROLEID = CR.ROLEID
    WHERE CR.USERID  = @VUSERID
      AND CR.ISACTIVE = 1
      AND R.ISACTIVE  = 1
      AND (CR.VALIDFROM  IS NULL OR GETDATE() >= CR.VALIDFROM)
      AND (CR.VALIDUNTIL IS NULL OR GETDATE() <= CR.VALIDUNTIL)
    ORDER BY R.ROLECODE

    -- RS3: Active canteen (staff) roles
    SELECT
        CR.USRCANROLEID, CR.CANTEENID,
        CN.CANTEENCODE, CN.CANTEENNAME,
        CR.ROLEID, R.ROLECODE, R.ROLENAME,
        CR.ISDEFAULT
    FROM dbo.CMS_CANTEENROLE CR
    INNER JOIN dbo.CMS_CANTEEN CN ON CN.CANTEENID = CR.CANTEENID
    INNER JOIN dbo.CMS_ROLE R    ON R.ROLEID      = CR.ROLEID
    WHERE CR.USERID  = @VUSERID
      AND CR.ISACTIVE = 1
      AND R.ISACTIVE  = 1
      AND (CR.VALIDFROM  IS NULL OR GETDATE() >= CR.VALIDFROM)
      AND (CR.VALIDUNTIL IS NULL OR GETDATE() <= CR.VALIDUNTIL)
    ORDER BY CR.ISDEFAULT DESC, CN.CANTEENNAME

    RETURN 0
END
GO

