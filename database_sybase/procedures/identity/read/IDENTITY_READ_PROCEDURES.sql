-- ============================================================
-- CMSFINDCUSTBYIDENTIFIER
-- Fuzzy lookup by emp code, login ID, or numeric customer ID.
-- MySQL REGEXP '^[0-9]+$' → ISNUMERIC() + PATINDEX guard.
-- LIMIT 1 → SELECT TOP 1.
-- ============================================================
IF OBJECT_ID('dbo.CMSFINDCUSTBYIDENTIFIER') IS NOT NULL DROP PROCEDURE dbo.CMSFINDCUSTBYIDENTIFIER
GO
CREATE PROCEDURE dbo.CMSFINDCUSTBYIDENTIFIER
    @PIDENTIFIER VARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @VCLEANID    VARCHAR(100)
    DECLARE @VNUMERICID  INT

    IF @PIDENTIFIER IS NULL OR LTRIM(RTRIM(@PIDENTIFIER)) = ''
    BEGIN
        RAISERROR 20060 'Search identifier is required'
        RETURN 1
    END

    SELECT @VCLEANID   = LTRIM(RTRIM(@PIDENTIFIER))
    SELECT @VNUMERICID = NULL

    -- ISNUMERIC + PATINDEX guards against floats/negatives being accepted
    IF ISNUMERIC(@VCLEANID) = 1
       AND PATINDEX('%[^0-9]%', @VCLEANID) = 0
        SELECT @VNUMERICID = CONVERT(INT, @VCLEANID)

    SELECT TOP 1
        c.CUSTOMERID, c.USERID,
        u.LOGINID, u.FULLNAME, u.EMAIL, u.MOBILENO,
        c.CTYPECODE, ct.CTYPENAME, c.DISPNAME,
        c.STATUSID, st.STATUSCODE,
        ce.CONTCODE, ce.VENDORNAME,
        pe.EMPCODE, pe.DEPT, pe.DESIG,
        COALESCE(ce.CONTCODE, pe.EMPCODE, oe.EMPCODE, u.LOGINID) AS EMPLOYEE_CODE
    FROM dbo.CMS_CUSTOMER c
    LEFT JOIN dbo.CMS_USER     u  ON u.USERID     = c.USERID
    LEFT JOIN dbo.CMS_CUSTTYPE ct ON ct.CTYPECODE = c.CTYPECODE
    LEFT JOIN dbo.CMS_STATUS   st ON st.STATUSID  = c.STATUSID
    LEFT JOIN dbo.CMS_CONTEMP  ce ON ce.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN dbo.CMS_PERMEMP  pe ON pe.CUSTOMERID = c.CUSTOMERID
    LEFT JOIN dbo.CMS_OCEEMP   oe ON oe.CUSTOMERID = c.CUSTOMERID
    WHERE LOWER(ce.CONTCODE) = LOWER(@VCLEANID)
       OR LOWER(pe.EMPCODE)  = LOWER(@VCLEANID)
       OR LOWER(oe.EMPCODE)  = LOWER(@VCLEANID)
       OR LOWER(u.LOGINID)   = LOWER(@VCLEANID)
       OR (@VNUMERICID IS NOT NULL AND c.CUSTOMERID = @VNUMERICID)

    RETURN 0
END
GO

