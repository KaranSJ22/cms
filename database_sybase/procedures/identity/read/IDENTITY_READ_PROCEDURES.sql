-- ============================================================
-- CMSVALIDATEACCKEY
-- Validates a raw key value, checks status/expiry/customer
-- status, then updates LASTUSEDAT and returns the full
-- customer context for the caller to build its JWT payload.
-- NOTE: Single-row SELECT via TOP 1 (replaces LIMIT 1).
-- ============================================================
IF OBJECT_ID('dbo.CMSVALIDATEACCKEY') IS NOT NULL DROP PROCEDURE dbo.CMSVALIDATEACCKEY
GO
CREATE PROCEDURE dbo.CMSVALIDATEACCKEY
    @PKEYVALUE VARCHAR(255)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err         INT
    DECLARE @VACCKEYID   INT
    DECLARE @VCUSTOMERID INT
    DECLARE @VKEYSTATUS  VARCHAR(20)
    DECLARE @VEXPIRESAT  DATETIME
    DECLARE @VCUSTSTATUS VARCHAR(20)

    IF @PKEYVALUE IS NULL OR LTRIM(RTRIM(@PKEYVALUE)) = ''
    BEGIN
        RAISERROR 20070 'Key value is required'
        RETURN 1
    END

    SELECT TOP 1
        @VACCKEYID   = AK.ACCKEYID,
        @VCUSTOMERID = AK.CUSTOMERID,
        @VKEYSTATUS  = STAK.STATUSCODE,
        @VEXPIRESAT  = AK.EXPIRESAT,
        @VCUSTSTATUS = STC.STATUSCODE
    FROM   dbo.CMS_ACCKEY  AK
    JOIN   dbo.CMS_STATUS  STAK ON STAK.STATUSID = AK.STATUSID
    JOIN   dbo.CMS_CUSTOMER C   ON C.CUSTOMERID  = AK.CUSTOMERID
    JOIN   dbo.CMS_STATUS  STC  ON STC.STATUSID  = C.STATUSID
    WHERE  AK.KEYVALUE = LTRIM(RTRIM(@PKEYVALUE))

    IF @VACCKEYID IS NULL
    BEGIN RAISERROR 20071 'Access key not recognised' RETURN 1 END

    IF @VKEYSTATUS <> 'ACT'
    BEGIN RAISERROR 20072 'Access key is inactive or revoked' RETURN 1 END

    IF @VEXPIRESAT IS NOT NULL AND GETDATE() > @VEXPIRESAT
    BEGIN RAISERROR 20073 'Access key has expired' RETURN 1 END

    IF @VCUSTSTATUS <> 'ACT'
    BEGIN RAISERROR 20074 'Customer account is not active' RETURN 1 END

    -- Update last-used timestamp
    UPDATE dbo.CMS_ACCKEY
    SET    LASTUSEDAT = GETDATE()
    WHERE  ACCKEYID   = @VACCKEYID

    SELECT @err = @@error
    IF @err != 0
    BEGIN RAISERROR 20075 'Failed to update access key last-used timestamp' RETURN 1 END

    -- Return full customer context
    SELECT C.CUSTOMERID, C.USERID, C.CTYPECODE, CT.CTYPENAME,
           C.DISPNAME, C.STATUSID AS CUSTSTATUSID, STC.STATUSCODE AS CUSTSTATUSCODE,
           AK.ACCKEYID, AK.KEYTYPE,
           U.LOGINID, U.FULLNAME
    FROM   dbo.CMS_CUSTOMER C
    JOIN   dbo.CMS_CUSTTYPE CT  ON CT.CTYPECODE  = C.CTYPECODE
    JOIN   dbo.CMS_STATUS  STC  ON STC.STATUSID  = C.STATUSID
    JOIN   dbo.CMS_ACCKEY  AK   ON AK.CUSTOMERID = C.CUSTOMERID AND AK.ACCKEYID = @VACCKEYID
    LEFT JOIN dbo.CMS_USER U    ON U.USERID       = C.USERID
    WHERE  C.CUSTOMERID = @VCUSTOMERID

    RETURN 0
END
