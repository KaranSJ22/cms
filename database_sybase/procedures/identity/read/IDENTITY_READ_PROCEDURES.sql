CREATE PROCEDURE dbo.CMSLISTCUST
    @PCTYPECODE  VARCHAR(20) = NULL,
    @PSTATUSCODE VARCHAR(20) = NULL
AS
BEGIN
    SET NOCOUNT ON
    SELECT C.CUSTOMERID, C.USERID, U.LOGINID, U.FULLNAME,
           C.CTYPECODE, CT.CTYPENAME, C.DISPNAME,
           C.STATUSID, ST.STATUSCODE, C.VALIDFROM, C.VALIDUNTIL,
           C.CREATEDAT, C.UPDATEDAT
    FROM   dbo.CMS_CUSTOMER C
    LEFT JOIN dbo.CMS_USER     U  ON U.USERID     = C.USERID
    JOIN      dbo.CMS_CUSTTYPE CT ON CT.CTYPECODE = C.CTYPECODE
    JOIN      dbo.CMS_STATUS   ST ON ST.STATUSID  = C.STATUSID
    WHERE  (@PCTYPECODE IS NULL OR LTRIM(RTRIM(@PCTYPECODE)) = '' OR C.CTYPECODE = @PCTYPECODE)
      AND  (
            @PSTATUSCODE IS NULL
            OR LTRIM(RTRIM(@PSTATUSCODE)) = ''
            OR ST.STATUSCODE = @PSTATUSCODE
            OR (@PSTATUSCODE = 'A' AND ST.STATUSCODE = 'ACT')
            OR (@PSTATUSCODE = 'I' AND ST.STATUSCODE = 'INACT')
           )
    ORDER BY C.DISPNAME
    RETURN 0
END
GO

