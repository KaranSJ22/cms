/* ============================================================
   FILE    : IDENTITY_READ_PROCEDURES.sql
   ENGINE  : SAP Sybase ASE 16.0 SP04+
   DOMAIN  : Identity — User, Customer, Profile, Role, Credential (Read)
   PROCEDURES:
     CMSGETUSER            — Fetch user by ID
     CMSLISTUSER           — List users, filter by ISACTIVE
     CMSSEARCHUSER         — Search users by keyword
     CMSLOGININFO          — Full login context (3 result sets)
     CMSGETCUST            — Fetch customer by ID
     CMSLISTCUST           — List customers by type/status
     CMSSEARCHCUST         — Search customers by keyword
     CMSGETCUSTBYUSER      — Fetch customer by USERID
     CMSFINDCUSTBYIDENTIFIER — Fuzzy lookup by code/ID
     CMSGETPERM            — Permanent employee profile
     CMSGETCONT            — Contractor profile
     CMSGETOCE             — OCE employee profile
     CMSGETVIS             — Visitor profile
     CMSGETROL             — Fetch role by ID
     CMSLISTROL            — List all roles
     CMSLISTCANROL         — Canteen roles for a user
     CMSLISTCANROLSTAFF    — Staff for a canteen
     CMSLISTCONSROL        — Consumer roles for a user
     CMSGETACCKEY          — Fetch access key by ID
     CMSLISTACCKEY         — List access keys for a customer
     CMSVALIDATEACCKEY     — Validate key + update LASTUSEDAT
   DIALECT CHANGES vs MySQL:
     - DELIMITER/BEGIN/END → removed; GO used.
     - IN params → @P prefix.
     - SET NOCOUNT ON in every proc.
     - DECLARE var DEFAULT → DECLARE @var type; SELECT @var = ...
     - SELECT x INTO var → SELECT @var = x FROM ...
     - CONCAT('%', x, '%') → '%' + x + '%'
     - IF...THEN...END IF → IF...BEGIN...END
     - CURRENT_TIMESTAMP → GETDATE()
     - LIMIT 1 → SELECT TOP 1
     - SIGNAL SQLSTATE → RAISERROR + RETURN 1
     - LOWER() → LOWER() (supported in ASE)
     - REGEXP → replaced with ISNUMERIC() check
   ============================================================ */

