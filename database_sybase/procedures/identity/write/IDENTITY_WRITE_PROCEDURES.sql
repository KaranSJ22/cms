CREATE PROCEDURE dbo.CMSASSIGNCANROL
    @PUSERID     INT,
    @PROLEID     INT,
    @PCANTEENID  INT,
    @PISDEFAULT  TINYINT,
    @PVALIDFROM  DATETIME,
    @PVALIDUNTIL DATETIME,
    @PASSIGNEDBY INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err       INT
    DECLARE @VVALIDFROM DATETIME

    IF @PUSERID IS NULL BEGIN RAISERROR 20210 'User ID is required' RETURN 1 END
    IF @PROLEID IS NULL BEGIN RAISERROR 20211 'Role ID is required' RETURN 1 END
    IF @PCANTEENID IS NULL BEGIN RAISERROR 20212 'Canteen ID is required' RETURN 1 END

    SELECT @VVALIDFROM = COALESCE(@PVALIDFROM, GETDATE())

    BEGIN TRANSACTION

    IF EXISTS (
        SELECT 1 FROM dbo.CMS_CANTEENROLE (HOLDLOCK)
        WHERE USERID = @PUSERID AND ROLEID = @PROLEID AND CANTEENID = @PCANTEENID
    )
    BEGIN
        UPDATE dbo.CMS_CANTEENROLE
        SET    ISDEFAULT  = COALESCE(@PISDEFAULT, ISDEFAULT),
               VALIDFROM  = @VVALIDFROM,
               VALIDUNTIL = @PVALIDUNTIL,
               ISACTIVE   = 1,
               ASSIGNEDBY = @PASSIGNEDBY,
               ASSIGNEDAT = GETDATE(),
               UPDATEDAT  = GETDATE()
        WHERE  USERID    = @PUSERID
          AND  ROLEID    = @PROLEID
          AND  CANTEENID = @PCANTEENID
    END
    ELSE
    BEGIN
        INSERT INTO dbo.CMS_CANTEENROLE
            (USERID, ROLEID, CANTEENID, ISDEFAULT, VALIDFROM, VALIDUNTIL, ISACTIVE, ASSIGNEDBY)
        VALUES (@PUSERID, @PROLEID, @PCANTEENID,
                COALESCE(@PISDEFAULT, 0), @VVALIDFROM, @PVALIDUNTIL, 1, @PASSIGNEDBY)
    END

    SELECT @err = @@error
    IF @err != 0 BEGIN ROLLBACK TRANSACTION RAISERROR 20213 'Failed to assign canteen role' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @PUSERID AS USERID, @PROLEID AS ROLEID, @PCANTEENID AS CANTEENID
