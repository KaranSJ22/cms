CREATE PROCEDURE dbo.CMSUPDACCKEY
    @PACCKEYID  INT,
    @PKEYVALUE  VARCHAR(255),
    @PEXPIRESAT DATETIME
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err INT DECLARE @VCOUNT INT
    IF @PACCKEYID IS NULL BEGIN RAISERROR 20230 'Access Key ID is required' RETURN 1 END
    SELECT @VCOUNT = COUNT(*) FROM dbo.CMS_ACCKEY WHERE ACCKEYID = @PACCKEYID
    IF @VCOUNT = 0 BEGIN RAISERROR 20231 'Access key not found' RETURN 1 END
    BEGIN TRANSACTION
    UPDATE dbo.CMS_ACCKEY
    SET    KEYVALUE  = COALESCE(@PKEYVALUE, KEYVALUE),
           EXPIRESAT = COALESCE(@PEXPIRESAT, EXPIRESAT),
           UPDATEDAT = GETDATE()
    WHERE  ACCKEYID  = @PACCKEYID
    SELECT @err = @@error
    IF @err != 0 BEGIN ROLLBACK TRANSACTION RAISERROR 20232 'Failed to update access key' RETURN 1 END
    COMMIT TRANSACTION
    SELECT @PACCKEYID AS ACCKEYID
    RETURN 0
END
GO

