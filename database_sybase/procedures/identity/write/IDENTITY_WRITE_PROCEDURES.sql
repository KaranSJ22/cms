CREATE PROCEDURE dbo.CMSADDUSER
    @PLOGINID  VARCHAR(50),
    @PFULLNAME VARCHAR(120),
    @PEMAIL    VARCHAR(120),
    @PMOBILENO VARCHAR(20),
    @PPWDHASH  VARCHAR(255),
    @PAUTHPROV VARCHAR(20),
    @PAUTHID   VARCHAR(120)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err     INT
    DECLARE @VUSERID INT

    IF @PLOGINID IS NULL OR LTRIM(RTRIM(@PLOGINID)) = ''
    BEGIN RAISERROR 20100 'Login ID is required' RETURN 1 END

    IF @PFULLNAME IS NULL OR LTRIM(RTRIM(@PFULLNAME)) = ''
    BEGIN RAISERROR 20101 'Full Name is required' RETURN 1 END

    IF @PPWDHASH IS NULL OR LTRIM(RTRIM(@PPWDHASH)) = ''
    BEGIN RAISERROR 20102 'Password hash is required' RETURN 1 END

    BEGIN TRANSACTION

    INSERT INTO dbo.CMS_USER (LOGINID, FULLNAME, EMAIL, MOBILENO, PWDHASH, AUTHPROV, AUTHID)
    VALUES (LTRIM(RTRIM(@PLOGINID)), LTRIM(RTRIM(@PFULLNAME)),
            @PEMAIL, @PMOBILENO, @PPWDHASH,
            COALESCE(@PAUTHPROV, 'LOCAL'), @PAUTHID)

    SELECT @err = @@error, @VUSERID = @@IDENTITY
    IF @err != 0
    BEGIN ROLLBACK TRANSACTION RAISERROR 20103 'Failed to insert user' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @VUSERID AS USERID
    RETURN 0
END
GO

