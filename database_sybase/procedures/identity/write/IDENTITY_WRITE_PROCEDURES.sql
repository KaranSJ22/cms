GO
CREATE PROCEDURE dbo.CMSADDCUST
    @PUSERID     INT,
    @PCTYPECODE  VARCHAR(20),
    @PDISPNAME   VARCHAR(120),
    @PSTATUSCODE VARCHAR(20),
    @PVALIDFROM  DATETIME,
    @PVALIDUNTIL DATETIME
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err        INT
    DECLARE @VCTYPE     INT
    DECLARE @VSTATUSID  INT
    DECLARE @VCUSTOMERID INT

    IF @PCTYPECODE IS NULL OR LTRIM(RTRIM(@PCTYPECODE)) = ''
    BEGIN RAISERROR 20110 'Customer Type Code is required' RETURN 1 END
    IF @PDISPNAME IS NULL OR LTRIM(RTRIM(@PDISPNAME)) = ''
    BEGIN RAISERROR 20111 'Display Name is required' RETURN 1 END

    SELECT @VCTYPE = COUNT(*) FROM dbo.CMS_CUSTTYPE
    WHERE CTYPECODE = @PCTYPECODE AND ISACTIVE = 1
    IF @VCTYPE = 0 BEGIN RAISERROR 20112 'Invalid or inactive Customer Type Code' RETURN 1 END

    -- Resolve STATUSID from code shorthand
    SELECT @VSTATUSID = 10   -- default: ACT
    IF @PSTATUSCODE IS NOT NULL AND LTRIM(RTRIM(@PSTATUSCODE)) <> ''
    BEGIN
        IF @PSTATUSCODE IN ('A', 'ACT')   SELECT @VSTATUSID = 10
        IF @PSTATUSCODE IN ('I', 'INACT') SELECT @VSTATUSID = 11
        IF @PSTATUSCODE IN ('B', 'BLK')   SELECT @VSTATUSID = 12
        IF @PSTATUSCODE IN ('S', 'SUSP')  SELECT @VSTATUSID = 13
        IF @PSTATUSCODE NOT IN ('A','ACT','I','INACT','B','BLK','S','SUSP')
        BEGIN
            SELECT @VSTATUSID = NULL
            SELECT @VSTATUSID = STATUSID FROM dbo.CMS_STATUS
            WHERE STATUSCODE = @PSTATUSCODE AND STATUSGRP = 'SYS'
            IF @VSTATUSID IS NULL BEGIN RAISERROR 20113 'Invalid Status Code' RETURN 1 END
        END
    END

    BEGIN TRANSACTION

    INSERT INTO dbo.CMS_CUSTOMER (USERID, CTYPECODE, DISPNAME, STATUSID, VALIDFROM, VALIDUNTIL)
    VALUES (@PUSERID, LTRIM(RTRIM(@PCTYPECODE)), LTRIM(RTRIM(@PDISPNAME)),
            @VSTATUSID, @PVALIDFROM, @PVALIDUNTIL)

    SELECT @err = @@error, @VCUSTOMERID = @@IDENTITY
    IF @err != 0
    BEGIN ROLLBACK TRANSACTION RAISERROR 20114 'Failed to insert customer' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @VCUSTOMERID AS CUSTOMERID
    RETURN 0
END
GO

