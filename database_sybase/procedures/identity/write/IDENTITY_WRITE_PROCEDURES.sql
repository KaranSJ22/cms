CREATE PROCEDURE dbo.CMSADDACCKEY
    @PCUSTOMERID INT,
    @PKEYTYPE    VARCHAR(30),
    @PKEYVALUE   VARCHAR(255),
    @PEXPIRESAT  DATETIME,
    @PCREATEDBY  INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err      INT
    DECLARE @VACCKEYID INT
    IF @PCUSTOMERID IS NULL BEGIN RAISERROR 20230 'Customer ID is required' RETURN 1 END
    IF @PKEYVALUE IS NULL OR LTRIM(RTRIM(@PKEYVALUE)) = ''
    BEGIN RAISERROR 20231 'Access key value is required' RETURN 1 END
    BEGIN TRANSACTION
    INSERT INTO dbo.CMS_ACCKEY (CUSTOMERID, KEYTYPE, KEYVALUE, EXPIRESAT, STATUSID, CREATEDBY)
    VALUES (@PCUSTOMERID, @PKEYTYPE, LTRIM(RTRIM(@PKEYVALUE)), @PEXPIRESAT, 10, @PCREATEDBY)
    SELECT @err = @@error, @VACCKEYID = @@IDENTITY
    IF @err != 0 BEGIN ROLLBACK TRANSACTION RAISERROR 20232 'Failed to insert access key' RETURN 1 END
    COMMIT TRANSACTION
    SELECT @VACCKEYID AS ACCKEYID
    RETURN 0
END
GO

