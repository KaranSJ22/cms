/* ============================================================
   CMS_ROLESCREEN — Role-Screen Permission Mutations
   (MySQL source: CMS_ROLESCN — corrected to CMS_ROLESCREEN)
   ON DUPLICATE KEY UPDATE → IF EXISTS...UPDATE ELSE INSERT
   ============================================================ */

IF OBJECT_ID('dbo.CMSSETROLESCN') IS NOT NULL DROP PROCEDURE dbo.CMSSETROLESCN
GO
CREATE PROCEDURE dbo.CMSSETROLESCN
    @PROLEID   INT,
    @PSCREENID INT,
    @PCANVIEW  TINYINT,
    @PCANEDIT  TINYINT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err INT

    IF @PROLEID IS NULL
    BEGIN RAISERROR 20040 'Role ID is required' RETURN 1 END

    IF @PSCREENID IS NULL
    BEGIN RAISERROR 20041 'Screen ID is required' RETURN 1 END

    BEGIN TRANSACTION

    IF EXISTS (
        SELECT 1 FROM dbo.CMS_ROLESCREEN (HOLDLOCK)
        WHERE ROLEID = @PROLEID AND SCREENID = @PSCREENID
    )
    BEGIN
        UPDATE dbo.CMS_ROLESCREEN
        SET    CANVIEW  = COALESCE(@PCANVIEW, CANVIEW),
               CANEDIT  = COALESCE(@PCANEDIT, CANEDIT)
        WHERE  ROLEID   = @PROLEID
          AND  SCREENID = @PSCREENID
    END
    ELSE
    BEGIN
        INSERT INTO dbo.CMS_ROLESCREEN (ROLEID, SCREENID, CANVIEW, CANEDIT)
        VALUES (@PROLEID, @PSCREENID,
                COALESCE(@PCANVIEW, 1),
                COALESCE(@PCANEDIT, 0))
    END

    SELECT @err = @@error
    IF @err != 0
    BEGIN ROLLBACK TRANSACTION RAISERROR 20042 'Failed to set role-screen permission' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @PROLEID AS ROLEID, @PSCREENID AS SCREENID
    RETURN 0
END
GO

IF OBJECT_ID('dbo.CMSREMOVEROLESCN') IS NOT NULL DROP PROCEDURE dbo.CMSREMOVEROLESCN
GO
CREATE PROCEDURE dbo.CMSREMOVEROLESCN
    @PROLEID   INT,
    @PSCREENID INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err INT DECLARE @VCOUNT INT

    IF @PROLEID IS NULL OR @PSCREENID IS NULL
    BEGIN RAISERROR 20040 'Role ID and Screen ID are required' RETURN 1 END

    SELECT @VCOUNT = COUNT(*)
    FROM dbo.CMS_ROLESCREEN
    WHERE ROLEID = @PROLEID AND SCREENID = @PSCREENID
    IF @VCOUNT = 0
    BEGIN RAISERROR 20041 'Role-Screen mapping not found' RETURN 1 END

    BEGIN TRANSACTION
    -- Soft-delete: remove row (hard delete is safe — no child FKs on this table)
    DELETE FROM dbo.CMS_ROLESCREEN
    WHERE ROLEID = @PROLEID AND SCREENID = @PSCREENID
    SELECT @err = @@error
    IF @err != 0
    BEGIN ROLLBACK TRANSACTION RAISERROR 20042 'Failed to remove role-screen permission' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @PROLEID AS ROLEID, @PSCREENID AS SCREENID
    RETURN 0
END
GO

