CREATE PROCEDURE dbo.CMSADDSTATUS
    @PSTATUSID   INT,
    @PSTATUSCODE VARCHAR(10),
    @PSTATUSNAME VARCHAR(50),
    @PSTATUSGRP  VARCHAR(30),
    @PDESCR      VARCHAR(255)
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err INT

    IF @PSTATUSID IS NULL
    BEGIN RAISERROR 20010 'Status ID is required (Manual ID mapping)' RETURN 1 END

    IF @PSTATUSCODE IS NULL OR LTRIM(RTRIM(@PSTATUSCODE)) = ''
    BEGIN RAISERROR 20011 'Status Code is required' RETURN 1 END

    IF @PSTATUSNAME IS NULL OR LTRIM(RTRIM(@PSTATUSNAME)) = ''
    BEGIN RAISERROR 20012 'Status Name is required' RETURN 1 END

    IF @PSTATUSGRP IS NULL OR LTRIM(RTRIM(@PSTATUSGRP)) = ''
    BEGIN RAISERROR 20013 'Status Group is required' RETURN 1 END

    BEGIN TRANSACTION

    -- Must SET IDENTITY_INSERT ON to use manual STATUSID
    SET IDENTITY_INSERT dbo.CMS_STATUS ON

    INSERT INTO dbo.CMS_STATUS (STATUSID, STATUSCODE, STATUSNAME, STATUSGRP, DESCR)
    VALUES (@PSTATUSID,
            LTRIM(RTRIM(@PSTATUSCODE)),
            LTRIM(RTRIM(@PSTATUSNAME)),
            LTRIM(RTRIM(@PSTATUSGRP)),
            @PDESCR)

    SET IDENTITY_INSERT dbo.CMS_STATUS OFF

    SELECT @err = @@error
    IF @err != 0
    BEGIN
        ROLLBACK TRANSACTION
        RAISERROR 20014 'Failed to insert status record'
        RETURN 1
    END

    COMMIT TRANSACTION
    SELECT @PSTATUSID AS STATUSID
    RETURN 0
END
GO

