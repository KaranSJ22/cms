CREATE PROCEDURE dbo.CMSADDAUTONO
    @PTBLNAME    VARCHAR(50),
    @PDATAITEM   VARCHAR(30),
    @PITEMLEN    INT,
    @PFLDTYPE    VARCHAR(10),
    @PPREFIXCHAR VARCHAR(5),
    @PSTARTNO    BIGINT,
    @PCREATEDBY  INT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err      INT
    DECLARE @VAUTONOID INT

    IF @PTBLNAME IS NULL OR LTRIM(RTRIM(@PTBLNAME)) = ''
    BEGIN RAISERROR 20050 'Table Name is required' RETURN 1 END

    IF @PDATAITEM IS NULL OR LTRIM(RTRIM(@PDATAITEM)) = ''
    BEGIN RAISERROR 20051 'Data Item is required' RETURN 1 END

    IF @PPREFIXCHAR IS NULL OR LTRIM(RTRIM(@PPREFIXCHAR)) = ''
    BEGIN RAISERROR 20052 'Prefix Character is required' RETURN 1 END

    IF @PITEMLEN IS NULL OR @PITEMLEN < 1
    BEGIN RAISERROR 20053 'Item Length must be at least 1' RETURN 1 END

    BEGIN TRANSACTION

    INSERT INTO dbo.CMS_AUTONOS (
        TBLNAME, DATAITEM, ITEMLEN, FLDTYPE, PREFIXCHAR,
        STARTNO, STARTDATE, LASTNO, STATUSID, CREATEDBY
    )
    VALUES (
        LTRIM(RTRIM(@PTBLNAME)),
        LTRIM(RTRIM(@PDATAITEM)),
        @PITEMLEN,
        COALESCE(@PFLDTYPE, 'CHAR'),
        LTRIM(RTRIM(@PPREFIXCHAR)),
        COALESCE(@PSTARTNO, 1),
        GETDATE(),
        0,
        10,
        @PCREATEDBY
    )

    SELECT @err = @@error, @VAUTONOID = @@IDENTITY
    IF @err != 0
    BEGIN ROLLBACK TRANSACTION RAISERROR 20054 'Failed to insert auto-number configuration' RETURN 1 END

    COMMIT TRANSACTION
    SELECT @VAUTONOID AS AUTONOID
    RETURN 0
END
GO

