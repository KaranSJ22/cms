GO
CREATE PROCEDURE dbo.CMSGENAUTOREF
    @PREFNO VARCHAR(80) OUTPUT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err INT

    EXEC dbo.CMSGENAUTO 'CMS_WALLETTRAN', 'REFNO', @PREFNO OUTPUT
    SELECT @err = @@error
    IF @err != 0
    BEGIN
        RAISERROR 20003 'Failed to generate wallet transaction reference number'
        RETURN 1
    END

    RETURN 0
END
GO

