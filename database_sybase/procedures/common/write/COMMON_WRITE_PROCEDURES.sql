-- ============================================================
-- CMSGENAUTO
-- Atomic daily-reset sequential number generator.
-- Called from within the CALLER's transaction (Pattern A/B).
-- Uses HOLDLOCK UPDLOCK on CMS_AUTONOS row for concurrency.
-- ============================================================
IF OBJECT_ID('dbo.CMSGENAUTO') IS NOT NULL DROP PROCEDURE dbo.CMSGENAUTO
GO
CREATE PROCEDURE dbo.CMSGENAUTO
    @PTBLNAME   VARCHAR(50),
    @PDATAITEM  VARCHAR(30),
    @PNEWNO     VARCHAR(50) OUTPUT
AS
BEGIN
    SET NOCOUNT ON
    DECLARE @err          INT
    DECLARE @VPREFIXCHAR  VARCHAR(5)
    DECLARE @VITEMLEN     INT
    DECLARE @VLASTNO      BIGINT
    DECLARE @VLASTGENDATE DATETIME
    DECLARE @VDATESTR     VARCHAR(8)
    DECLARE @VNUMSTR      VARCHAR(20)
    DECLARE @VPADLEN      INT

    -- 1. Read and lock configuration row atomically
    SELECT
        @VPREFIXCHAR  = PREFIXCHAR,
        @VITEMLEN     = ITEMLEN,
        @VLASTNO      = LASTNO,
        @VLASTGENDATE = LASTGENDATE
    FROM dbo.CMS_AUTONOS (HOLDLOCK UPDLOCK)
    WHERE TBLNAME  = @PTBLNAME
      AND DATAITEM = @PDATAITEM

    IF @VPREFIXCHAR IS NULL
    BEGIN
        RAISERROR 20001 'Auto-number configuration not found for the requested table and column'
        RETURN 1
    END

    -- 2. Daily reset: if last-generated date is before today, reset counter
    IF @VLASTGENDATE IS NULL
       OR CONVERT(VARCHAR(8), @VLASTGENDATE, 112) < CONVERT(VARCHAR(8), GETDATE(), 112)
        SELECT @VLASTNO = 1
    ELSE
        SELECT @VLASTNO = @VLASTNO + 1

    -- 3. Date string YYYYMMDD (Style 112)
    SELECT @VDATESTR = CONVERT(VARCHAR(8), GETDATE(), 112)

    -- 4. LPAD simulation: REPLICATE + RIGHT
    --    padded number length = total - prefix length - 8 (date chars)
    SELECT @VPADLEN = @VITEMLEN - LEN(@VPREFIXCHAR) - 8
    IF @VPADLEN < 1 SELECT @VPADLEN = 4

    SELECT @VNUMSTR = RIGHT(REPLICATE('0', @VPADLEN) + CONVERT(VARCHAR(20), @VLASTNO), @VPADLEN)

    -- 5. Construct composite number: PREFIX + YYYYMMDD + PADDED_SEQ
    SELECT @PNEWNO = @VPREFIXCHAR + @VDATESTR + @VNUMSTR

    -- 6. Update master row
    UPDATE dbo.CMS_AUTONOS
    SET LASTNO      = @VLASTNO,
        LASTGENDATE = GETDATE(),
        UPDATEDAT   = GETDATE()
    WHERE TBLNAME  = @PTBLNAME
      AND DATAITEM = @PDATAITEM

    SELECT @err = @@error
    IF @err != 0
    BEGIN
        RAISERROR 20002 'Failed to update auto-number generator table'
        RETURN 1
    END

    RETURN 0
END
GO

-- ============================================================
-- CMSGENAUTOREF
-- Convenience wrapper for generating wallet TXN reference numbers.
-- ============================================================
